CREATE TABLE IF NOT EXISTS manuals (
    manual_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_type varchar(50) NOT NULL CHECK (manual_type IN ('USER','ADMIN')),
    version varchar(50) NOT NULL,
    target_user varchar(100) NOT NULL,
    effective_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500),
    CONSTRAINT uq_manuals_type_target_version UNIQUE (manual_type, target_user, version),
    CONSTRAINT fk_manuals_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_manuals_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE manuals IS '사용자·관리자 매뉴얼의 유형, 대상 사용자, 버전, 시행일을 관리하고 시행일 기준 최신 버전 선택에 사용한다.';
COMMENT ON COLUMN manuals.manual_type IS 'USER:사용자|ADMIN:관리자';
COMMENT ON COLUMN manuals.target_user IS 'roles.role_code 또는 사용자 유형 참조 의도 (FK 미선언)';
COMMENT ON COLUMN manuals.change_reason IS 'ManualManagementService.createManual 시 매뉴얼 등록 사유로 애플리케이션에서 갱신';

CREATE TABLE IF NOT EXISTS manual_files (
    manual_file_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_id bigint NOT NULL UNIQUE,
    original_file_name varchar(255) NOT NULL,
    internal_storage_name varchar(255) NOT NULL UNIQUE,
    file_content bytea NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    CONSTRAINT fk_manual_files_manual_id FOREIGN KEY (manual_id) REFERENCES manuals(manual_id) ON DELETE CASCADE,
    CONSTRAINT fk_manual_files_created_by FOREIGN KEY (created_by) REFERENCES users(user_id)
);
COMMENT ON TABLE manual_files IS '매뉴얼 파일의 원본 파일명과 내부 저장 식별자를 분리 보존하여 다운로드 시 내부 경로와 실제 저장명을 노출하지 않는다.';
COMMENT ON COLUMN manual_files.original_file_name IS '다운로드에 사용할 원본 파일명 보존 값';
COMMENT ON COLUMN manual_files.internal_storage_name IS '외부에 노출하지 않는 내부 저장 식별자';
COMMENT ON COLUMN manual_files.file_content IS 'ManualManagementService.createManual 시 등록된 파일 내용을 그대로 보존하며 자동 수정하지 않는다.';
COMMENT ON COLUMN manual_files.created_by IS 'users.user_id 참조 의도 (파일 등록자)';

CREATE INDEX IF NOT EXISTS idx_manuals_type_target_effective ON manuals (manual_type, target_user, effective_date DESC);
CREATE INDEX IF NOT EXISTS idx_manual_files_manual_id ON manual_files (manual_id);

