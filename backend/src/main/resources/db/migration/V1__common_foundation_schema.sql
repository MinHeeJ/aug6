CREATE TABLE IF NOT EXISTS users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id varchar(100) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    employee_no varchar(50) UNIQUE,
    system_use_yn varchar(1) NOT NULL DEFAULT 'Y' CHECK (system_use_yn IN ('Y','N')),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','DELETED')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500),
    CONSTRAINT fk_users_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_users_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE users IS '로컬 DB에서 관리되는 사용자 계정. KORUS 원천 인사정보는 직접 수정하지 않고 시스템 사용여부와 인증 정보를 관리한다.';
COMMENT ON COLUMN users.system_use_yn IS 'Y:사용|N:미사용';
COMMENT ON COLUMN users.status IS 'ACTIVE:활성|INACTIVE:비활성|DELETED:삭제';
COMMENT ON COLUMN users.employee_no IS 'korus_personnel_snapshots.employee_no 참조 의도 (FK 미선언)';

