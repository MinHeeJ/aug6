CREATE TABLE IF NOT EXISTS evaluation_organization_mappings (
    mapping_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    organization_code varchar(50) NOT NULL,
    business_type varchar(50) NOT NULL,
    data_scope varchar(30) NOT NULL,
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_evaluation_organization_mappings_key UNIQUE (user_id, organization_code, business_type),
    CONSTRAINT ck_evaluation_mapping_business_type CHECK (business_type IN ('FACULTY_ACHIEVEMENT','ACADEMIC_GRANT','OBJECTION')),
    CONSTRAINT ck_evaluation_mapping_data_scope CHECK (data_scope IN ('SELF','DEPARTMENT','COLLEGE','BUSINESS','ALL')),
    CONSTRAINT fk_evaluation_mapping_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_mapping_org FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_evaluation_mapping_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_mapping_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_organization_mappings IS '기존 사용자·KORUS 조직과 교수업적평가·학술지원금·이의신청 업무 데이터 범위를 연결하는 평가조직 매핑.';
COMMENT ON COLUMN evaluation_organization_mappings.business_type IS 'FACULTY_ACHIEVEMENT:교수업적평가|ACADEMIC_GRANT:학술지원금|OBJECTION:이의신청';
COMMENT ON COLUMN evaluation_organization_mappings.data_scope IS 'SELF:본인|DEPARTMENT:학과|COLLEGE:단과대학|BUSINESS:담당업무|ALL:전체';

CREATE INDEX IF NOT EXISTS idx_evaluation_mapping_business_org ON evaluation_organization_mappings(business_type, organization_code);
CREATE INDEX IF NOT EXISTS idx_evaluation_mapping_user_scope ON evaluation_organization_mappings(user_id, data_scope);

