CREATE TABLE IF NOT EXISTS rejection_reasons (
    rejection_reason_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type varchar(50) NOT NULL,
    reason_code varchar(50) NOT NULL,
    standard_message varchar(500) NOT NULL,
    additional_opinion_allowed_yn varchar(1) NOT NULL DEFAULT 'Y',
    change_reason varchar(500) NOT NULL DEFAULT '초기 반려사유 seed',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_rejection_reasons_key UNIQUE (business_type, reason_code),
    CONSTRAINT ck_rejection_reasons_business_type CHECK (business_type IN ('FACULTY_ACHIEVEMENT','ACADEMIC_GRANT','OBJECTION')),
    CONSTRAINT ck_rejection_reasons_additional_opinion CHECK (additional_opinion_allowed_yn IN ('Y','N')),
    CONSTRAINT fk_rejection_reasons_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_rejection_reasons_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE rejection_reasons IS '교수업적평가·학술지원금·이의신청 업무유형별 표준 반려사유 코드, 사용자 안내 문구와 추가 의견 허용 여부를 관리하는 업무 상태 모델 기준정보.';
COMMENT ON COLUMN rejection_reasons.business_type IS 'FACULTY_ACHIEVEMENT:교수업적평가|ACADEMIC_GRANT:학술지원금|OBJECTION:이의신청';
COMMENT ON COLUMN rejection_reasons.additional_opinion_allowed_yn IS 'Y:허용|N:불가';
COMMENT ON COLUMN rejection_reasons.created_by IS 'users.user_id 참조 의도 (반려사유 생성 처리자)';
COMMENT ON COLUMN rejection_reasons.updated_by IS 'users.user_id 참조 의도 (반려사유 최종 수정 처리자)';

CREATE INDEX IF NOT EXISTS idx_rejection_reasons_filter ON rejection_reasons(business_type, reason_code, additional_opinion_allowed_yn);
CREATE INDEX IF NOT EXISTS idx_rejection_reasons_updated ON rejection_reasons(updated_at DESC);

