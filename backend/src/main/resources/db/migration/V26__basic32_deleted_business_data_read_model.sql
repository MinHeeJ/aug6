CREATE TABLE IF NOT EXISTS deleted_business_data (
    deleted_data_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type varchar(50) NOT NULL,
    original_key varchar(200) NOT NULL,
    deleted_by bigint NOT NULL,
    deleted_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_reason varchar(500) NOT NULL,
    recoverable_yn char(1) NOT NULL DEFAULT 'N',
    CONSTRAINT ck_deleted_business_data_business_type CHECK (business_type IN ('FACULTY_ACHIEVEMENT','ACADEMIC_GRANT','OBJECTION')),
    CONSTRAINT ck_deleted_business_data_recoverable CHECK (recoverable_yn IN ('Y','N')),
    CONSTRAINT fk_deleted_business_data_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id)
);
COMMENT ON TABLE deleted_business_data IS '논리삭제된 교수업적평가·학술지원금·이의신청 업무자료의 원본키와 삭제정보를 조회하기 위한 삭제자료 projection.';
COMMENT ON COLUMN deleted_business_data.business_type IS 'FACULTY_ACHIEVEMENT:교수업적평가|ACADEMIC_GRANT:학술지원금|OBJECTION:이의신청';
COMMENT ON COLUMN deleted_business_data.recoverable_yn IS 'Y:복구가능|N:복구불가';

CREATE INDEX IF NOT EXISTS idx_deleted_business_data_business_key ON deleted_business_data(business_type, original_key);
CREATE INDEX IF NOT EXISTS idx_deleted_business_data_deleted_by_at ON deleted_business_data(deleted_by, deleted_at DESC);
CREATE INDEX IF NOT EXISTS idx_deleted_business_data_deleted_at ON deleted_business_data(deleted_at DESC);

