CREATE TABLE IF NOT EXISTS evaluation_rule_versions (
    rule_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_code varchar(50) NOT NULL,
    effective_start_date date NOT NULL,
    effective_end_date date NOT NULL,
    version_status varchar(20) NOT NULL,
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_evaluation_rule_versions_code UNIQUE (version_code),
    CONSTRAINT ck_evaluation_rule_versions_period CHECK (effective_end_date >= effective_start_date),
    CONSTRAINT ck_evaluation_rule_versions_status CHECK (version_status IN ('DRAFT','CONFIRMED','DISCARDED')),
    CONSTRAINT fk_evaluation_rule_versions_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_rule_versions_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_rule_versions IS '평가영역·평가항목·평가요소·관리항목 분류체계를 적용시작일·적용종료일과 작성중·확정·폐기 상태 단위로 묶는 평가규정 버전.';
COMMENT ON COLUMN evaluation_rule_versions.version_status IS 'DRAFT:작성중|CONFIRMED:확정|DISCARDED:폐기';
COMMENT ON COLUMN evaluation_rule_versions.created_by IS 'users.user_id 참조 의도 (평가규정 버전 생성자)';
COMMENT ON COLUMN evaluation_rule_versions.updated_by IS 'users.user_id 참조 의도 (평가규정 버전 수정자)';

CREATE TABLE IF NOT EXISTS evaluation_areas (
    area_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_version_id bigint NOT NULL,
    area_code varchar(50) NOT NULL,
    area_name varchar(100) NOT NULL,
    sort_order integer NOT NULL,
    active_yn char(1) NOT NULL DEFAULT 'Y',
    period_apply_method varchar(50) NOT NULL,
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_evaluation_areas_code UNIQUE (rule_version_id, area_code),
    CONSTRAINT ck_evaluation_areas_active CHECK (active_yn IN ('Y','N')),
    CONSTRAINT fk_evaluation_areas_rule_version FOREIGN KEY (rule_version_id) REFERENCES evaluation_rule_versions(rule_version_id),
    CONSTRAINT fk_evaluation_areas_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_areas_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_areas IS '평가규정 버전별 교육·연구/창작·봉사 등 최상위 평가영역 코드와 명칭, 정렬순서, 사용여부, 평가기간 적용방식을 관리한다.';
COMMENT ON COLUMN evaluation_areas.active_yn IS 'Y:사용|N:미사용';
COMMENT ON COLUMN evaluation_areas.period_apply_method IS 'OQ-DATA-B33-001 참조:평가기간 적용방식';

CREATE TABLE IF NOT EXISTS evaluation_items (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id bigint NOT NULL,
    item_code varchar(50) NOT NULL,
    item_name varchar(100) NOT NULL,
    parent_item_code varchar(50),
    sort_order integer NOT NULL,
    active_yn char(1) NOT NULL DEFAULT 'Y',
    score_apply_method varchar(50) NOT NULL,
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_evaluation_items_code UNIQUE (area_id, item_code),
    CONSTRAINT ck_evaluation_items_active CHECK (active_yn IN ('Y','N')),
    CONSTRAINT fk_evaluation_items_area FOREIGN KEY (area_id) REFERENCES evaluation_areas(area_id),
    CONSTRAINT fk_evaluation_items_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_items_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_items IS '평가영역별 평가항목·지표 코드와 상위항목 계층, 정렬순서, 사용여부, 배점 적용방식 구분을 관리한다.';
COMMENT ON COLUMN evaluation_items.parent_item_code IS '같은 evaluation_areas.area_id 내부 evaluation_items.item_code 참조 의도 (FK 미선언)';
COMMENT ON COLUMN evaluation_items.active_yn IS 'Y:사용|N:미사용';
COMMENT ON COLUMN evaluation_items.score_apply_method IS '점수값 제외:배점 적용방식 구분만 저장';

CREATE TABLE IF NOT EXISTS evaluation_elements (
    element_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    element_code varchar(50) NOT NULL,
    element_name varchar(100) NOT NULL,
    sort_order integer NOT NULL,
    active_yn char(1) NOT NULL DEFAULT 'Y',
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_evaluation_elements_code UNIQUE (item_id, evaluation_year, element_code),
    CONSTRAINT ck_evaluation_elements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_evaluation_elements_active CHECK (active_yn IN ('Y','N')),
    CONSTRAINT fk_evaluation_elements_item FOREIGN KEY (item_id) REFERENCES evaluation_items(item_id),
    CONSTRAINT fk_evaluation_elements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_elements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_elements IS '평가항목 아래 평가연도별 평가요소 코드와 코드명, 정렬순서, 사용여부를 관리한다.';
COMMENT ON COLUMN evaluation_elements.active_yn IS 'Y:사용|N:미사용';

CREATE TABLE IF NOT EXISTS evaluation_management_items (
    management_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    element_id bigint NOT NULL,
    management_item_code varchar(50) NOT NULL,
    management_item_name varchar(100) NOT NULL,
    sort_order integer NOT NULL,
    active_yn char(1) NOT NULL DEFAULT 'Y',
    teacher_editable_yn char(1) NOT NULL DEFAULT 'N',
    required_yn char(1) NOT NULL DEFAULT 'N',
    data_type varchar(30) NOT NULL,
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_evaluation_management_items_code UNIQUE (element_id, management_item_code),
    CONSTRAINT ck_evaluation_management_items_active CHECK (active_yn IN ('Y','N')),
    CONSTRAINT ck_evaluation_management_items_teacher_editable CHECK (teacher_editable_yn IN ('Y','N')),
    CONSTRAINT ck_evaluation_management_items_required CHECK (required_yn IN ('Y','N')),
    CONSTRAINT ck_evaluation_management_items_data_type CHECK (data_type IN ('TEXT','NUMBER','DATE','BOOLEAN','CODE','FILE')),
    CONSTRAINT fk_evaluation_management_items_element FOREIGN KEY (element_id) REFERENCES evaluation_elements(element_id),
    CONSTRAINT fk_evaluation_management_items_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_management_items_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_management_items IS '평가요소별 세부 관리항목 코드와 교원 입력가능 여부, 필수여부, 데이터형식 조건을 관리한다.';
COMMENT ON COLUMN evaluation_management_items.active_yn IS 'Y:사용|N:미사용';
COMMENT ON COLUMN evaluation_management_items.teacher_editable_yn IS 'Y:교원입력가능|N:교원입력불가';
COMMENT ON COLUMN evaluation_management_items.required_yn IS 'Y:필수|N:선택';
COMMENT ON COLUMN evaluation_management_items.data_type IS 'TEXT:문자|NUMBER:숫자|DATE:일자|BOOLEAN:여부|CODE:코드|FILE:파일';

CREATE TABLE IF NOT EXISTS area_element_system_settings (
    system_setting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id bigint NOT NULL,
    target_scope varchar(100) NOT NULL,
    active_yn char(1) NOT NULL DEFAULT 'Y',
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_area_element_system_settings_key UNIQUE (area_id, target_scope),
    CONSTRAINT ck_area_element_system_settings_active CHECK (active_yn IN ('Y','N')),
    CONSTRAINT fk_area_element_system_settings_area FOREIGN KEY (area_id) REFERENCES evaluation_areas(area_id),
    CONSTRAINT fk_area_element_system_settings_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_area_element_system_settings_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE area_element_system_settings IS '업적영역별 평가항목·지표·평가요소 체계의 적용 대상과 사용상태를 관리한다.';
COMMENT ON COLUMN area_element_system_settings.target_scope IS '기존 조직·소속·평가대상 참조 의도 (FK 미선언)';
COMMENT ON COLUMN area_element_system_settings.active_yn IS 'Y:사용|N:미사용';

