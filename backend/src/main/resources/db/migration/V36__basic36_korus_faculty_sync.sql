CREATE TABLE IF NOT EXISTS korus_faculty_sync_runs (
    run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id varchar(100) NOT NULL UNIQUE,
    run_type varchar(20) NOT NULL CHECK (run_type IN ('MANUAL','RETRY','SCHEDULED')),
    target_start_date date NOT NULL,
    target_end_date date NOT NULL,
    run_status varchar(20) NOT NULL DEFAULT 'RUNNING' CHECK (run_status IN ('RUNNING','SUCCESS','FAILED','PARTIAL')),
    total_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    created_by bigint,
    started_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at timestamp,
    failure_reason varchar(1000),
    CONSTRAINT fk_korus_faculty_sync_runs_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT ck_korus_faculty_sync_runs_period CHECK (target_end_date >= target_start_date)
);
COMMENT ON TABLE korus_faculty_sync_runs IS 'KORUS 교원 기본정보 연계 실행 단위. 자동 02:00 또는 관리자 수동·재처리 요청의 request_id와 성공/실패 집계를 보존한다.';
COMMENT ON COLUMN korus_faculty_sync_runs.run_type IS 'MANUAL:수동|RETRY:재처리|SCHEDULED:자동';
COMMENT ON COLUMN korus_faculty_sync_runs.run_status IS 'RUNNING:실행중|SUCCESS:성공|FAILED:실패|PARTIAL:부분성공';

CREATE TABLE IF NOT EXISTS korus_faculty_sync_results (
    result_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL,
    request_id varchar(100) NOT NULL,
    employee_no varchar(50) NOT NULL,
    name varchar(100) NOT NULL,
    organization_code varchar(50) NOT NULL,
    rank_name varchar(100),
    appointment_id varchar(100) NOT NULL,
    sync_status varchar(20) NOT NULL CHECK (sync_status IN ('SUCCESS','FAILED')),
    error_message varchar(1000),
    retry_of_result_id bigint,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_korus_faculty_sync_results_run FOREIGN KEY (run_id) REFERENCES korus_faculty_sync_runs(run_id),
    CONSTRAINT fk_korus_faculty_sync_results_retry_of FOREIGN KEY (retry_of_result_id) REFERENCES korus_faculty_sync_results(result_id),
    CONSTRAINT uq_korus_faculty_sync_result_source UNIQUE (run_id, employee_no, organization_code, appointment_id)
);
COMMENT ON TABLE korus_faculty_sync_results IS 'KORUS 교원 기본정보 연계 결과. 교번·조직·보직 원천 식별자와 성공/실패·오류 재처리 대상을 보존한다.';
COMMENT ON COLUMN korus_faculty_sync_results.employee_no IS 'korus_personnel_snapshots.employee_no 참조 의도 (FK 미선언)';
COMMENT ON COLUMN korus_faculty_sync_results.organization_code IS 'organizations.organization_code 참조 의도 (FK 미선언)';
COMMENT ON COLUMN korus_faculty_sync_results.appointment_id IS 'KORUS 보직/임용 원천 식별자 참조 의도 (FK 미선언)';
COMMENT ON COLUMN korus_faculty_sync_results.sync_status IS 'SUCCESS:성공|FAILED:실패';
COMMENT ON COLUMN korus_faculty_sync_results.request_id IS 'KorusFacultySyncService.createRun/retryFailedResult 처리 시 애플리케이션에서 부여·갱신';

CREATE INDEX IF NOT EXISTS idx_korus_faculty_sync_runs_started_at ON korus_faculty_sync_runs(started_at);
CREATE INDEX IF NOT EXISTS idx_korus_faculty_sync_results_request_id ON korus_faculty_sync_results(request_id);
CREATE INDEX IF NOT EXISTS idx_korus_faculty_sync_results_employee_no ON korus_faculty_sync_results(employee_no);
CREATE INDEX IF NOT EXISTS idx_korus_faculty_sync_results_status ON korus_faculty_sync_results(sync_status);

