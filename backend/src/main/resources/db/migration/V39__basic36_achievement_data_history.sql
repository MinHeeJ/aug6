CREATE TABLE IF NOT EXISTS achievement_data_histories (
    history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_history_id bigint,
    achievement_type varchar(100) NOT NULL,
    achievement_key varchar(200) NOT NULL,
    employee_no varchar(50),
    change_type varchar(20) NOT NULL,
    field_name varchar(100) NOT NULL,
    before_value text,
    after_value text,
    changed_by bigint NOT NULL,
    changed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT ck_achievement_data_histories_change_type CHECK (change_type IN ('CREATE','UPDATE','DELETE')),
    CONSTRAINT fk_achievement_data_histories_source FOREIGN KEY (source_history_id) REFERENCES data_change_histories(history_id),
    CONSTRAINT fk_achievement_data_histories_changed_by FOREIGN KEY (changed_by) REFERENCES users(user_id)
);
COMMENT ON TABLE achievement_data_histories IS '업적데이터 변경이력 조회 전용 보존 테이블. 변경 전후 값·변경자·변경일시·변경사유를 BASIC-36 이력 화면에 제공한다.';
COMMENT ON COLUMN achievement_data_histories.source_history_id IS 'data_change_histories.history_id 참조 의도 (기존 공통 변경이력 패턴 연결)';
COMMENT ON COLUMN achievement_data_histories.change_type IS 'CREATE:등록|UPDATE:수정|DELETE:삭제';
COMMENT ON COLUMN achievement_data_histories.employee_no IS 'korus_personnel_snapshots.employee_no 참조 의도 (업적 소유 교원 식별)';
COMMENT ON COLUMN achievement_data_histories.before_value IS 'ResearcherProfileService 등 업무 저장 직전 값으로 애플리케이션에서 기록';
COMMENT ON COLUMN achievement_data_histories.after_value IS 'ResearcherProfileService 등 업무 저장 직후 값으로 애플리케이션에서 기록';

CREATE TABLE IF NOT EXISTS achievement_data_as_of_snapshots (
    snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(100) NOT NULL,
    achievement_key varchar(200) NOT NULL,
    employee_no varchar(50),
    achievement_title varchar(300) NOT NULL,
    achievement_status varchar(20) NOT NULL,
    snapshot_value text NOT NULL,
    base_at timestamp NOT NULL,
    captured_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    captured_by bigint NOT NULL,
    CONSTRAINT fk_achievement_data_as_of_snapshots_captured_by FOREIGN KEY (captured_by) REFERENCES users(user_id)
);
COMMENT ON TABLE achievement_data_as_of_snapshots IS '업적데이터 기준시점 조회 재현용 snapshot. 확정 또는 기준시점 데이터와 원본 변경 이후에도 재현 가능한 값을 보존한다.';
COMMENT ON COLUMN achievement_data_as_of_snapshots.employee_no IS 'korus_personnel_snapshots.employee_no 참조 의도 (업적 소유 교원 식별)';
COMMENT ON COLUMN achievement_data_as_of_snapshots.achievement_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN achievement_data_as_of_snapshots.snapshot_value IS 'ResearcherProfileService 저장 이력 또는 평가확정 처리 시 기준시점 재현용으로 애플리케이션에서 기록';
COMMENT ON COLUMN achievement_data_as_of_snapshots.base_at IS '기준시점 조회 조건과 비교하는 업무 기준시점';

CREATE UNIQUE INDEX IF NOT EXISTS ux_achievement_data_histories_source ON achievement_data_histories(source_history_id) WHERE source_history_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_achievement_data_histories_filter ON achievement_data_histories(achievement_type, achievement_key, changed_at DESC);
CREATE INDEX IF NOT EXISTS idx_achievement_data_histories_employee ON achievement_data_histories(employee_no, changed_at DESC);
CREATE INDEX IF NOT EXISTS idx_achievement_data_as_of_filter ON achievement_data_as_of_snapshots(achievement_type, achievement_key, base_at DESC);
CREATE INDEX IF NOT EXISTS idx_achievement_data_as_of_employee ON achievement_data_as_of_snapshots(employee_no, base_at DESC);

INSERT INTO achievement_data_histories (source_history_id, achievement_type, achievement_key, employee_no, change_type, field_name, before_value, after_value, changed_by, changed_at, change_reason)
SELECT dch.history_id,
       dch.target_business,
       dch.target_key,
       case when dch.target_business = 'BASIC36_RESEARCHER_PROFILE' then dch.target_key else null end,
       dch.change_type,
       dch.field_name,
       dch.before_value,
       dch.after_value,
       dch.changed_by,
       dch.changed_at,
       dch.change_reason
FROM data_change_histories dch
WHERE dch.target_business LIKE 'BASIC36_%'
ON CONFLICT DO NOTHING;

INSERT INTO achievement_data_histories (achievement_type, achievement_key, employee_no, change_type, field_name, before_value, after_value, changed_by, change_reason)
SELECT 'BASIC36_RESEARCHER_PROFILE', rp.employee_no, rp.employee_no, 'UPDATE', 'degrees', '[]', rd.degree_type || ':' || rd.university_name, rp.updated_by, 'BASIC-36 업적데이터 변경이력 seed'
FROM researcher_profiles rp
JOIN researcher_degrees rd ON rd.employee_no = rp.employee_no
WHERE rp.employee_no = 'E1001'
  AND NOT EXISTS (SELECT 1 FROM achievement_data_histories WHERE achievement_type = 'BASIC36_RESEARCHER_PROFILE' AND achievement_key = rp.employee_no);

INSERT INTO achievement_data_as_of_snapshots (achievement_type, achievement_key, employee_no, achievement_title, achievement_status, snapshot_value, base_at, captured_by)
SELECT 'BASIC36_RESEARCHER_PROFILE', rp.employee_no, rp.employee_no, '연구자 프로필 직접관리 정보', 'CERTIFIED', coalesce(rd.degree_type, '-') || ':' || coalesce(rd.university_name, '-'), CURRENT_TIMESTAMP, rp.updated_by
FROM researcher_profiles rp
LEFT JOIN researcher_degrees rd ON rd.employee_no = rp.employee_no
WHERE rp.employee_no = 'E1001'
  AND NOT EXISTS (SELECT 1 FROM achievement_data_as_of_snapshots WHERE achievement_type = 'BASIC36_RESEARCHER_PROFILE' AND achievement_key = rp.employee_no);

