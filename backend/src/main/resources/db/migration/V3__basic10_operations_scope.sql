CREATE TABLE IF NOT EXISTS position_assignments (
    position_assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_code varchar(50) NOT NULL,
    user_id bigint NOT NULL,
    organization_code varchar(50) NOT NULL,
    effective_start_date date NOT NULL,
    effective_end_date date,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','EXPIRED','DELETED')),
    confirmed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT fk_position_assignments_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_position_assignments_org FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_position_assignments_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_position_assignments_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
    CONSTRAINT ck_position_assignments_dates CHECK (effective_end_date IS NULL OR effective_end_date >= effective_start_date)
);
COMMENT ON TABLE position_assignments IS '보직코드별 대상 사용자·소속조직·유효기간을 관리하는 보직 지정 테이블. 사용자 원천 인사정보와 조직구조는 변경하지 않고 기간별 보직 권한 판정에 사용한다.';
COMMENT ON COLUMN position_assignments.status IS 'ACTIVE:유효|EXPIRED:만료|DELETED:삭제';
COMMENT ON COLUMN position_assignments.confirmed_at IS '보직 지정 저장 또는 변경 확정 시 애플리케이션에서 갱신';

CREATE INDEX IF NOT EXISTS idx_position_assignments_reference_date ON position_assignments (position_code, organization_code, effective_start_date, effective_end_date);
CREATE INDEX IF NOT EXISTS idx_position_assignments_user ON position_assignments (user_id);

CREATE TABLE IF NOT EXISTS duty_assignments (
    duty_assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duty_organization varchar(100) NOT NULL,
    user_id bigint NOT NULL,
    duty_area varchar(100) NOT NULL,
    valid_start_date date NOT NULL,
    valid_end_date date,
    data_scope_type varchar(20) NOT NULL CHECK (data_scope_type IN ('SELF','DEPARTMENT','COLLEGE','DUTY','ALL')),
    processing_permission varchar(100) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ENDED','DELETED')),
    confirmed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT fk_duty_assignments_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_duty_assignments_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_duty_assignments_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
    CONSTRAINT ck_duty_assignments_dates CHECK (valid_end_date IS NULL OR valid_end_date >= valid_start_date)
);
COMMENT ON TABLE duty_assignments IS '업무조직별 담당자와 담당 업무영역·지정기간·데이터범위·처리권한을 관리한다. 겹치는 지정은 조회·판정 시 confirmed_at 최신 확정 row를 우선 적용한다.';
COMMENT ON COLUMN duty_assignments.data_scope_type IS 'SELF:본인|DEPARTMENT:소속학과|COLLEGE:단과대학|DUTY:담당업무|ALL:전체';
COMMENT ON COLUMN duty_assignments.status IS 'ACTIVE:지정|ENDED:지정종료|DELETED:삭제';
COMMENT ON COLUMN duty_assignments.confirmed_at IS '업무담당자 지정 저장 또는 변경 확정 시 애플리케이션에서 갱신';

CREATE INDEX IF NOT EXISTS idx_duty_assignments_effective ON duty_assignments (user_id, duty_area, valid_start_date, valid_end_date, confirmed_at);
CREATE INDEX IF NOT EXISTS idx_duty_assignments_scope ON duty_assignments (duty_organization, duty_area);

CREATE TABLE IF NOT EXISTS data_scope_rules (
    data_scope_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code varchar(3) NOT NULL,
    data_scope_type varchar(20) NOT NULL CHECK (data_scope_type IN ('SELF','DEPARTMENT','COLLEGE','DUTY','ALL')),
    organization_code varchar(50),
    duty_area varchar(100),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','DELETED')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500),
    CONSTRAINT fk_data_scope_rules_role FOREIGN KEY (role_code) REFERENCES roles(role_code),
    CONSTRAINT fk_data_scope_rules_org FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_data_scope_rules_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_data_scope_rules_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
    CONSTRAINT uq_data_scope_rule_scope UNIQUE (role_code, data_scope_type, organization_code, duty_area)
);
COMMENT ON TABLE data_scope_rules IS '역할별 조회·처리 가능 데이터 범위 규칙을 관리한다. 여러 역할의 데이터 범위는 서버 조회조건에서 합집합으로 적용된다.';
COMMENT ON COLUMN data_scope_rules.role_code IS 'roles.role_code 참조, R01~R09 기존 역할코드만 사용';
COMMENT ON COLUMN data_scope_rules.data_scope_type IS 'SELF:본인|DEPARTMENT:소속학과|COLLEGE:단과대학|DUTY:담당업무|ALL:전체';
COMMENT ON COLUMN data_scope_rules.status IS 'ACTIVE:활성|INACTIVE:비활성|DELETED:삭제';
COMMENT ON COLUMN data_scope_rules.organization_code IS 'organizations.organization_code 참조, 조직 범위 조건';
COMMENT ON COLUMN data_scope_rules.duty_area IS 'duty_assignments.duty_area 참조 의도 (FK 미선언)';

CREATE INDEX IF NOT EXISTS idx_data_scope_rules_role ON data_scope_rules (role_code, status);
CREATE INDEX IF NOT EXISTS idx_data_scope_rules_scope_type ON data_scope_rules (data_scope_type);
