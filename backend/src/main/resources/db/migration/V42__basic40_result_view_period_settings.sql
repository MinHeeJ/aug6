CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS result_view_period_settings (
    setting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    college_organization_code varchar(50) NOT NULL,
    department_organization_code varchar(50),
    view_start_at timestamp NOT NULL,
    view_end_at timestamp NOT NULL,
    visibility_scope varchar(50) NOT NULL,
    active_yn varchar(1) NOT NULL DEFAULT 'Y',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT ck_result_view_period_settings_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_result_view_period_settings_period CHECK (view_end_at >= view_start_at),
    CONSTRAINT ck_result_view_period_settings_visibility CHECK (visibility_scope IN ('SELF','DEPARTMENT','COLLEGE','BUSINESS','ALL')),
    CONSTRAINT ck_result_view_period_settings_active CHECK (active_yn IN ('Y','N')),
    CONSTRAINT fk_result_view_period_settings_college FOREIGN KEY (college_organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_result_view_period_settings_department FOREIGN KEY (department_organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_result_view_period_settings_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_result_view_period_settings_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
    CONSTRAINT ex_result_view_period_settings_active_period EXCLUDE USING gist (
        evaluation_year WITH =,
        college_organization_code WITH =,
        COALESCE(department_organization_code, '') WITH =,
        visibility_scope WITH =,
        tsrange(view_start_at, view_end_at, '[]') WITH &&
    ) WHERE (active_yn = 'Y')
);
COMMENT ON TABLE result_view_period_settings IS '결과조회기간 관리 설정. 평가연도와 소속대학·학과별 개인평가 결과 공개 시작·종료일시 및 공개범위를 저장한다.';
COMMENT ON COLUMN result_view_period_settings.visibility_scope IS 'SELF:본인|DEPARTMENT:학과|COLLEGE:단과대학|BUSINESS:담당업무|ALL:전체';
COMMENT ON COLUMN result_view_period_settings.active_yn IS 'Y:사용|N:미사용';
COMMENT ON COLUMN result_view_period_settings.created_by IS 'users.user_id 참조 의도 (결과조회기간 관리 생성자)';
COMMENT ON COLUMN result_view_period_settings.updated_by IS 'users.user_id 참조 의도 (결과조회기간 관리 수정자)';

CREATE INDEX IF NOT EXISTS idx_result_view_period_settings_search
    ON result_view_period_settings(evaluation_year, college_organization_code, department_organization_code, visibility_scope, active_yn, view_start_at, view_end_at);
CREATE INDEX IF NOT EXISTS idx_result_view_period_settings_visibility
    ON result_view_period_settings(visibility_scope, active_yn, view_start_at, view_end_at);

