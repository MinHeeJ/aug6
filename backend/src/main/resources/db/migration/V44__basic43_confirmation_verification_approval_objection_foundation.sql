CREATE TABLE IF NOT EXISTS department_chair_confirmations (
    confirmation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    department_organization_code varchar(50) NOT NULL,
    area_code varchar(50) NOT NULL,
    confirm_status varchar(50) NOT NULL,
    previous_status varchar(50) NOT NULL,
    next_status varchar(50) NOT NULL,
    opinion varchar(1000),
    reason_code varchar(50),
    processed_by bigint NOT NULL,
    processed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_type varchar(30) NOT NULL DEFAULT 'TRANSITION',
    changed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by bigint NOT NULL,
    change_reason varchar(500) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_department_chair_confirmations_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_department_chair_confirmations_status CHECK (confirm_status IN ('DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED')),
    CONSTRAINT ck_department_chair_confirmations_previous_status CHECK (previous_status IN ('DRAFTING','SUBMITTED','DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED','CERTIFIED','CERTIFICATION_RETURNED','EVALUATION_CONFIRMED','DELETED')),
    CONSTRAINT ck_department_chair_confirmations_next_status CHECK (next_status IN ('DRAFTING','SUBMITTED','DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED','CERTIFIED','CERTIFICATION_RETURNED','EVALUATION_CONFIRMED','DELETED')),
    CONSTRAINT ck_department_chair_confirmations_change_type CHECK (change_type IN ('CREATE','TRANSITION','UPDATE','DELETE')),
    CONSTRAINT fk_department_chair_confirmations_department FOREIGN KEY (department_organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_department_chair_confirmations_processed_by FOREIGN KEY (processed_by) REFERENCES users(user_id),
    CONSTRAINT fk_department_chair_confirmations_changed_by FOREIGN KEY (changed_by) REFERENCES users(user_id),
    CONSTRAINT fk_department_chair_confirmations_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_department_chair_confirmations_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE department_chair_confirmations IS '학과장 확인 관리 처리 결과와 의견 보존 테이블. 제출 업적에 대한 확인·미승인 상태 전이, 처리자, 처리일시, 사유와 변경 이력을 저장한다.';
COMMENT ON COLUMN department_chair_confirmations.achievement_id IS 'achievement records 참조 의도 (FK 미선언, 업적 원천정보 수정 금지)';
COMMENT ON COLUMN department_chair_confirmations.department_organization_code IS 'organizations.organization_code 참조 의도 (학과장 확인 소속 학과)';
COMMENT ON COLUMN department_chair_confirmations.area_code IS 'evaluation_areas.area_code 참조 의도 (학과장 확인 평가영역)';
COMMENT ON COLUMN department_chair_confirmations.confirm_status IS 'DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인';
COMMENT ON COLUMN department_chair_confirmations.previous_status IS 'business_status_transitions.from_status_code 참조 의도 (전이 전 업적 상태)';
COMMENT ON COLUMN department_chair_confirmations.next_status IS 'business_status_transitions.to_status_code 참조 의도 (전이 후 업적 상태)';
COMMENT ON COLUMN department_chair_confirmations.reason_code IS 'rejection_reasons.reason_code 참조 의도 (학과장미승인 표준 사유)';
COMMENT ON COLUMN department_chair_confirmations.processed_by IS 'users.user_id 참조 의도 (학과장 확인 처리자)';
COMMENT ON COLUMN department_chair_confirmations.changed_by IS 'users.user_id 참조 의도 (변경 이력 처리자)';
COMMENT ON COLUMN department_chair_confirmations.change_type IS 'CREATE:생성|TRANSITION:상태전이|UPDATE:수정|DELETE:삭제';
COMMENT ON COLUMN department_chair_confirmations.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN department_chair_confirmations.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_department_chair_confirmations_search
    ON department_chair_confirmations(evaluation_year, department_organization_code, area_code, confirm_status, processed_at DESC);
CREATE INDEX IF NOT EXISTS idx_department_chair_confirmations_achievement
    ON department_chair_confirmations(achievement_id, processed_at DESC);
CREATE INDEX IF NOT EXISTS idx_department_chair_confirmations_reason
    ON department_chair_confirmations(reason_code);

