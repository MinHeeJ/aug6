CREATE TABLE IF NOT EXISTS evaluation_batch_requests (
    batch_request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id varchar(100) NOT NULL,
    job_type varchar(30) NOT NULL,
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    request_user_id bigint NOT NULL,
    request_status varchar(30) NOT NULL DEFAULT 'REQUESTED',
    request_id varchar(100) NOT NULL,
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at timestamp,
    completed_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_evaluation_batch_requests_batch_id UNIQUE (batch_id),
    CONSTRAINT uq_evaluation_batch_requests_request_id UNIQUE (request_id),
    CONSTRAINT ck_evaluation_batch_requests_job_type CHECK (job_type IN ('GENERATION','DELETION','RECALCULATION','CONFIRMATION')),
    CONSTRAINT ck_evaluation_batch_requests_status CHECK (request_status IN ('REQUESTED','RUNNING','COMPLETED','FAILED','CANCELLED')),
    CONSTRAINT fk_evaluation_batch_requests_user FOREIGN KEY (request_user_id) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_batch_requests IS '평가자료 생성·삭제, 점수 재계산, 최종평가 확정 요청 조건과 batchId, requestId, 요청자를 보존하는 BASIC-45 일괄처리 요청 테이블.';
COMMENT ON COLUMN evaluation_batch_requests.batch_id IS 'B45-{JOB_TYPE}-{YYYYMMDD}-{SEQ6} 형식의 업무 일괄처리 식별자';
COMMENT ON COLUMN evaluation_batch_requests.job_type IS 'GENERATION:생성|DELETION:삭제|RECALCULATION:재계산|CONFIRMATION:확정';
COMMENT ON COLUMN evaluation_batch_requests.target_condition_json IS '평가연도·영역·조직·대상자 등 요청 조건 JSON (EvaluationBatchService 요청 등록 시 애플리케이션에서 갱신)';
COMMENT ON COLUMN evaluation_batch_requests.request_user_id IS 'users.user_id 참조 의도 (일괄처리 요청자)';
COMMENT ON COLUMN evaluation_batch_requests.request_status IS 'REQUESTED:요청|RUNNING:실행중|COMPLETED:완료|FAILED:실패|CANCELLED:취소';
COMMENT ON COLUMN evaluation_batch_requests.request_id IS 'HTTP requestId tracing 식별자; ApiResponse.meta.requestId와 동일하게 애플리케이션에서 갱신';

CREATE TABLE IF NOT EXISTS evaluation_materials (
    evaluation_material_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    area_code varchar(50) NOT NULL,
    target_user_id bigint NOT NULL,
    source_achievement_id bigint NOT NULL,
    generation_batch_id varchar(100) NOT NULL,
    material_status varchar(30) NOT NULL DEFAULT '인증',
    material_origin varchar(30) NOT NULL DEFAULT 'BATCH_GENERATED',
    material_snapshot_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    calculated_score numeric(10,2) NOT NULL DEFAULT 0,
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    delete_reason varchar(500),
    deleted_by bigint,
    deleted_at timestamp,
    request_id varchar(100) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_evaluation_materials_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_evaluation_materials_status CHECK (material_status IN ('작성중','제출','학과장확인','학과장미승인','인증','인증반려','평가확정','삭제')),
    CONSTRAINT ck_evaluation_materials_origin CHECK (material_origin IN ('BATCH_GENERATED','MANUAL')),
    CONSTRAINT ck_evaluation_materials_deleted CHECK (deleted_yn IN ('Y','N')),
    CONSTRAINT fk_evaluation_materials_target_user FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_materials_generation_batch FOREIGN KEY (generation_batch_id) REFERENCES evaluation_batch_requests(batch_id),
    CONSTRAINT fk_evaluation_materials_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_materials_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_materials_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
