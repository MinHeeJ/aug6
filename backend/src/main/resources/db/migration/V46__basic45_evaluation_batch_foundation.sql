COMMENT ON TABLE evaluation_materials IS '인증 원천 실적을 평가연도·영역·대상자 기준으로 전환한 평가자료. 원천 실적은 변경하지 않고 평가자료 삭제는 물리삭제 대신 deleted_yn과 material_status로 보존한다.';
