CREATE TABLE IF NOT EXISTS evaluation_batch_results (
    batch_result_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id varchar(100) NOT NULL,
    job_type varchar(30) NOT NULL,
    total_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    excluded_count integer NOT NULL DEFAULT 0,
    error_detail_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    request_id varchar(100) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_evaluation_batch_results_batch_id UNIQUE (batch_id),
    CONSTRAINT ck_evaluation_batch_results_job_type CHECK (job_type IN ('GENERATION','DELETION','RECALCULATION','CONFIRMATION')),
    CONSTRAINT ck_evaluation_batch_results_counts CHECK (total_count >= 0 AND success_count >= 0 AND failure_count >= 0 AND excluded_count >= 0),
    CONSTRAINT fk_evaluation_batch_results_batch FOREIGN KEY (batch_id) REFERENCES evaluation_batch_requests(batch_id)
);
COMMENT ON TABLE evaluation_batch_results IS 'BASIC-45 batchId별 일괄처리 결과 조회용 테이블. 총건수, 성공, 실패, 제외 건수와 오류 상세를 원작업 결과로 보존하며 조회 기능은 재실행하거나 변경하지 않는다.';
COMMENT ON COLUMN evaluation_batch_results.batch_id IS 'evaluation_batch_requests.batch_id 참조 의도 (결과 조회 기준 batchId)';
COMMENT ON COLUMN evaluation_batch_results.job_type IS 'GENERATION:생성|DELETION:삭제|RECALCULATION:재계산|CONFIRMATION:확정';
COMMENT ON COLUMN evaluation_batch_results.error_detail_json IS 'EvaluationBatchResultService가 실패 대상 식별정보와 오류 상세를 JSON 배열로 보존';
COMMENT ON COLUMN evaluation_batch_results.request_id IS '처리 결과를 생성한 HTTP 또는 배치 requestId tracing 식별자';

CREATE TABLE IF NOT EXISTS score_calculation_generations (
    calculation_generation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_material_id bigint NOT NULL,
    formula_version_id bigint NOT NULL,
    generation_no integer NOT NULL,
    before_score numeric(10,2) NOT NULL DEFAULT 0,
    after_score numeric(10,2) NOT NULL DEFAULT 0,
    calculated_score numeric(10,2) NOT NULL DEFAULT 0,
    rule_version_id bigint NOT NULL,
    calculation_basis_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    recalculation_batch_id varchar(100) NOT NULL,
    request_id varchar(100) NOT NULL,
    calculated_by bigint NOT NULL,
    calculated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_score_calculation_generations_material_generation UNIQUE (evaluation_material_id, generation_no),
    CONSTRAINT ck_score_calculation_generations_no CHECK (generation_no > 0),
    CONSTRAINT fk_score_calculation_generations_material FOREIGN KEY (evaluation_material_id) REFERENCES evaluation_materials(evaluation_material_id),
    CONSTRAINT fk_score_calculation_generations_formula FOREIGN KEY (formula_version_id) REFERENCES calculation_formula_versions(formula_version_id),
    CONSTRAINT fk_score_calculation_generations_rule FOREIGN KEY (rule_version_id) REFERENCES evaluation_rule_versions(rule_version_id),
    CONSTRAINT fk_score_calculation_generations_batch FOREIGN KEY (recalculation_batch_id) REFERENCES evaluation_batch_requests(batch_id),
    CONSTRAINT fk_score_calculation_generations_by FOREIGN KEY (calculated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE score_calculation_generations IS '평가자료 점수 재계산 세대 테이블. 산식버전별 재계산 전후 점수와 산출근거를 세대 단위로 보존하고 기존 산출근거를 덮어쓰지 않는다.';
COMMENT ON COLUMN score_calculation_generations.evaluation_material_id IS 'evaluation_materials.evaluation_material_id 참조 의도 (재계산 대상 평가자료)';
COMMENT ON COLUMN score_calculation_generations.formula_version_id IS 'calculation_formula_versions.formula_version_id 참조 의도 (적용 산식버전)';
COMMENT ON COLUMN score_calculation_generations.rule_version_id IS 'evaluation_rule_versions.rule_version_id 참조 의도 (적용 규정버전)';
COMMENT ON COLUMN score_calculation_generations.calculation_basis_json IS 'ScoreRecalculationService가 원천 업적, 기준배점, 참여구분, 배분율, 상한 적용 여부 등 산출근거를 애플리케이션에서 보존';
COMMENT ON COLUMN score_calculation_generations.recalculation_batch_id IS 'evaluation_batch_requests.batch_id 참조 의도 (재계산 배치)';
COMMENT ON COLUMN score_calculation_generations.request_id IS '재계산 requestId tracing 식별자';
COMMENT ON COLUMN score_calculation_generations.calculated_by IS 'users.user_id 참조 의도 (재계산 처리자)';

