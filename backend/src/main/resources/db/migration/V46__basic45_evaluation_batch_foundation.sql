COMMENT ON COLUMN evaluation_materials.material_origin IS 'BATCH_GENERATED:일괄생성|MANUAL:수동등록';
COMMENT ON COLUMN evaluation_materials.material_snapshot_json IS 'EvaluationMaterialGenerationService 생성 시 원천 실적의 평가 사용 snapshot을 애플리케이션에서 보존';
