CREATE TABLE IF NOT EXISTS evaluation_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    batch_type varchar(50) NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    area_code varchar(50),
    organization_code varchar(50),
    target_user_id bigint,
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    total_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    excluded_count integer NOT NULL DEFAULT 0,
    job_status varchar(30) NOT NULL DEFAULT 'COMPLETED',
    requested_by bigint NOT NULL,
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_id varchar(100) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_evaluation_batch_jobs_type CHECK (batch_type IN ('GENERATION','DELETION','SCORE_RECALCULATION','FINALIZATION','FINALIZATION_CANCEL')),
    CONSTRAINT ck_evaluation_batch_jobs_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_evaluation_batch_jobs_counts CHECK (total_count >= 0 AND success_count >= 0 AND failure_count >= 0 AND excluded_count >= 0),
    CONSTRAINT ck_evaluation_batch_jobs_status CHECK (job_status IN ('REQUESTED','RUNNING','COMPLETED','FAILED','CANCELLED')),
    CONSTRAINT fk_evaluation_batch_jobs_organization FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_evaluation_batch_jobs_target_user FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_batch_jobs_requested_by FOREIGN KEY (requested_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_batch_jobs_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_evaluation_batch_jobs_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE evaluation_batch_jobs IS 'BASIC-46 평가자료 생성·삭제, 점수 재계산, 최종평가 확정·취소 작업의 batchId와 조건, 처리 건수, 요청 식별자를 보존하는 일괄처리 작업 테이블.';
COMMENT ON COLUMN evaluation_batch_jobs.batch_type IS 'GENERATION:평가자료생성|DELETION:평가자료삭제|SCORE_RECALCULATION:점수재계산|FINALIZATION:평가확정|FINALIZATION_CANCEL:평가확정취소';
COMMENT ON COLUMN evaluation_batch_jobs.area_code IS 'evaluation_areas.area_code 참조 의도 (업무 영역 필터, 규정버전별 코드라 FK 미선언)';
COMMENT ON COLUMN evaluation_batch_jobs.organization_code IS 'organizations.organization_code 참조 의도 (조직 조건)';
COMMENT ON COLUMN evaluation_batch_jobs.target_user_id IS 'users.user_id 참조 의도 (대상자 조건)';
COMMENT ON COLUMN evaluation_batch_jobs.target_condition_json IS '평가연도·영역·조직·대상자·산식버전 등 실행 조건 snapshot';
