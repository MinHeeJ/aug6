COMMENT ON COLUMN email_verification_events.token_id IS 'email_verification_tokens.token_id 참조. 기존 계정 면제 이벤트는 null 가능';
COMMENT ON COLUMN email_verification_events.actor_type IS 'SYSTEM:시스템|VISITOR:방문자|USER:사용자';

