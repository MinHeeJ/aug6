CREATE OR REPLACE FUNCTION supersede_email_verification_tokens(p_user_id bigint, p_target_email varchar)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    affected integer;
BEGIN
    UPDATE email_verification_tokens
    SET status = 'SUPERSEDED',
        updated_at = CURRENT_TIMESTAMP
    WHERE user_id = p_user_id
      AND target_email = lower(trim(p_target_email))
      AND status = 'ACTIVE';
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$;

UPDATE users
SET email_substitute_yn = 'Y'
WHERE email IS NULL
  AND login_id IN ('admin', 'professor1')
  AND coalesce(account_status, status) IN ('ACTIVE', 'INACTIVE', 'DELETED');

UPDATE users
SET email_verified_yn = 'Y',
    verification_origin = 'EXEMPT_EXISTING',
    account_status = coalesce(account_status, status),
    updated_at = CURRENT_TIMESTAMP
WHERE login_id = 'admin'
  AND coalesce(account_status, status) IN ('ACTIVE', 'INACTIVE', 'DELETED');

UPDATE users
SET email_verified_yn = 'Y',
    verification_origin = 'EXEMPT_EXISTING',
    account_status = coalesce(account_status, status),
    updated_at = CURRENT_TIMESTAMP
WHERE login_id = 'professor1'
  AND coalesce(account_status, status) IN ('ACTIVE', 'INACTIVE', 'DELETED');

INSERT INTO email_verification_events (user_id, event_type, normalized_email, actor_type, event_reason)
SELECT u.user_id, 'EXEMPT_EXISTING', u.email, 'SYSTEM', 'BASIC-58 existing-account exemption migration'
FROM users u
WHERE u.login_id IN ('admin', 'professor1')
  AND u.email_verified_yn = 'Y'
  AND u.verification_origin = 'EXEMPT_EXISTING'
  AND NOT EXISTS (
      SELECT 1
      FROM email_verification_events existing
      WHERE existing.user_id = u.user_id
        AND existing.event_type = 'EXEMPT_EXISTING'
  );
