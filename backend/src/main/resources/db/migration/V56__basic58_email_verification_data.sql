CREATE TABLE IF NOT EXISTS email_verification_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    event_type varchar(30) NOT NULL CHECK (event_type IN ('EXEMPT_EXISTING','LINK_VERIFIED','RESEND_REQUESTED','TOKEN_REJECTED')),
    occurred_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    token_id bigint,
    normalized_email varchar(320),
    actor_type varchar(30) NOT NULL DEFAULT 'SYSTEM' CHECK (actor_type IN ('SYSTEM','VISITOR','USER')),
    event_reason varchar(500),
    CONSTRAINT fk_email_verification_events_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_email_verification_events_token FOREIGN KEY (token_id) REFERENCES email_verification_tokens(token_id)
);
COMMENT ON TABLE email_verification_events IS '기존 계정 정책 면제와 실제 링크 인증 등 이메일 인증 출처를 append-only로 보존한다.';
COMMENT ON COLUMN email_verification_events.user_id IS 'users.user_id 참조';
