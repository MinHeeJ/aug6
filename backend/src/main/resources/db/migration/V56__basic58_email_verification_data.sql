CREATE TABLE IF NOT EXISTS email_verification_tokens (
    token_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    target_email varchar(320) NOT NULL,
    token_hash varchar(255) NOT NULL,
    issued_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP + interval '24 hours'),
    used_at timestamp,
    status varchar(30) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','USED','EXPIRED','SUPERSEDED')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT uq_email_verification_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_email_verification_tokens_target_email CHECK (length(trim(target_email)) > 0),
    CONSTRAINT ck_email_verification_tokens_used_state CHECK (
        (status = 'USED' AND used_at IS NOT NULL) OR (status <> 'USED' AND used_at IS NULL)
    ),
    CONSTRAINT ck_email_verification_tokens_expiry CHECK (expires_at > issued_at)
);
COMMENT ON TABLE email_verification_tokens IS '회원가입 이메일 인증 토큰의 해시·대상 이메일·만료·일회성 사용 상태를 보존한다.';
COMMENT ON COLUMN email_verification_tokens.user_id IS 'users.user_id 참조';
COMMENT ON COLUMN email_verification_tokens.target_email IS '토큰 발급 시점의 정규화된 대상 이메일. 인증 시 다른 이메일로 전용할 수 없다.';
COMMENT ON COLUMN email_verification_tokens.token_hash IS '원문 토큰은 저장하지 않고 SHA-256 등 서버 해시만 저장한다.';
COMMENT ON COLUMN email_verification_tokens.expires_at IS '발급 시점 + 24시간으로 애플리케이션에서 설정하거나 기본값으로 보정한다.';
COMMENT ON COLUMN email_verification_tokens.status IS 'ACTIVE:활성|USED:사용됨|EXPIRED:만료|SUPERSEDED:대체됨';

