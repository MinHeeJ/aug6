CREATE TABLE IF NOT EXISTS data_access_histories (
    access_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_business varchar(100) NOT NULL,
    viewer_user_id bigint NOT NULL,
    target_scope varchar(1000) NOT NULL,
    access_purpose varchar(500) NOT NULL,
    request_id varchar(100) NOT NULL,
    accessed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_data_access_histories_viewer FOREIGN KEY (viewer_user_id) REFERENCES users(user_id)
);
COMMENT ON TABLE data_access_histories IS '개인정보 및 평가 결과 조회 이력. BASIC-59 FR-024 교과영역 그룹평가 성적 조회 시 조회자와 대상 범위를 보존한다.';
COMMENT ON COLUMN data_access_histories.target_business IS 'COURSE_AREA_GROUP_GRADE:교과영역그룹평가성적목록|COURSE_AREA_GROUP_GRADE_DETAIL:교과영역그룹평가성적상세';
COMMENT ON COLUMN data_access_histories.viewer_user_id IS 'users.user_id 참조 (조회자)';
COMMENT ON COLUMN data_access_histories.target_scope IS '조회 대상 범위 요약. 평가결과 원문값은 저장하지 않는다.';
COMMENT ON COLUMN data_access_histories.access_purpose IS '조회 목적 또는 시스템 업무 맥락.';
COMMENT ON COLUMN data_access_histories.request_id IS '요청 식별자 전 구간 추적을 위해 업무 서비스에서 기록';

CREATE INDEX IF NOT EXISTS idx_data_access_histories_viewer_time
    ON data_access_histories(viewer_user_id, accessed_at DESC);
CREATE INDEX IF NOT EXISTS idx_data_access_histories_target_business
    ON data_access_histories(target_business, accessed_at DESC);
