  );

-- 기존 최대 menu_id 뒤에서 충돌 없이 4개 교육영역 leaf menu를 할당한다.
WITH next_menu AS (
    SELECT COALESCE(MAX(menu_id), 0) AS maximum_menu_id
    FROM menus
),
requested_menus AS (
    SELECT *
    FROM (VALUES
        (1, '강의평가 실적', 61, 'SCR-LECTURE-EVALUATION-ACHIEVEMENT', '/faculty/education/lecture-evaluation-achievements', 'clipboard-check', '교육영역 강의평가 실적 입력과 조회'),
        (2, '강의실적', 62, 'SCR-LECTURE-ACHIEVEMENT', '/faculty/education/lecture-achievements', 'book-open-check', '교육영역 강의실적 입력과 조회'),
        (3, '학생지도 실적', 63, 'SCR-STUDENT-GUIDANCE-ACHIEVEMENT', '/faculty/education/student-guidance-achievements', 'users-round', '교육영역 학생지도 실적 입력과 Excel 일괄등록'),
        (4, '석·박사 배출 실적', 64, 'SCR-DEGREE-COMPLETION-ACHIEVEMENT', '/faculty/education/degree-completion-achievements', 'graduation-cap', '교육영역 석·박사 배출 실적 입력과 조회')
    ) AS requested(menu_sequence, menu_name, display_order, screen_id, url, icon, description)
),
missing_menus AS (
    SELECT requested.*, ROW_NUMBER() OVER (ORDER BY requested.menu_sequence) AS missing_sequence
    FROM requested_menus requested
    WHERE NOT EXISTS (
        SELECT 1
        FROM menus existing_menu
        WHERE existing_menu.screen_id = requested.screen_id
           OR existing_menu.url = requested.url
    )
)
INSERT INTO menus (
    menu_id, parent_menu_id, menu_type, menu_name, display_order, screen_id, url, icon,
    business_category, description, system_use_yn, status, updated_by, change_reason
)
SELECT
    next_menu.maximum_menu_id + missing_menus.missing_sequence,
    300,
    'SCREEN',
    missing_menus.menu_name,
    missing_menus.display_order,
    missing_menus.screen_id,
    missing_menus.url,
    missing_menus.icon,
    'BUSINESS',
    missing_menus.description,
    'Y',
    'ACTIVE',
    1,
    'BASIC-73 교육영역 실적 leaf menu seed'
FROM missing_menus
CROSS JOIN next_menu;

INSERT INTO menu_execution_info (menu_id, screen_id, url, icon, business_category, description, updated_by)
SELECT menu.menu_id, menu.screen_id, menu.url, menu.icon, menu.business_category, menu.description, 1
FROM menus menu
WHERE menu.screen_id IN (
    'SCR-LECTURE-EVALUATION-ACHIEVEMENT',
    'SCR-LECTURE-ACHIEVEMENT',
    'SCR-STUDENT-GUIDANCE-ACHIEVEMENT',
    'SCR-DEGREE-COMPLETION-ACHIEVEMENT'
)
  AND NOT EXISTS (
      SELECT 1 FROM menu_execution_info execution WHERE execution.menu_id = menu.menu_id
  );

INSERT INTO menu_permissions (
    target_type, target_id, menu_id, access_allowed, status, created_by, updated_by, change_reason
)
SELECT 'ROLE', role_seed.role_code, menu.menu_id, 'ALLOW', 'ACTIVE', 1, 1,
       'BASIC-73 교육영역 실적 메뉴 접근'
FROM (VALUES ('R01'), ('R02'), ('R04')) AS role_seed(role_code)
CROSS JOIN (
    SELECT menu_id
    FROM menus
    WHERE screen_id IN (
        'SCR-LECTURE-EVALUATION-ACHIEVEMENT',
        'SCR-LECTURE-ACHIEVEMENT',
        'SCR-STUDENT-GUIDANCE-ACHIEVEMENT',
        'SCR-DEGREE-COMPLETION-ACHIEVEMENT'
    )
) AS menu
WHERE NOT EXISTS (
    SELECT 1
    FROM menu_permissions permission
    WHERE permission.target_type = 'ROLE'
      AND permission.target_id = role_seed.role_code
      AND permission.menu_id = menu.menu_id
);
