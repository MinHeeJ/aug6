    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    CONSTRAINT ck_student_guidance_details_period CHECK (guidance_end_date >= guidance_start_date),
    CONSTRAINT ck_student_guidance_details_count CHECK (student_count > 0),
    CONSTRAINT fk_student_guidance_details_achievement FOREIGN KEY (achievement_id) REFERENCES education_achievements(achievement_id),
    CONSTRAINT fk_student_guidance_details_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_student_guidance_details_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
