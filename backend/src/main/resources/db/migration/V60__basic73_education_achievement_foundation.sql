SELECT menu_base.max_menu_id + menu_seed.display_order, 300, 'SCREEN', menu_seed.menu_name, menu_seed.display_order,
       menu_seed.screen_id, menu_seed.url, menu_seed.icon, 'EDUCATION', menu_seed.description, 'Y', 'ACTIVE', 1,
       'BASIC-73 교육영역 실적 메뉴 seed'
FROM menu_base
CROSS JOIN menu_seed
WHERE NOT EXISTS (SELECT 1 FROM menus existing WHERE existing.screen_id = menu_seed.screen_id);

