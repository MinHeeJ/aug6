COMMENT ON TABLE education_achievement_management_values IS 'FR-018 관리항목 설정에 따라 교육영역 실적별 동적 입력값을 보존한다.';
COMMENT ON COLUMN education_achievement_management_values.value_json IS '동적 관리항목의 구조화 값. EducationAchievementService 저장 시 갱신';

CREATE TABLE IF NOT EXISTS student_guidance_details (
