-- BASIC-73 교육영역 4개 실적의 공통 원장, 상세, 상태·변경이력과 메뉴 기반을 추가한다.
-- 기존 FACULTY_ACHIEVEMENT 상태정의, 변경이력, 역할·권한 테이블을 재사용하며 새 공통 기반은 만들지 않는다.

CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_key varchar(100) NOT NULL UNIQUE,
    achievement_type varchar(50) NOT NULL,
    business_type varchar(50) NOT NULL DEFAULT 'FACULTY_ACHIEVEMENT',
    status_definition_version varchar(30) NOT NULL DEFAULT 'CONFIRMED',
    achievement_status varchar(50) NOT NULL DEFAULT 'DRAFTING',
    evaluation_year varchar(4) NOT NULL,
    owner_user_id bigint NOT NULL,
    organization_code varchar(50),
    management_number varchar(100),
    achievement_title varchar(300) NOT NULL,
    occurred_on date,
    evaluation_confirmed_yn varchar(1) NOT NULL DEFAULT 'N',
    deleted_yn varchar(1) NOT NULL DEFAULT 'N',
    deleted_at timestamp,
    deleted_by bigint,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    change_reason varchar(500),
    CONSTRAINT ck_education_achievements_type CHECK (achievement_type IN ('LECTURE_EVALUATION', 'LECTURE', 'STUDENT_GUIDANCE', 'DEGREE_COMPLETION')),
    CONSTRAINT ck_education_achievements_business_type CHECK (business_type = 'FACULTY_ACHIEVEMENT'),
    CONSTRAINT ck_education_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_education_achievements_confirmed CHECK (evaluation_confirmed_yn IN ('Y', 'N')),
    CONSTRAINT ck_education_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_education_achievements_status FOREIGN KEY (business_type, status_definition_version, achievement_status)
        REFERENCES business_status_codes (business_type, definition_version, status_code),
    CONSTRAINT fk_education_achievements_owner FOREIGN KEY (owner_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_organization FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_education_achievements_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievements IS '교육영역 강의평가·강의·학생지도·석박사 배출 실적의 공통 원장. 상태, 평가확정 잠금, 논리삭제와 감사정보를 보존한다.';
COMMENT ON COLUMN education_achievements.achievement_type IS 'LECTURE_EVALUATION:강의평가|LECTURE:강의실적|STUDENT_GUIDANCE:학생지도|DEGREE_COMPLETION:석박사배출';
COMMENT ON COLUMN education_achievements.business_type IS 'FACULTY_ACHIEVEMENT:교수업적평가 공통 상태코드 연결';
COMMENT ON COLUMN education_achievements.achievement_status IS 'business_status_codes.status_code 참조 (FACULTY_ACHIEVEMENT 상태)';
COMMENT ON COLUMN education_achievements.evaluation_confirmed_yn IS 'Y:평가확정|N:미확정';
COMMENT ON COLUMN education_achievements.deleted_yn IS 'Y:논리삭제|N:정상';

