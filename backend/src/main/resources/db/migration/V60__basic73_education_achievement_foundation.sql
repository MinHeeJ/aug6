CREATE TABLE IF NOT EXISTS education_achievement_status_histories (
    status_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL,
    source_change_history_id bigint,
    business_type varchar(50) NOT NULL DEFAULT 'FACULTY_ACHIEVEMENT',
    status_definition_version varchar(30) NOT NULL DEFAULT 'DRAFT',
    from_status_code varchar(50) NOT NULL,
    to_status_code varchar(50) NOT NULL,
    changed_by bigint NOT NULL,
    changed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT ck_education_status_histories_business_type CHECK (business_type = 'FACULTY_ACHIEVEMENT'),
    CONSTRAINT ck_education_status_histories_not_self CHECK (from_status_code <> to_status_code),
    CONSTRAINT fk_education_status_histories_achievement FOREIGN KEY (achievement_id) REFERENCES education_achievements(achievement_id) ON DELETE RESTRICT,
    CONSTRAINT fk_education_status_histories_source_change FOREIGN KEY (source_change_history_id) REFERENCES data_change_histories(history_id),
    CONSTRAINT fk_education_status_histories_from_status FOREIGN KEY (business_type, status_definition_version, from_status_code)
        REFERENCES business_status_codes(business_type, definition_version, status_code),
    CONSTRAINT fk_education_status_histories_to_status FOREIGN KEY (business_type, status_definition_version, to_status_code)
        REFERENCES business_status_codes(business_type, definition_version, status_code),
    CONSTRAINT fk_education_status_histories_changed_by FOREIGN KEY (changed_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievement_status_histories IS '교육영역 실적의 상태 전후값, 처리자, 처리일시, 사유를 보존하는 append-only 이력. 공통 상태정의와 변경이력에 연결한다.';
COMMENT ON COLUMN education_achievement_status_histories.achievement_id IS 'education_achievements.achievement_id 참조 의도 (상태전이 대상 실적)';
COMMENT ON COLUMN education_achievement_status_histories.source_change_history_id IS 'data_change_histories.history_id 참조 의도 (공통 변경이력 연결)';
COMMENT ON COLUMN education_achievement_status_histories.business_type IS 'FACULTY_ACHIEVEMENT:교수업적평가';
COMMENT ON COLUMN education_achievement_status_histories.status_definition_version IS 'business_status_codes.definition_version 및 business_status_transitions.definition_version 참조 의도 (상태 정의 버전)';

