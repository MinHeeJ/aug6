CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_user_id bigint NOT NULL,
    achievement_type varchar(50) NOT NULL,
    business_type varchar(50) NOT NULL DEFAULT 'FACULTY_ACHIEVEMENT',
    status_definition_version varchar(30) NOT NULL DEFAULT 'DRAFT',
    management_item_code varchar(50) NOT NULL,
    occurrence_date date NOT NULL,
    certification_status varchar(50) NOT NULL DEFAULT 'DRAFTING',
    attachment_token varchar(200),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    deleted_at timestamp,
    deleted_by bigint,
    delete_reason varchar(500),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT ck_education_achievements_type CHECK (achievement_type IN ('LECTURE_EVALUATION', 'LECTURE_ACHIEVEMENT', 'STUDENT_GUIDANCE', 'DEGREE_COMPLETION')),
    CONSTRAINT ck_education_achievements_business_type CHECK (business_type = 'FACULTY_ACHIEVEMENT'),
    CONSTRAINT ck_education_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT ck_education_achievements_deleted_audit CHECK (
        (deleted_yn = 'N' AND deleted_at IS NULL AND deleted_by IS NULL)
        OR (deleted_yn = 'Y' AND deleted_at IS NOT NULL AND deleted_by IS NOT NULL AND delete_reason IS NOT NULL)
    ),
    CONSTRAINT fk_education_achievements_faculty FOREIGN KEY (faculty_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_status FOREIGN KEY (business_type, status_definition_version, certification_status)
        REFERENCES business_status_codes(business_type, definition_version, status_code),
    CONSTRAINT fk_education_achievements_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievements IS '교육영역 4개 실적의 공통 원장. 기존 FACULTY_ACHIEVEMENT 상태정의와 논리삭제·감사 정보를 연결한다.';
COMMENT ON COLUMN education_achievements.achievement_type IS 'LECTURE_EVALUATION:강의평가|LECTURE_ACHIEVEMENT:강의실적|STUDENT_GUIDANCE:학생지도|DEGREE_COMPLETION:석박사배출';
COMMENT ON COLUMN education_achievements.business_type IS 'FACULTY_ACHIEVEMENT:교수업적평가';
COMMENT ON COLUMN education_achievements.status_definition_version IS 'business_status_codes.definition_version 참조 의도 (상태 정의 버전)';
COMMENT ON COLUMN education_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievements.faculty_user_id IS 'users.user_id 참조 의도 (실적 소유 교원)';
COMMENT ON COLUMN education_achievements.management_item_code IS 'evaluation_element_management_item_settings.management_item_code 참조 의도 (FR-018 설정 기반 입력항목)';
COMMENT ON COLUMN education_achievements.attachment_token IS '기존 FileStoragePort 외부 노출용 첨부 식별자 참조 의도 (저장 경로·실제 파일명 미보관)';
COMMENT ON COLUMN education_achievements.deleted_yn IS 'Y:논리삭제|N:정상';
COMMENT ON COLUMN education_achievements.deleted_by IS 'users.user_id 참조 의도 (논리삭제 처리자)';

