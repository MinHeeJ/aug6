-- 신규 leaf menu ID는 실행 시점의 현재 MAX(menu_id) 뒤에서 배정해 기존 메뉴와 충돌하지 않는다.
WITH menu_base AS (
    SELECT COALESCE(MAX(menu_id), 0) AS max_menu_id FROM menus
