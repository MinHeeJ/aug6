INSERT INTO menu_execution_info (menu_id, screen_id, url, icon, business_category, description, updated_by)
SELECT menu.menu_id, menu.screen_id, menu.url, menu.icon, menu.business_category, menu.description, admin_user.user_id
FROM menus menu
CROSS JOIN users admin_user
WHERE menu.screen_id IN ('SCR-LECTURE-EVALUATION-ACHIEVEMENT', 'SCR-LECTURE-PERFORMANCE-ACHIEVEMENT', 'SCR-STUDENT-GUIDANCE-ACHIEVEMENT', 'SCR-GRADUATE-DEGREE-ACHIEVEMENT')
  AND admin_user.login_id = 'admin'
ON CONFLICT (menu_id) DO UPDATE SET screen_id = EXCLUDED.screen_id, url = EXCLUDED.url, icon = EXCLUDED.icon,
    business_category = EXCLUDED.business_category, description = EXCLUDED.description, updated_at = CURRENT_TIMESTAMP;

INSERT INTO menu_permissions (target_type, target_id, menu_id, access_allowed, status, created_by, updated_by, change_reason)
SELECT 'ROLE', role.role_code, menu.menu_id, 'ALLOW', 'ACTIVE', admin_user.user_id, admin_user.user_id,
       'BASIC-74 교육영역 실적 메뉴 접근'
FROM menus menu
CROSS JOIN roles role
CROSS JOIN users admin_user
WHERE menu.screen_id IN ('SCR-LECTURE-EVALUATION-ACHIEVEMENT', 'SCR-LECTURE-PERFORMANCE-ACHIEVEMENT', 'SCR-STUDENT-GUIDANCE-ACHIEVEMENT', 'SCR-GRADUATE-DEGREE-ACHIEVEMENT')
  AND (
      role.role_code IN ('R01', 'R02', 'R04')
      OR (role.role_code = 'R07' AND menu.screen_id = 'SCR-STUDENT-GUIDANCE-ACHIEVEMENT')
  )
  AND admin_user.login_id = 'admin'
ON CONFLICT (target_type, target_id, menu_id) DO UPDATE SET access_allowed = EXCLUDED.access_allowed,
    status = EXCLUDED.status, updated_at = CURRENT_TIMESTAMP, updated_by = EXCLUDED.updated_by,
    change_reason = EXCLUDED.change_reason;
