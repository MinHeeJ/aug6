CREATE TABLE IF NOT EXISTS education_achievements (
    education_achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(50) NOT NULL,
    management_number varchar(100) NOT NULL,
    teacher_user_id bigint NOT NULL,
    management_item_code varchar(100) NOT NULL,
    achievement_date date NOT NULL,
    achievement_name varchar(300) NOT NULL,
    achievement_detail_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(200),
    deleted_yn varchar(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    change_reason varchar(500),
    CONSTRAINT uq_education_achievements_management_number UNIQUE (management_number),
    CONSTRAINT ck_education_achievements_type CHECK (achievement_type IN ('LECTURE_EVALUATION', 'LECTURE_PERFORMANCE', 'STUDENT_GUIDANCE', 'GRADUATE_DEGREE')),
    CONSTRAINT ck_education_achievements_status CHECK (achievement_status IN ('DRAFT', 'SUBMITTED', 'CHAIR_CONFIRMED', 'CHAIR_REJECTED', 'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED')),
    CONSTRAINT ck_education_achievements_deleted_yn CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_education_achievements_teacher FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievements IS 'FR-025~028 교육영역 실적의 공통 원천 데이터와 인증상태, 논리삭제, 감사정보를 보관한다.';
COMMENT ON COLUMN education_achievements.achievement_type IS 'LECTURE_EVALUATION:강의평가|LECTURE_PERFORMANCE:강의실적|STUDENT_GUIDANCE:학생지도|GRADUATE_DEGREE:석박사배출';
COMMENT ON COLUMN education_achievements.teacher_user_id IS 'users.user_id 참조 의도 (실적 소유 교원)';
COMMENT ON COLUMN education_achievements.achievement_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievements.deleted_yn IS 'Y:논리삭제|N:정상';
COMMENT ON COLUMN education_achievements.achievement_detail_json IS '항목별 동적 입력값을 EducationAchievementService 저장 시 기록';

CREATE TABLE IF NOT EXISTS education_achievement_status_histories (
    status_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    education_achievement_id bigint NOT NULL,
    from_status varchar(30),
    to_status varchar(30) NOT NULL,
    processed_by bigint NOT NULL,
    processed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason varchar(500),
    request_id varchar(100),
    CONSTRAINT fk_education_achievement_status_histories_achievement FOREIGN KEY (education_achievement_id) REFERENCES education_achievements(education_achievement_id),
    CONSTRAINT fk_education_achievement_status_histories_processed_by FOREIGN KEY (processed_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievement_status_histories IS '교육영역 실적의 상태 전이별 이전·이후 상태, 처리자, 처리시각, 사유와 요청 식별자를 보관한다.';
COMMENT ON COLUMN education_achievement_status_histories.processed_by IS 'users.user_id 참조 의도 (상태 전이 처리자)';
COMMENT ON COLUMN education_achievement_status_histories.to_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievement_status_histories.request_id IS 'EducationAchievementService 처리 요청의 X-Request-Id 또는 서버 생성 요청 식별자';

CREATE TABLE IF NOT EXISTS student_guidance_achievement_details (
    student_guidance_detail_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    education_achievement_id bigint NOT NULL,
    student_name varchar(100) NOT NULL,
    student_number varchar(50),
    guidance_start_date date NOT NULL,
    guidance_end_date date,
    student_count integer NOT NULL DEFAULT 1,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    CONSTRAINT uq_student_guidance_achievement_details_achievement UNIQUE (education_achievement_id),
    CONSTRAINT ck_student_guidance_achievement_details_dates CHECK (guidance_end_date IS NULL OR guidance_end_date >= guidance_start_date),
    CONSTRAINT ck_student_guidance_achievement_details_count CHECK (student_count > 0),
    CONSTRAINT fk_student_guidance_achievement_details_achievement FOREIGN KEY (education_achievement_id) REFERENCES education_achievements(education_achievement_id),
    CONSTRAINT fk_student_guidance_achievement_details_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_student_guidance_achievement_details_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE student_guidance_achievement_details IS '학생지도 실적의 지도학생, 지도기간, 학생 수 상세정보를 실적 원천과 연결해 보관한다.';
COMMENT ON COLUMN student_guidance_achievement_details.education_achievement_id IS 'education_achievements.education_achievement_id 참조 의도 (학생지도 실적 원천)';

CREATE TABLE IF NOT EXISTS graduate_degree_achievement_students (
    graduate_degree_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    education_achievement_id bigint NOT NULL,
    student_name varchar(100) NOT NULL,
    student_number varchar(50),
    degree_type varchar(20) NOT NULL,
    thesis_title varchar(500),
    degree_awarded_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    CONSTRAINT ck_graduate_degree_achievement_students_type CHECK (degree_type IN ('MASTER', 'DOCTOR')),
    CONSTRAINT fk_graduate_degree_achievement_students_achievement FOREIGN KEY (education_achievement_id) REFERENCES education_achievements(education_achievement_id),
    CONSTRAINT fk_graduate_degree_achievement_students_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_graduate_degree_achievement_students_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE graduate_degree_achievement_students IS '석사·박사 배출 실적의 지도학생, 학위구분, 논문제목과 학위수여일을 보관한다.';
COMMENT ON COLUMN graduate_degree_achievement_students.education_achievement_id IS 'education_achievements.education_achievement_id 참조 의도 (석박사 배출 실적 원천)';
