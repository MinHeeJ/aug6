CREATE TABLE IF NOT EXISTS lecture_evaluation_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_number varchar(50) NOT NULL UNIQUE,
    employee_no varchar(50) NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(200),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    CONSTRAINT ck_lecture_evaluation_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_evaluation_achievements_status CHECK (certification_status IN (
        'DRAFT', 'SUBMITTED', 'CHAIR_CONFIRMED', 'CHAIR_REJECTED',
        'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
    )),
    CONSTRAINT ck_lecture_evaluation_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_lecture_evaluation_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_evaluation_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE lecture_evaluation_achievements IS '교육영역 강의평가 실적 원천. 인증상태와 논리삭제, 입력 및 수정 메타정보를 보존한다.';
COMMENT ON COLUMN lecture_evaluation_achievements.employee_no IS 'korus_personnel_snapshots.employee_no 참조 의도 (FK 미선언)';
COMMENT ON COLUMN lecture_evaluation_achievements.management_item_code IS 'evaluation_element_management_item_settings.management_item_code 참조 의도 (FK 미선언)';
COMMENT ON COLUMN lecture_evaluation_achievements.achievement_detail IS '강의평가 활성 관리항목의 동적 입력값을 애플리케이션에서 기록';
COMMENT ON COLUMN lecture_evaluation_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_evaluation_achievements.attachment_ref IS '기존 FileStoragePort가 발급한 외부 노출용 첨부 식별자';
COMMENT ON COLUMN lecture_evaluation_achievements.deleted_yn IS 'Y:논리삭제|N:정상';

CREATE TABLE IF NOT EXISTS education_achievement_status_histories (
    status_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(30) NOT NULL,
    achievement_id bigint NOT NULL,
    previous_status varchar(30),
    next_status varchar(30) NOT NULL,
    action_type varchar(30) NOT NULL,
    reason_code varchar(50),
    opinion varchar(1000),
    processed_by bigint NOT NULL,
    processed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_education_achievement_status_histories_type CHECK (achievement_type IN (
        'LECTURE_EVALUATION', 'LECTURE', 'STUDENT_GUIDANCE', 'DEGREE_COMPLETION'
    )),
    CONSTRAINT ck_education_achievement_status_histories_status CHECK (
        (previous_status IS NULL OR previous_status IN ('DRAFT', 'SUBMITTED', 'CHAIR_CONFIRMED', 'CHAIR_REJECTED', 'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'))
        AND next_status IN ('DRAFT', 'SUBMITTED', 'CHAIR_CONFIRMED', 'CHAIR_REJECTED', 'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED')
    ),
    CONSTRAINT ck_education_achievement_status_histories_action CHECK (action_type IN (
        'CREATE', 'SUBMIT', 'CHAIR_CONFIRM', 'CHAIR_REJECT', 'CERTIFY', 'CERTIFICATION_REJECT', 'CONFIRM_EVALUATION', 'CANCEL_EVALUATION', 'DELETE'
    )),
    CONSTRAINT ck_education_achievement_status_histories_rejection_reason CHECK (
        next_status NOT IN ('CHAIR_REJECTED', 'CERTIFICATION_REJECTED')
        OR reason_code IS NOT NULL
        OR opinion IS NOT NULL
    ),
    CONSTRAINT fk_education_achievement_status_histories_processed_by FOREIGN KEY (processed_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievement_status_histories IS '교육영역 실적 인증상태 전이 이력. 처리자, 처리일시와 반려 사유 또는 의견을 변경 불가능한 행으로 보존한다.';
COMMENT ON COLUMN education_achievement_status_histories.achievement_type IS 'LECTURE_EVALUATION:강의평가|LECTURE:강의실적|STUDENT_GUIDANCE:학생지도|DEGREE_COMPLETION:석박사배출';
COMMENT ON COLUMN education_achievement_status_histories.achievement_id IS 'achievement_type별 업무 실적 PK 참조 의도 (다형 FK 미선언)';
COMMENT ON COLUMN education_achievement_status_histories.previous_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievement_status_histories.next_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievement_status_histories.action_type IS 'CREATE:등록|SUBMIT:제출|CHAIR_CONFIRM:학과장확인|CHAIR_REJECT:학과장미승인|CERTIFY:인증|CERTIFICATION_REJECT:인증반려|CONFIRM_EVALUATION:평가확정|CANCEL_EVALUATION:평가확정취소|DELETE:삭제';
COMMENT ON COLUMN education_achievement_status_histories.reason_code IS '기존 공통 반려사유 코드 참조 의도 (FK 미선언)';

CREATE INDEX IF NOT EXISTS idx_lecture_evaluation_achievements_lookup
    ON lecture_evaluation_achievements (evaluation_year, employee_no, certification_status, occurred_date DESC)
    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_education_achievement_status_histories_achievement
    ON education_achievement_status_histories (achievement_type, achievement_id, processed_at DESC);

WITH fixture_user AS (
    SELECT user_id
    FROM users
    WHERE login_id = 'admin'
), inserted_achievements AS (
    INSERT INTO lecture_evaluation_achievements (
        achievement_number, employee_no, evaluation_year, management_item_code, occurred_date,
        achievement_detail, certification_status, attachment_ref, deleted_yn, created_by, updated_by
    )
    SELECT fixture.achievement_number, fixture.employee_no, fixture.evaluation_year, fixture.management_item_code,
           fixture.occurred_date, fixture.achievement_detail::jsonb, fixture.certification_status,
           fixture.attachment_ref, 'N', fixture_user.user_id, fixture_user.user_id
    FROM fixture_user
    CROSS JOIN (VALUES
        ('B77-LE-001', 'E1001', '2026', 'EDU_LECTURE_EVALUATION', DATE '2026-03-15', '{"courseName":"교육평가론","score":"4.8"}', 'DRAFT', NULL),
        ('B77-LE-002', 'E1001', '2026', 'EDU_LECTURE_EVALUATION', DATE '2026-04-01', '{"courseName":"교육과정론","score":"4.5"}', 'SUBMITTED', 'b77-le-attachment-002'),
        ('B77-LE-003', 'E1001', '2026', 'EDU_LECTURE_EVALUATION', DATE '2025-12-31', '{"courseName":"교육행정론","score":"4.2"}', 'EVALUATION_CONFIRMED', 'b77-le-attachment-003')
    ) AS fixture(achievement_number, employee_no, evaluation_year, management_item_code, occurred_date, achievement_detail, certification_status, attachment_ref)
    ON CONFLICT (achievement_number) DO UPDATE SET
        employee_no = EXCLUDED.employee_no,
        evaluation_year = EXCLUDED.evaluation_year,
        management_item_code = EXCLUDED.management_item_code,
        occurred_date = EXCLUDED.occurred_date,
        achievement_detail = EXCLUDED.achievement_detail,
        certification_status = EXCLUDED.certification_status,
        attachment_ref = EXCLUDED.attachment_ref,
        deleted_yn = EXCLUDED.deleted_yn,
        updated_at = CURRENT_TIMESTAMP,
        updated_by = EXCLUDED.updated_by
    RETURNING achievement_id, achievement_number, certification_status
)
INSERT INTO education_achievement_status_histories (
    achievement_type, achievement_id, previous_status, next_status, action_type, reason_code, opinion, processed_by
)
SELECT 'LECTURE_EVALUATION', achievement_id,
       CASE achievement_number WHEN 'B77-LE-001' THEN NULL WHEN 'B77-LE-002' THEN 'DRAFT' ELSE 'CERTIFIED' END,
       certification_status,
       CASE achievement_number WHEN 'B77-LE-001' THEN 'CREATE' WHEN 'B77-LE-002' THEN 'SUBMIT' ELSE 'CONFIRM_EVALUATION' END,
       NULL,
       CASE achievement_number WHEN 'B77-LE-001' THEN '강의평가 실적 입력 fixture' WHEN 'B77-LE-002' THEN '제출 fixture' ELSE '평가확정 잠금 fixture' END,
       fixture_user.user_id
FROM inserted_achievements
CROSS JOIN fixture_user
WHERE NOT EXISTS (
    SELECT 1
    FROM education_achievement_status_histories history
    WHERE history.achievement_type = 'LECTURE_EVALUATION'
      AND history.achievement_id = inserted_achievements.achievement_id
      AND history.action_type = CASE inserted_achievements.achievement_number
          WHEN 'B77-LE-001' THEN 'CREATE'
          WHEN 'B77-LE-002' THEN 'SUBMIT'
          ELSE 'CONFIRM_EVALUATION'
      END
);
