       fixture.occurred_date, fixture.achievement_detail::jsonb, fixture.certification_status,
       'N', admin_user.user_id, admin_user.user_id
FROM (VALUES
    ('B77-LE-001', DATE '2026-03-15', '{"fixtureId":"B77-LE-001"}', 'DRAFTING'),
    ('B77-LE-002', DATE '2026-06-20', '{"fixtureId":"B77-LE-002"}', 'SUBMITTED'),
    ('B77-LE-003', DATE '2026-08-31', '{"fixtureId":"B77-LE-003"}', 'CERTIFIED')
) AS fixture(management_item_code, occurred_date, achievement_detail, certification_status)
CROSS JOIN LATERAL (SELECT user_id FROM users WHERE login_id = 'admin' LIMIT 1) admin_user
CROSS JOIN LATERAL (SELECT user_id FROM users WHERE login_id <> 'admin' ORDER BY user_id LIMIT 1) owner_user
CROSS JOIN LATERAL (
    SELECT organization_code
    FROM organization_user_mappings
    WHERE user_id = owner_user.user_id AND status = 'ACTIVE'
    ORDER BY effective_start_date DESC
    LIMIT 1
) owner_org
WHERE NOT EXISTS (
    SELECT 1
    FROM lecture_evaluation_achievements existing
    WHERE existing.management_item_code = fixture.management_item_code
      AND existing.evaluation_year = '2026'
);

