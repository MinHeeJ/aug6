CREATE TABLE IF NOT EXISTS lecture_evaluation_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(100) NOT NULL,
    teacher_user_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    organization_code varchar(50),
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(50) NOT NULL DEFAULT 'DRAFTING',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    deleted_at timestamp,
    deleted_by bigint,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_lecture_evaluation_achievements_management_no UNIQUE (management_no),
    CONSTRAINT ck_lecture_evaluation_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_evaluation_achievements_status CHECK (
        certification_status IN (
            'DRAFTING',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_RETURNED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )
    ),
    CONSTRAINT ck_lecture_evaluation_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_lecture_evaluation_achievements_teacher FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_evaluation_achievements_organization FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_lecture_evaluation_achievements_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_evaluation_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_evaluation_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE lecture_evaluation_achievements IS '교육영역 강의평가 실적의 원천과 인증상태, 논리삭제 및 입력·수정 메타정보를 보존한다.';
COMMENT ON COLUMN lecture_evaluation_achievements.teacher_user_id IS 'users.user_id 참조 의도 (실적 입력 교원)';
COMMENT ON COLUMN lecture_evaluation_achievements.organization_code IS 'organizations.organization_code 참조 의도 (실적 소속 조직)';
COMMENT ON COLUMN lecture_evaluation_achievements.achievement_detail IS 'FR-018 활성 관리항목의 동적 상세값을 저장한다.';
COMMENT ON COLUMN lecture_evaluation_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_evaluation_achievements.attachment_ref IS '기존 FileStoragePort 첨부 참조값이며 물리 저장 경로와 실제 파일명은 저장하지 않음';
COMMENT ON COLUMN lecture_evaluation_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN lecture_evaluation_achievements.deleted_by IS 'users.user_id 참조 의도 (논리삭제 처리자)';
COMMENT ON COLUMN lecture_evaluation_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN lecture_evaluation_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_lecture_evaluation_achievements_search
    ON lecture_evaluation_achievements(
        evaluation_year,
        organization_code,
        teacher_user_id,
        management_item_code,
        certification_status,
        occurred_date DESC
    );
CREATE INDEX IF NOT EXISTS idx_lecture_evaluation_achievements_active_management
    ON lecture_evaluation_achievements(management_no)
    WHERE deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS education_achievement_status_histories (
    status_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(50) NOT NULL,
    achievement_id bigint NOT NULL,
    previous_status varchar(50) NOT NULL,
    next_status varchar(50) NOT NULL,
    action_type varchar(50) NOT NULL,
    reason_code varchar(100),
    opinion varchar(1000),
    processed_by bigint NOT NULL,
    processed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    CONSTRAINT ck_education_achievement_status_histories_type CHECK (
        achievement_type IN ('LECTURE_EVALUATION', 'LECTURE', 'STUDENT_GUIDANCE', 'DEGREE_COMPLETION')
    ),
    CONSTRAINT ck_education_achievement_status_histories_previous_status CHECK (
        previous_status IN (
            'DRAFTING',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_RETURNED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )
    ),
    CONSTRAINT ck_education_achievement_status_histories_next_status CHECK (
        next_status IN (
            'DRAFTING',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_RETURNED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )
    ),
    CONSTRAINT ck_education_achievement_status_histories_not_self CHECK (previous_status <> next_status),
    CONSTRAINT ck_education_achievement_status_histories_rejection_reason CHECK (
        next_status NOT IN ('DEPARTMENT_REJECTED', 'CERTIFICATION_RETURNED')
        OR reason_code IS NOT NULL
        OR opinion IS NOT NULL
    ),
    CONSTRAINT fk_education_achievement_status_histories_processed_by FOREIGN KEY (processed_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievement_status_histories_created_by FOREIGN KEY (created_by) REFERENCES users(user_id)
);
COMMENT ON TABLE education_achievement_status_histories IS '교육영역 실적의 허용 상태 전이와 처리자, 처리일시, 반려사유 및 의견을 변경 불가 이력으로 보존한다.';
COMMENT ON COLUMN education_achievement_status_histories.achievement_type IS 'LECTURE_EVALUATION:강의평가|LECTURE:강의실적|STUDENT_GUIDANCE:학생지도|DEGREE_COMPLETION:석박사배출';
COMMENT ON COLUMN education_achievement_status_histories.achievement_id IS '각 교육영역 실적 header의 achievement_id 참조 의도 (다형 참조이므로 FK 미선언)';
COMMENT ON COLUMN education_achievement_status_histories.previous_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievement_status_histories.next_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievement_status_histories.action_type IS 'SUBMIT:제출|CONFIRM:확인또는확정|REJECT:반려|RETURN:인증반려|CANCEL:취소';
COMMENT ON COLUMN education_achievement_status_histories.processed_by IS 'users.user_id 참조 의도 (상태 전이 처리자)';
COMMENT ON COLUMN education_achievement_status_histories.created_by IS 'users.user_id 참조 의도 (이력 기록 생성자)';

CREATE INDEX IF NOT EXISTS idx_education_achievement_status_histories_target
    ON education_achievement_status_histories(achievement_type, achievement_id, processed_at DESC);
CREATE INDEX IF NOT EXISTS idx_education_achievement_status_histories_processed
    ON education_achievement_status_histories(processed_by, processed_at DESC);

