CREATE TABLE IF NOT EXISTS lecture_evaluation_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    target_user_id bigint NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFTING',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_lecture_evaluation_achievements_year
        CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_evaluation_achievements_status
        CHECK (certification_status IN (
            'DRAFTING',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_RETURNED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )),
    CONSTRAINT ck_lecture_evaluation_achievements_deleted
        CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_lecture_evaluation_achievements_target_user
        FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_evaluation_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_evaluation_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE lecture_evaluation_achievements IS 'FR-025 교육영역 강의평가 실적 원천. 평가확정 대상은 수정 또는 삭제하지 않고 상태와 이력을 보존한다.';
COMMENT ON COLUMN lecture_evaluation_achievements.target_user_id IS 'users.user_id 참조 의도 (실적 귀속 교원)';
COMMENT ON COLUMN lecture_evaluation_achievements.management_item_code IS 'evaluation_element_management_item_settings의 활성 관리항목 코드 참조 의도 (규정버전별 FK 미선언)';
COMMENT ON COLUMN lecture_evaluation_achievements.achievement_detail IS 'FR-018 활성 설정에 따라 입력되는 강의평가 세부값';
COMMENT ON COLUMN lecture_evaluation_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_evaluation_achievements.attachment_ref IS '기존 FileStoragePort가 발급한 외부 비노출 첨부 참조값';
COMMENT ON COLUMN lecture_evaluation_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN lecture_evaluation_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN lecture_evaluation_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE TABLE IF NOT EXISTS education_achievement_status_histories (
