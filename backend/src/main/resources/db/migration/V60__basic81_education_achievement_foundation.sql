    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_education_achievement_status_histories_type
        CHECK (achievement_type IN (
            'LECTURE_EVALUATION',
            'LECTURE',
            'STUDENT_GUIDANCE',
            'DEGREE_COMPLETION'
        )),
    CONSTRAINT ck_education_achievement_status_histories_previous_status
        CHECK (previous_status IS NULL OR previous_status IN (
            'DRAFTING',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_RETURNED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )),
    CONSTRAINT ck_education_achievement_status_histories_next_status
        CHECK (next_status IN (
            'DRAFTING',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_RETURNED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )),
    CONSTRAINT ck_education_achievement_status_histories_action_type
        CHECK (action_type IN (
            'CREATE',
            'SUBMIT',
            'DEPARTMENT_CONFIRM',
            'DEPARTMENT_REJECT',
            'CERTIFY',
            'CERTIFICATION_RETURN',
            'EVALUATION_CONFIRM',
            'EVALUATION_CANCEL',
            'DELETE'
        )),
    CONSTRAINT fk_education_achievement_status_histories_processed_by
        FOREIGN KEY (processed_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievement_status_histories_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievement_status_histories_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
