CREATE INDEX IF NOT EXISTS idx_lecture_evaluation_achievements_search
    ON lecture_evaluation_achievements(
        evaluation_year,
        target_user_id,
        management_item_code,
        certification_status,
        occurred_date DESC
    )
    WHERE deleted_yn = 'N';
