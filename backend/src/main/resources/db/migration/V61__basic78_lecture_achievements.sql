    management_no, evaluation_year, teacher_user_id, teacher_name, management_item_code,
    occurred_date, achievement_detail, certification_status, attachment_ref, deleted_yn,
    created_by, updated_by, change_reason
)
SELECT fixture.management_no, fixture.evaluation_year, professor.user_id, professor_snapshot.name,
       fixture.management_item_code, fixture.occurred_date, fixture.achievement_detail::jsonb,
       fixture.certification_status, fixture.attachment_ref, 'N', administrator.user_id,
       administrator.user_id, fixture.change_reason
FROM (VALUES
    ('B77-LA-001-NORMAL', '2026', 'EDU-LECTURE', DATE '2026-03-15', '{"courseName":"교육학개론","credit":3}', 'DRAFTING', NULL, 'B77-LA-001 정상 작성중 강의실적 fixture'),
    ('B77-LA-001-WARNING', '2026', 'EDU-LECTURE', DATE '2025-12-31', '{"courseName":"교육학개론","credit":3}', 'SUBMITTED', NULL, 'B77-LA-001 평가기간 경계 경고 강의실적 fixture'),
    ('B77-LA-001-CONFIRMED', '2026', 'EDU-LECTURE', DATE '2026-06-30', '{"courseName":"교육학개론","credit":3}', 'EVALUATION_CONFIRMED', 'file-ref-b77-la-confirmed', 'B77-LA-001 평가확정 잠금 강의실적 fixture')
) AS fixture(management_no, evaluation_year, management_item_code, occurred_date, achievement_detail, certification_status, attachment_ref, change_reason)
JOIN users professor ON professor.login_id = 'professor1'
JOIN korus_personnel_snapshots professor_snapshot ON professor_snapshot.employee_no = professor.employee_no
JOIN users administrator ON administrator.login_id = 'admin'
ON CONFLICT (management_no) DO NOTHING;

INSERT INTO education_achievement_status_histories (
    achievement_type, achievement_id, previous_status, next_status, action_type, opinion, processed_by
)
SELECT 'LECTURE', achievement.achievement_id, NULL, achievement.certification_status, 'CREATE',
       'B77-LA-001 초기 상태 fixture', administrator.user_id
FROM lecture_achievements achievement
JOIN users administrator ON administrator.login_id = 'admin'
WHERE achievement.management_no LIKE 'B77-LA-001-%'
  AND NOT EXISTS (
      SELECT 1 FROM education_achievement_status_histories history
      WHERE history.achievement_type = 'LECTURE'
        AND history.achievement_id = achievement.achievement_id
        AND history.action_type = 'CREATE'
  );

INSERT INTO data_change_histories (
    target_business, target_key, change_type, field_name, before_value, after_value,
    changed_by, change_reason
)
SELECT 'lecture_achievements', achievement.achievement_id::text, 'CREATE',
       'certification_status', NULL, achievement.certification_status, administrator.user_id,
       'B77-LA-001 초기 변경 이력 fixture'
FROM lecture_achievements achievement
JOIN users administrator ON administrator.login_id = 'admin'
WHERE achievement.management_no LIKE 'B77-LA-001-%'
  AND NOT EXISTS (
      SELECT 1 FROM data_change_histories history
      WHERE history.target_business = 'lecture_achievements'
        AND history.target_key = achievement.achievement_id::text
        AND history.change_type = 'CREATE'
  );
