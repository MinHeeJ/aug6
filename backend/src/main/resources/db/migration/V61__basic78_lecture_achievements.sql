CREATE TABLE IF NOT EXISTS lecture_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL UNIQUE,
    evaluation_year varchar(4) NOT NULL,
    teacher_user_id bigint NOT NULL,
    teacher_name varchar(100) NOT NULL,
    management_item_code varchar(100) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFTING',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    change_reason varchar(500),
    CONSTRAINT ck_lecture_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_achievements_status CHECK (certification_status IN ('DRAFTING', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED', 'CERTIFIED', 'CERTIFICATION_RETURNED', 'EVALUATION_CONFIRMED', 'DELETED')),
    CONSTRAINT ck_lecture_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_lecture_achievements_teacher FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE lecture_achievements IS '교육영역 강의실적의 원천 데이터. 상태, 논리삭제, 생성·수정 메타정보와 동적 세부값을 보존한다.';
COMMENT ON COLUMN lecture_achievements.teacher_user_id IS 'users.user_id 참조 의도 (강의실적 소유 교원)';
COMMENT ON COLUMN lecture_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN lecture_achievements.achievement_detail IS 'FR-018 활성 관리항목 정의에 따라 애플리케이션이 저장하는 동적 세부 입력값';
COMMENT ON COLUMN lecture_achievements.attachment_ref IS '기존 FileStoragePort 참조값 (실제 저장 경로와 파일명은 외부에 노출하지 않음)';

CREATE INDEX IF NOT EXISTS idx_lecture_achievements_search
    ON lecture_achievements(evaluation_year, teacher_user_id, management_item_code, occurred_date DESC)
    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_lecture_achievements_status
    ON lecture_achievements(certification_status, updated_at DESC)
    WHERE deleted_yn = 'N';

