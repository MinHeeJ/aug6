CREATE TABLE IF NOT EXISTS lecture_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    owner_user_id bigint NOT NULL,
    organization_code varchar(50) NOT NULL,
    management_item_code varchar(100) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(50) NOT NULL DEFAULT 'DRAFTING',
    attachment_ref varchar(300),
    deleted_yn varchar(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    CONSTRAINT ck_lecture_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_achievements_status CHECK (certification_status IN ('DRAFTING','SUBMITTED','DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED','CERTIFIED','CERTIFICATION_RETURNED','EVALUATION_CONFIRMED','DELETED')),
    CONSTRAINT ck_lecture_achievements_deleted CHECK (deleted_yn IN ('Y','N')),
    CONSTRAINT fk_lecture_achievements_owner FOREIGN KEY (owner_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_organization FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_lecture_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE lecture_achievements IS 'BASIC-79 강의실적 원천 실적과 인증상태를 보존하는 업무 테이블.';
COMMENT ON COLUMN lecture_achievements.owner_user_id IS 'users.user_id 참조 의도 (강의실적 소유 교원)';
COMMENT ON COLUMN lecture_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_achievements.attachment_ref IS '기존 FileStoragePort 또는 첨부 서비스의 비공개 참조값';
COMMENT ON COLUMN lecture_achievements.deleted_yn IS 'Y:논리삭제|N:정상';
COMMENT ON COLUMN lecture_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN lecture_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_lecture_achievements_list
    ON lecture_achievements(evaluation_year, owner_user_id, organization_code, certification_status, occurred_date DESC)
    WHERE deleted_yn = 'N';

