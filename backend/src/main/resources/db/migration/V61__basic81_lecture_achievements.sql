CREATE TABLE IF NOT EXISTS lecture_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL UNIQUE,
    evaluation_year varchar(4) NOT NULL,
    organization_code varchar(50) NOT NULL,
    teacher_user_id bigint NOT NULL,
    management_item_code varchar(100) NOT NULL,
    achievement_date date NOT NULL,
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFTING',
    detail_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    attachment_count integer NOT NULL DEFAULT 0,
    occurrence_date_warning_yn varchar(1) NOT NULL DEFAULT 'N',
    deleted_at timestamp,
    deleted_by bigint,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL,
    change_reason varchar(500) NOT NULL,
    CONSTRAINT ck_lecture_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_achievements_status CHECK (achievement_status IN ('DRAFTING','SUBMITTED','DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED','CERTIFIED','CERTIFICATION_RETURNED','EVALUATION_CONFIRMED','DELETED')),
    CONSTRAINT ck_lecture_achievements_attachment_count CHECK (attachment_count >= 0),
    CONSTRAINT ck_lecture_achievements_warning CHECK (occurrence_date_warning_yn IN ('Y','N')),
    CONSTRAINT fk_lecture_achievements_organization FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_lecture_achievements_teacher FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id)
);
COMMENT ON TABLE lecture_achievements IS '교육영역 강의실적의 원천, 인증상태 및 논리삭제 정보를 보존한다.';
COMMENT ON COLUMN lecture_achievements.management_item_code IS 'evaluation_element_management_item_settings의 활성 관리항목 코드 참조 의도 (FK 미선언)';
COMMENT ON COLUMN lecture_achievements.achievement_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_achievements.detail_payload IS 'FR-018 활성 관리항목 설정에 따라 애플리케이션이 검증·저장하는 유형별 상세값';
COMMENT ON COLUMN lecture_achievements.occurrence_date_warning_yn IS 'Y:평가대상 기간 밖 발생일 경고|N:경고없음';
COMMENT ON COLUMN lecture_achievements.deleted_by IS 'users.user_id 참조 의도 (논리삭제 처리자)';

CREATE INDEX IF NOT EXISTS idx_lecture_achievements_list
    ON lecture_achievements (evaluation_year, organization_code, teacher_user_id, achievement_status, achievement_date DESC)
    WHERE deleted_at IS NULL;

