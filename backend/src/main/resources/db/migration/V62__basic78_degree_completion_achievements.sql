WHERE achievement.management_no LIKE 'B77-DC-001-%' AND NOT EXISTS (SELECT 1 FROM education_achievement_status_histories history WHERE history.achievement_type = 'DEGREE_COMPLETION' AND history.achievement_id = achievement.achievement_id AND history.action_type = 'CREATE');

INSERT INTO data_change_histories (target_business, target_key, change_type, field_name, before_value, after_value, changed_by, change_reason)
