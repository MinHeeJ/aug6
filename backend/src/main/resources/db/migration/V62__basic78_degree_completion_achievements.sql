    ('B77-DC-001-WARNING', '2026', 'EDU-DEGREE-COMPLETION', DATE '2025-12-31', 'SUBMITTED', NULL, 'B77-DC-001 평가기간 경계 석박사 배출 fixture'),
    ('B77-DC-001-CONFIRMED', '2026', 'EDU-DEGREE-COMPLETION', DATE '2026-06-30', 'EVALUATION_CONFIRMED', 'file-ref-b77-dc-confirmed', 'B77-DC-001 평가확정 잠금 석박사 배출 fixture')
) AS fixture(management_no, evaluation_year, management_item_code, occurred_date, certification_status, attachment_ref, change_reason)
JOIN users professor ON professor.login_id = 'professor1'
JOIN korus_personnel_snapshots snapshot ON snapshot.employee_no = professor.employee_no
JOIN users administrator ON administrator.login_id = 'admin'
ON CONFLICT (management_no) DO NOTHING;

INSERT INTO degree_completion_students (achievement_id, degree_type, student_name, thesis_title, degree_awarded_date, created_by, updated_by)
SELECT achievement.achievement_id, fixture.degree_type, fixture.student_name, fixture.thesis_title, fixture.degree_awarded_date, administrator.user_id, administrator.user_id
FROM (VALUES
    ('B77-DC-001-NORMAL', 'MASTER', '김학생', '교육 평가 연구', DATE '2026-02-20'),
    ('B77-DC-001-WARNING', 'DOCTOR', '이학생', '교수학습 분석', DATE '2025-12-31'),
    ('B77-DC-001-CONFIRMED', 'MASTER', '박학생', '교육 정책 연구', DATE '2026-06-30')
) AS fixture(management_no, degree_type, student_name, thesis_title, degree_awarded_date)
JOIN degree_completion_achievements achievement ON achievement.management_no = fixture.management_no
JOIN users administrator ON administrator.login_id = 'admin'
WHERE NOT EXISTS (SELECT 1 FROM degree_completion_students student WHERE student.achievement_id = achievement.achievement_id);

INSERT INTO education_achievement_status_histories (achievement_type, achievement_id, next_status, action_type, opinion, processed_by)
SELECT 'DEGREE_COMPLETION', achievement.achievement_id, achievement.certification_status, 'CREATE', 'B77-DC-001 초기 상태 fixture', administrator.user_id
