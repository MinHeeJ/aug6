CREATE TABLE IF NOT EXISTS degree_completion_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL UNIQUE,
    evaluation_year varchar(4) NOT NULL,
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    teacher_name varchar(100) NOT NULL,
    management_item_code varchar(100) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFTING',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL REFERENCES users(user_id),
    change_reason varchar(500),
    CONSTRAINT ck_degree_completion_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_degree_completion_achievements_status CHECK (certification_status IN ('DRAFTING', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED', 'CERTIFIED', 'CERTIFICATION_RETURNED', 'EVALUATION_CONFIRMED', 'DELETED')),
    CONSTRAINT ck_degree_completion_achievements_deleted CHECK (deleted_yn IN ('Y', 'N'))
);
COMMENT ON TABLE degree_completion_achievements IS '교육영역 석·박사 배출 실적의 헤더 원천 데이터. 지도학생 상세와 상태·감사 메타정보를 보존한다.';
COMMENT ON COLUMN degree_completion_achievements.teacher_user_id IS 'users.user_id 참조 의도 (석·박사 배출 실적 소유 교원)';
COMMENT ON COLUMN degree_completion_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN degree_completion_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN degree_completion_achievements.achievement_detail IS 'FR-018 활성 관리항목 정의에 따라 애플리케이션이 저장하는 동적 세부 입력값';
COMMENT ON COLUMN degree_completion_achievements.attachment_ref IS '기존 FileStoragePort 참조값 (실제 저장 경로와 파일명은 외부에 노출하지 않음)';

CREATE TABLE IF NOT EXISTS degree_completion_students (
    degree_completion_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL REFERENCES degree_completion_achievements(achievement_id),
    degree_type varchar(20) NOT NULL,
    student_name varchar(100) NOT NULL,
    thesis_title varchar(1000) NOT NULL,
    degree_awarded_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL REFERENCES users(user_id),
    CONSTRAINT ck_degree_completion_students_type CHECK (degree_type IN ('MASTER', 'DOCTOR'))
);
COMMENT ON TABLE degree_completion_students IS '석·박사 배출 실적에 연결되는 지도학생별 학위·논문·수여일 상세 데이터.';
COMMENT ON COLUMN degree_completion_students.achievement_id IS 'degree_completion_achievements.achievement_id 참조';
COMMENT ON COLUMN degree_completion_students.degree_type IS 'MASTER:석사|DOCTOR:박사';

CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_search ON degree_completion_achievements(evaluation_year, teacher_user_id, management_item_code, occurred_date DESC) WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_degree_completion_students_achievement ON degree_completion_students(achievement_id, degree_completion_student_id);

