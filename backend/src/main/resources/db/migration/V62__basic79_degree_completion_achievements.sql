CREATE TABLE IF NOT EXISTS degree_completion_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(100) NOT NULL,
    teacher_user_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    organization_code varchar(50) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(50) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    change_reason varchar(500),
    CONSTRAINT uq_degree_completion_achievements_management_no UNIQUE (management_no),
    CONSTRAINT ck_degree_completion_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_degree_completion_achievements_status CHECK (certification_status IN ('DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED', 'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED')),
    CONSTRAINT ck_degree_completion_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_degree_completion_achievements_teacher FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_degree_completion_achievements_organization FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_degree_completion_achievements_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_degree_completion_achievements_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE degree_completion_achievements IS 'BASIC-79 석·박사 배출 실적 헤더를 논리 삭제와 생성·수정 메타정보로 보존한다.';
COMMENT ON COLUMN degree_completion_achievements.teacher_user_id IS 'users.user_id 참조 의도 (실적 대상 교원)';
COMMENT ON COLUMN degree_completion_achievements.organization_code IS 'organizations.organization_code 참조 의도 (실적 대상 소속)';
COMMENT ON COLUMN degree_completion_achievements.achievement_detail IS 'FR-018 활성 관리항목 기준의 가변 석·박사 배출 상세값';
COMMENT ON COLUMN degree_completion_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN degree_completion_achievements.attachment_ref IS 'FileStoragePort가 발급한 외부 비노출 첨부 참조값';
COMMENT ON COLUMN degree_completion_achievements.deleted_yn IS 'Y:논리삭제|N:정상';
COMMENT ON COLUMN degree_completion_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN degree_completion_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE TABLE IF NOT EXISTS degree_completion_students (
    degree_completion_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL,
    degree_type varchar(20) NOT NULL,
    student_name varchar(200) NOT NULL,
    thesis_title varchar(1000),
    degree_awarded_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_degree_completion_students_degree_type CHECK (degree_type IN ('MASTER', 'DOCTORAL')),
    CONSTRAINT fk_degree_completion_students_achievement FOREIGN KEY (achievement_id) REFERENCES degree_completion_achievements(achievement_id),
    CONSTRAINT fk_degree_completion_students_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_degree_completion_students_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE degree_completion_students IS '석·박사 배출 실적에 속한 지도학생과 학위 수여 정보를 보존한다.';
COMMENT ON COLUMN degree_completion_students.achievement_id IS 'degree_completion_achievements.achievement_id 참조 의도';
COMMENT ON COLUMN degree_completion_students.degree_type IS 'MASTER:석사|DOCTORAL:박사';
COMMENT ON COLUMN degree_completion_students.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN degree_completion_students.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_search
    ON degree_completion_achievements (evaluation_year, organization_code, teacher_user_id, certification_status, occurred_date DESC);
CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_management_item
    ON degree_completion_achievements (management_item_code, deleted_yn);
CREATE INDEX IF NOT EXISTS idx_degree_completion_students_achievement
    ON degree_completion_students (achievement_id, degree_awarded_date DESC, degree_completion_student_id DESC);

