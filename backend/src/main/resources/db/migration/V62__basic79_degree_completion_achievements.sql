INSERT INTO degree_completion_students (
    achievement_id, degree_type, student_name, thesis_title, degree_awarded_date, created_by, updated_by
)
SELECT fixture.achievement_id, fixture.degree_type, fixture.student_name, fixture.thesis_title,
       fixture.degree_awarded_date, administrator.user_id, administrator.user_id
FROM users administrator
CROSS JOIN (
    VALUES
        (792001::bigint, 'MASTER', '학생가', '교원 역량 개발 연구', DATE '2026-08-20'),
        (792002::bigint, 'DOCTORAL', '학생나', '교육정책 분석 연구', DATE '2026-02-28'),
        (792003::bigint, 'MASTER', '학생다', '수학교육 평가 연구', DATE '2026-08-25')
) AS fixture(achievement_id, degree_type, student_name, thesis_title, degree_awarded_date)
WHERE administrator.login_id = 'admin'
  AND NOT EXISTS (
      SELECT 1
      FROM degree_completion_students existing_student
      WHERE existing_student.achievement_id = fixture.achievement_id
        AND existing_student.student_name = fixture.student_name
        AND existing_student.degree_type = fixture.degree_type
  );

SELECT setval(
    pg_get_serial_sequence('degree_completion_achievements', 'achievement_id'),
    COALESCE((SELECT MAX(achievement_id) FROM degree_completion_achievements), 1),
    true
);
