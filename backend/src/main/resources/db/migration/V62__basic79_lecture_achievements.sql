COMMENT ON COLUMN lecture_achievements.deleted_by IS 'users.user_id 참조 의도 (논리삭제 처리자)';

CREATE INDEX IF NOT EXISTS idx_lecture_achievements_search
    ON lecture_achievements (
        evaluation_year,
        teacher_user_id,
        organization_code,
        management_item_code,
        occurred_date DESC
    )
    WHERE deleted_yn = 'N';

CREATE INDEX IF NOT EXISTS idx_lecture_achievements_status
    ON lecture_achievements (certification_status, updated_at DESC)
    WHERE deleted_yn = 'N';

