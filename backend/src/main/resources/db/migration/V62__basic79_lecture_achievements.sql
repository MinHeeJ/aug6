-- BASIC-79 강의실적 원천·조회 성능·메뉴 권한을 기존 교육영역 기반 위에 추가한다.
CREATE TABLE IF NOT EXISTS lecture_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    teacher_user_id bigint NOT NULL,
    organization_code varchar(50),
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    deleted_at timestamp,
    deleted_by bigint,
    delete_reason varchar(500),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_lecture_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_lecture_achievements_status CHECK (certification_status IN (
        'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
        'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
    )),
    CONSTRAINT ck_lecture_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT ck_lecture_achievements_delete_state
        CHECK (deleted_yn = 'N' OR certification_status = 'DELETED'),
    CONSTRAINT fk_lecture_achievements_teacher
        FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_organization
        FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
    CONSTRAINT fk_lecture_achievements_deleted_by
        FOREIGN KEY (deleted_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_lecture_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

COMMENT ON TABLE lecture_achievements IS 'FR-026 교육영역 강의실적 원천. 교원별 입력값, 인증 상태, 논리삭제와 변경 추적의 기준을 보존한다.';
COMMENT ON COLUMN lecture_achievements.teacher_user_id IS 'users.user_id 참조 의도 (실적 소유 교원 및 데이터 범위 판단)';
COMMENT ON COLUMN lecture_achievements.organization_code IS 'organizations.organization_code 참조 의도 (소속 기반 데이터 범위 판단)';
COMMENT ON COLUMN lecture_achievements.management_item_code IS 'evaluation_management_items.management_item_code 참조 의도 (활성 관리항목 검증)';
COMMENT ON COLUMN lecture_achievements.achievement_detail IS 'FR-018에서 결정되는 동적 입력 항목을 저장하는 JSONB 원천값';
COMMENT ON COLUMN lecture_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN lecture_achievements.attachment_ref IS 'FileStoragePort가 발급한 외부 비노출 첨부 참조값';
