INSERT INTO education_achievement_status_histories (
    achievement_type,
    achievement_id,
    previous_status,
    next_status,
    action_type,
    processed_by,
    created_by,
    updated_by
)
SELECT
    'LECTURE',
    achievement.achievement_id,
    CASE achievement.certification_status
        WHEN 'DRAFT' THEN NULL
        WHEN 'SUBMITTED' THEN 'DRAFT'
        ELSE 'CERTIFIED'
    END,
    achievement.certification_status,
    CASE achievement.certification_status
        WHEN 'DRAFT' THEN 'CREATE'
        WHEN 'SUBMITTED' THEN 'SUBMIT'
        ELSE 'CONFIRM_EVALUATION'
    END,
    admin.user_id,
    admin.user_id,
    admin.user_id
FROM lecture_achievements achievement
CROSS JOIN users admin
WHERE achievement.achievement_id IN (790101, 790102, 790103)
  AND admin.login_id = 'admin'
  AND NOT EXISTS (
      SELECT 1
      FROM education_achievement_status_histories history
      WHERE history.achievement_type = 'LECTURE'
        AND history.achievement_id = achievement.achievement_id
        AND history.next_status = achievement.certification_status
  );

