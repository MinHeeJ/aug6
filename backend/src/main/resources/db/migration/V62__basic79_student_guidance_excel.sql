CREATE TABLE IF NOT EXISTS student_guidance_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    owner_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) NOT NULL REFERENCES organizations(organization_code),
    management_item_code varchar(100) NOT NULL,
    guidance_start_date date NOT NULL,
    guidance_end_date date NOT NULL,
    student_count integer NOT NULL DEFAULT 0,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(50) NOT NULL DEFAULT 'DRAFTING',
    attachment_ref varchar(300),
    deleted_yn varchar(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL REFERENCES users(user_id),
    CONSTRAINT ck_student_guidance_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_student_guidance_achievements_dates CHECK (guidance_end_date >= guidance_start_date),
    CONSTRAINT ck_student_guidance_achievements_student_count CHECK (student_count >= 0),
    CONSTRAINT ck_student_guidance_achievements_status CHECK (certification_status IN ('DRAFTING','SUBMITTED','DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED','CERTIFIED','CERTIFICATION_RETURNED','EVALUATION_CONFIRMED','DELETED')),
    CONSTRAINT ck_student_guidance_achievements_deleted CHECK (deleted_yn IN ('Y','N'))
);
COMMENT ON TABLE student_guidance_achievements IS 'FR-027 학생지도 실적의 지도기간, 학생수, 인증상태를 보존하는 업무 헤더 테이블.';
COMMENT ON COLUMN student_guidance_achievements.owner_user_id IS 'users.user_id 참조 의도 (학생지도 실적 소유 교원)';
COMMENT ON COLUMN student_guidance_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN student_guidance_achievements.attachment_ref IS '기존 FileStoragePort 또는 첨부 서비스의 비공개 참조값';
COMMENT ON COLUMN student_guidance_achievements.deleted_yn IS 'Y:논리삭제|N:정상';
COMMENT ON COLUMN student_guidance_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN student_guidance_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE TABLE IF NOT EXISTS student_guidance_students (
    student_guidance_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL REFERENCES student_guidance_achievements(achievement_id),
    student_name varchar(100) NOT NULL,
    student_detail_jsonb jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL REFERENCES users(user_id),
    CONSTRAINT uq_student_guidance_students_name UNIQUE (achievement_id, student_name)
);
COMMENT ON TABLE student_guidance_students IS '학생지도 실적에 연결된 지도학생 반복 상세를 보존하는 업무 테이블.';
COMMENT ON COLUMN student_guidance_students.achievement_id IS 'student_guidance_achievements.achievement_id 참조 의도 (학생지도 실적 헤더)';
COMMENT ON COLUMN student_guidance_students.student_detail_jsonb IS 'StudentGuidanceAchievementService 저장 시 기존 개인정보 계약상 허용된 학생 상세만 갱신';
COMMENT ON COLUMN student_guidance_students.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN student_guidance_students.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_student_guidance_achievements_list ON student_guidance_achievements (evaluation_year, owner_user_id, organization_code, certification_status, guidance_start_date DESC) WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_student_guidance_students_achievement ON student_guidance_students (achievement_id, student_name);

