CREATE TABLE IF NOT EXISTS degree_completion_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_number varchar(50) NOT NULL UNIQUE,
    employee_no varchar(50) NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(200),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint NOT NULL REFERENCES users(user_id),
    CONSTRAINT ck_degree_completion_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_degree_completion_achievements_status CHECK (certification_status IN ('DRAFT', 'SUBMITTED', 'CHAIR_CONFIRMED', 'CHAIR_REJECTED', 'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED')),
    CONSTRAINT ck_degree_completion_achievements_deleted CHECK (deleted_yn IN ('Y', 'N'))
);
COMMENT ON TABLE degree_completion_achievements IS '교육영역 석·박사 배출 실적 헤더. 인증상태와 논리삭제, 입력 및 수정 메타정보를 보존한다.';
COMMENT ON COLUMN degree_completion_achievements.employee_no IS 'korus_personnel_snapshots.employee_no 참조 의도 (FK 미선언)';
COMMENT ON COLUMN degree_completion_achievements.management_item_code IS 'evaluation_element_management_item_settings.management_item_code 참조 의도 (FK 미선언)';
COMMENT ON COLUMN degree_completion_achievements.achievement_detail IS '석·박사 배출 활성 관리항목의 동적 입력값을 애플리케이션에서 기록';
COMMENT ON COLUMN degree_completion_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|CHAIR_CONFIRMED:학과장확인|CHAIR_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN degree_completion_achievements.attachment_ref IS '기존 FileStoragePort가 발급한 외부 노출용 첨부 식별자';
COMMENT ON COLUMN degree_completion_achievements.deleted_yn IS 'Y:논리삭제|N:정상';

CREATE TABLE IF NOT EXISTS degree_completion_students (
    degree_completion_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL REFERENCES degree_completion_achievements(achievement_id),
    degree_type varchar(20) NOT NULL,
    student_name varchar(100) NOT NULL,
    thesis_title varchar(500) NOT NULL,
    degree_awarded_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint NOT NULL REFERENCES users(user_id),
    CONSTRAINT ck_degree_completion_students_degree_type CHECK (degree_type IN ('MASTER', 'DOCTOR')),
    CONSTRAINT uq_degree_completion_students_detail UNIQUE (achievement_id, degree_type, student_name, thesis_title)
);
COMMENT ON TABLE degree_completion_students IS '석·박사 배출 실적의 지도학생 반복 상세. 헤더와 동일한 트랜잭션으로 저장된다.';
COMMENT ON COLUMN degree_completion_students.achievement_id IS 'degree_completion_achievements.achievement_id 참조';
COMMENT ON COLUMN degree_completion_students.degree_type IS 'MASTER:석사|DOCTOR:박사';

CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_lookup
    ON degree_completion_achievements (evaluation_year, employee_no, certification_status, occurred_date DESC)
    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_degree_completion_students_achievement
    ON degree_completion_students (achievement_id, degree_awarded_date, degree_type);

WITH fixture_user AS (
    SELECT user_id FROM users WHERE login_id = 'admin'
), seeded_headers AS (
    INSERT INTO degree_completion_achievements (
        achievement_number, employee_no, evaluation_year, management_item_code, occurred_date,
        achievement_detail, certification_status, attachment_ref, deleted_yn, created_by, updated_by
    )
    SELECT fixture.achievement_number, 'E1001', '2026', 'EDU_DEGREE_COMPLETION', fixture.occurred_date,
           fixture.achievement_detail::jsonb, fixture.certification_status, fixture.attachment_ref, 'N',
           fixture_user.user_id, fixture_user.user_id
    FROM fixture_user
    CROSS JOIN (VALUES
        ('B77-DC-001', DATE '2026-08-20', '{"college":"교육대학원"}', 'DRAFT', NULL),
        ('B77-DC-002', DATE '2026-08-21', '{"college":"교육대학원"}', 'SUBMITTED', 'b77-dc-attachment-002'),
        ('B77-DC-003', DATE '2025-12-31', '{"college":"교육대학원"}', 'EVALUATION_CONFIRMED', 'b77-dc-attachment-003')
    ) AS fixture(achievement_number, occurred_date, achievement_detail, certification_status, attachment_ref)
    ON CONFLICT (achievement_number) DO UPDATE SET
        occurred_date = EXCLUDED.occurred_date,
        achievement_detail = EXCLUDED.achievement_detail,
        certification_status = EXCLUDED.certification_status,
        attachment_ref = EXCLUDED.attachment_ref,
        deleted_yn = EXCLUDED.deleted_yn,
        updated_at = CURRENT_TIMESTAMP,
        updated_by = EXCLUDED.updated_by
    RETURNING achievement_id, achievement_number
)
INSERT INTO degree_completion_students (achievement_id, degree_type, student_name, thesis_title, degree_awarded_date, created_by)
SELECT seeded_headers.achievement_id, student.degree_type, student.student_name, student.thesis_title,
       student.degree_awarded_date, fixture_user.user_id
FROM seeded_headers
CROSS JOIN fixture_user
CROSS JOIN LATERAL (
    SELECT * FROM (VALUES
        ('B77-DC-001', 'MASTER', '김석사', '교육 데이터 분석', DATE '2026-08-20'),
        ('B77-DC-001', 'DOCTOR', '이박사', '학습 분석 연구', DATE '2026-08-20'),
        ('B77-DC-002', 'MASTER', '박석사', '교수법 연구', DATE '2026-08-21'),
        ('B77-DC-003', 'DOCTOR', '최박사', '평가 모형 연구', DATE '2025-12-31')
    ) AS rows(achievement_number, degree_type, student_name, thesis_title, degree_awarded_date)
    WHERE rows.achievement_number = seeded_headers.achievement_number
) AS student
ON CONFLICT (achievement_id, degree_type, student_name, thesis_title) DO UPDATE SET
    degree_awarded_date = EXCLUDED.degree_awarded_date;
