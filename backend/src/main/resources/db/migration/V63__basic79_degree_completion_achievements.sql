CREATE TABLE IF NOT EXISTS degree_completion_achievements (
  achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_year varchar(4) NOT NULL,
  management_item_code varchar(50) NOT NULL,
  organization_code varchar(50) NOT NULL,
  occurred_date date NOT NULL,
  achievement_detail text,
  certification_status varchar(30) NOT NULL DEFAULT 'DRAFTING',
  attachment_ref varchar(200),
  deleted_yn varchar(1) NOT NULL DEFAULT 'N',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by bigint NOT NULL,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by bigint NOT NULL,
  change_reason varchar(500),
  CONSTRAINT ck_degree_completion_status CHECK (certification_status IN ('DRAFTING','SUBMITTED','DEPARTMENT_CONFIRMED','DEPARTMENT_REJECTED','CERTIFIED','CERTIFICATION_RETURNED','EVALUATION_CONFIRMED','DELETED')),
  CONSTRAINT fk_degree_completion_org FOREIGN KEY (organization_code) REFERENCES organizations(organization_code),
  CONSTRAINT fk_degree_completion_created FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_degree_completion_updated FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE degree_completion_achievements IS '교육영역 석·박사 배출 실적의 헤더와 인증상태를 보존한다.';
COMMENT ON COLUMN degree_completion_achievements.certification_status IS 'DRAFTING:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_RETURNED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN degree_completion_achievements.attachment_ref IS '기존 FileStoragePort 파일 식별자 참조 의도 (FK 미선언)';

CREATE TABLE IF NOT EXISTS degree_completion_students (
  degree_completion_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  achievement_id bigint NOT NULL,
  degree_type varchar(20) NOT NULL,
  student_name varchar(100) NOT NULL,
  thesis_title varchar(1000) NOT NULL,
  degree_awarded_date date NOT NULL,
  CONSTRAINT ck_degree_completion_degree_type CHECK (degree_type IN ('MASTER','DOCTORAL')),
  CONSTRAINT fk_degree_completion_students_header FOREIGN KEY (achievement_id) REFERENCES degree_completion_achievements(achievement_id) ON DELETE CASCADE
);
COMMENT ON TABLE degree_completion_students IS '석·박사 배출 실적별 지도학생의 학위와 논문·수여일을 반복 상세로 보존한다.';
COMMENT ON COLUMN degree_completion_students.degree_type IS 'MASTER:석사|DOCTORAL:박사';

CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_search ON degree_completion_achievements(evaluation_year, organization_code, certification_status, occurred_date DESC) WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_degree_completion_students_achievement ON degree_completion_students(achievement_id);

