-- BASIC-79 FR-027 학생지도 실적과 Excel 일괄반영 원천을 추가한다.
CREATE TABLE IF NOT EXISTS student_guidance_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) REFERENCES organizations(organization_code),
    management_item_code varchar(50) NOT NULL,
    guidance_start_date date NOT NULL,
    guidance_end_date date NOT NULL,
    student_count integer NOT NULL CHECK (student_count > 0),
    attachment_ref varchar(300),
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn char(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_student_guidance_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_student_guidance_achievements_dates CHECK (guidance_end_date >= guidance_start_date)
);
COMMENT ON TABLE student_guidance_achievements IS 'FR-027 학생지도 실적 헤더 원천. 지도 기간과 학생 수, 인증 상태를 보존한다.';
COMMENT ON COLUMN student_guidance_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN student_guidance_achievements.teacher_user_id IS 'users.user_id 참조 의도 (실적 소유 교원 및 데이터 범위 판단)';
COMMENT ON COLUMN student_guidance_achievements.attachment_ref IS 'FileStoragePort가 발급한 외부 비노출 첨부 참조값';
CREATE INDEX IF NOT EXISTS idx_student_guidance_achievements_search
    ON student_guidance_achievements (teacher_user_id, guidance_start_date DESC)
    WHERE deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS student_guidance_students (
    guidance_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL REFERENCES student_guidance_achievements(achievement_id),
    student_detail_jsonb jsonb NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id)
);
COMMENT ON TABLE student_guidance_students IS 'FR-027 학생지도 실적의 반복 지도학생 상세. 개인정보 계약 확정 전 학생 상세를 JSONB 원천으로 보존한다.';
COMMENT ON COLUMN student_guidance_students.achievement_id IS 'student_guidance_achievements.achievement_id 참조';
COMMENT ON COLUMN student_guidance_students.student_detail_jsonb IS '기존 개인정보 계약 확정 전 지도학생 상세 원천 JSONB';
CREATE INDEX IF NOT EXISTS idx_student_guidance_students_achievement
    ON student_guidance_students (achievement_id);

INSERT INTO student_guidance_achievements (
    achievement_id, evaluation_year, teacher_user_id, organization_code, management_item_code,
    guidance_start_date, guidance_end_date, student_count, certification_status, created_by, updated_by
)
SELECT seed.achievement_id, '2026', professor.user_id, 'KNUE-COL-EDU', seed.management_item_code,
       seed.guidance_start_date, seed.guidance_end_date, 1, seed.certification_status,
       admin.user_id, admin.user_id
FROM users admin
CROSS JOIN users professor
CROSS JOIN (VALUES
    (790201, 'EDU-GUIDANCE-A', DATE '2026-03-01', DATE '2026-03-05', 'DRAFT'),
    (790202, 'EDU-GUIDANCE-B', DATE '2026-02-01', DATE '2026-02-10', 'SUBMITTED'),
    (790203, 'EDU-GUIDANCE-C', DATE '2026-03-10', DATE '2026-03-15', 'EVALUATION_CONFIRMED')
) AS seed(achievement_id, management_item_code, guidance_start_date, guidance_end_date, certification_status)
WHERE admin.login_id = 'admin' AND professor.login_id = 'professor1'
ON CONFLICT (achievement_id) DO NOTHING;

SELECT setval(
    pg_get_serial_sequence('student_guidance_achievements', 'achievement_id'),
    COALESCE((SELECT MAX(achievement_id) FROM student_guidance_achievements), 1),
    true
);

INSERT INTO student_guidance_students (achievement_id, student_detail_jsonb, created_by, updated_by)
SELECT achievement_id, jsonb_build_object('fixtureId', 'B77-SG-001', 'studentName', '지도학생' || achievement_id), created_by, updated_by
FROM student_guidance_achievements
WHERE achievement_id IN (790201, 790202, 790203)
  AND NOT EXISTS (SELECT 1 FROM student_guidance_students s WHERE s.achievement_id = student_guidance_achievements.achievement_id);

WITH inserted_menu AS (
    INSERT INTO menus (menu_id, parent_menu_id, menu_type, menu_name, display_order, screen_id, url, icon, business_category, description, system_use_yn, status, updated_by)
    SELECT COALESCE(MAX(menu_id), 0) + 1, NULL, 'SCREEN', '학생지도 Excel 일괄등록', 3,
           'SCR-STUDENT-GUIDANCE-EXCEL-UPLOAD', '/achievements/education/student-guidance-uploads',
           'file-spreadsheet', 'BUSINESS', '학생지도 실적 Excel 검증과 전체 반영을 제공한다.', 'Y', 'ACTIVE', 1
    FROM menus
    WHERE NOT EXISTS (SELECT 1 FROM menus WHERE url = '/achievements/education/student-guidance-uploads')
    RETURNING menu_id
), target_menu AS (
    SELECT menu_id FROM inserted_menu
    UNION ALL
    SELECT menu_id FROM menus WHERE url = '/achievements/education/student-guidance-uploads'
      AND NOT EXISTS (SELECT 1 FROM inserted_menu)
)
INSERT INTO menu_permissions (target_type, target_id, menu_id, access_allowed, status, created_by, updated_by, change_reason)
SELECT 'ROLE', roles.role_code, menu_id, 'ALLOW', 'ACTIVE', 1, 1, 'BASIC-79 학생지도 실적 메뉴 접근'
FROM target_menu
CROSS JOIN (VALUES ('R01'), ('R02'), ('R04'), ('R07')) AS roles(role_code)
ON CONFLICT (target_type, target_id, menu_id) DO UPDATE SET access_allowed = EXCLUDED.access_allowed, status = EXCLUDED.status;
