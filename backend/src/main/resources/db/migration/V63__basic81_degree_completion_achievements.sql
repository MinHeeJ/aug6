INSERT INTO education_achievement_status_histories (
    achievement_type, achievement_id, previous_status, next_status, transition_reason, processed_by, request_id
)
SELECT 'DEGREE_COMPLETION', achievement_id,
       CASE achievement_status WHEN 'EVALUATION_CONFIRMED' THEN 'CERTIFIED' ELSE 'DRAFTING' END,
       achievement_status, change_reason, created_by, 'BASIC-81-DEGREE-SEED'
FROM degree_completion_achievements
WHERE management_no IN ('B77-DC-001', 'B77-DC-002', 'B77-DC-003')
  AND achievement_status <> 'DRAFTING'
  AND NOT EXISTS (
      SELECT 1 FROM education_achievement_status_histories history
      WHERE history.achievement_type = 'DEGREE_COMPLETION'
        AND history.achievement_id = degree_completion_achievements.achievement_id
        AND history.request_id = 'BASIC-81-DEGREE-SEED'
  );
