-- BASIC-81 석·박사 배출 실적 헤더와 지도학생 상세를 추가한다.

CREATE TABLE IF NOT EXISTS degree_completion_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL,
    target_user_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail text,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_degree_completion_achievements_management_no UNIQUE (management_no),
    CONSTRAINT ck_degree_completion_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_degree_completion_achievements_status CHECK (
        certification_status IN (
            'DRAFT',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_REJECTED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )
    ),
    CONSTRAINT ck_degree_completion_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_degree_completion_achievements_target_user
        FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_degree_completion_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_degree_completion_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE degree_completion_achievements IS '교육영역 석·박사 배출 실적의 헤더 원천. 대상 교원, 관리항목, 발생일과 인증상태를 보존한다.';
COMMENT ON COLUMN degree_completion_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN degree_completion_achievements.attachment_ref IS 'FileStoragePort의 외부 비노출 첨부 참조값';
COMMENT ON COLUMN degree_completion_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN degree_completion_achievements.target_user_id IS 'users.user_id 참조 의도 (실적 대상 교원)';
COMMENT ON COLUMN degree_completion_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN degree_completion_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_search
    ON degree_completion_achievements (
        target_user_id,
        evaluation_year,
        management_item_code,
        occurred_date DESC,
        certification_status
    )
    WHERE deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS degree_completion_students (
    degree_completion_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL,
    degree_type varchar(20) NOT NULL,
    student_name varchar(100) NOT NULL,
    thesis_title varchar(500) NOT NULL,
    degree_awarded_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_degree_completion_students_degree_type CHECK (degree_type IN ('MASTER', 'DOCTORAL')),
    CONSTRAINT fk_degree_completion_students_achievement
        FOREIGN KEY (achievement_id) REFERENCES degree_completion_achievements(achievement_id),
    CONSTRAINT fk_degree_completion_students_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_degree_completion_students_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE degree_completion_students IS '석·박사 배출 실적에 속한 지도학생 상세. 헤더 저장과 같은 트랜잭션에서 보존한다.';
COMMENT ON COLUMN degree_completion_students.degree_type IS 'MASTER:석사|DOCTORAL:박사';
COMMENT ON COLUMN degree_completion_students.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN degree_completion_students.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_degree_completion_students_achievement
    ON degree_completion_students (achievement_id, degree_awarded_date, degree_completion_student_id);

INSERT INTO degree_completion_achievements (
    management_no,
    target_user_id,
    evaluation_year,
    management_item_code,
    occurred_date,
    achievement_detail,
    certification_status,
    created_by,
    updated_by
)
SELECT
    seed.management_no,
    owner.user_id,
    seed.evaluation_year,
    seed.management_item_code,
    seed.occurred_date,
    seed.achievement_detail,
    seed.certification_status,
    owner.user_id,
    owner.user_id
FROM (
    VALUES
        ('B77-DC-001', 'professor1', '2026', 'DEGREE_COMPLETION', DATE '2026-02-20', '석사 배출 fixture', 'DRAFT'),
        ('B77-DC-002', 'professor2', '2026', 'DEGREE_COMPLETION', DATE '2026-02-25', '박사 배출 fixture', 'SUBMITTED'),
        ('B77-DC-003', 'business-owner', '2026', 'DEGREE_COMPLETION', DATE '2026-03-01', '석박사 배출 fixture', 'CERTIFIED')
) AS seed (
    management_no,
    login_id,
    evaluation_year,
    management_item_code,
    occurred_date,
    achievement_detail,
    certification_status
)
JOIN users owner
    ON owner.login_id = seed.login_id
ON CONFLICT (management_no) DO UPDATE SET
    target_user_id = EXCLUDED.target_user_id,
    evaluation_year = EXCLUDED.evaluation_year,
    management_item_code = EXCLUDED.management_item_code,
    occurred_date = EXCLUDED.occurred_date,
    achievement_detail = EXCLUDED.achievement_detail,
    certification_status = EXCLUDED.certification_status,
    updated_at = CURRENT_TIMESTAMP,
    updated_by = EXCLUDED.updated_by;

INSERT INTO degree_completion_students (
    achievement_id,
    degree_type,
    student_name,
    thesis_title,
    degree_awarded_date,
    created_by,
    updated_by
)
SELECT
    achievement.achievement_id,
    seed.degree_type,
    seed.student_name,
    seed.thesis_title,
    seed.degree_awarded_date,
    owner.user_id,
    owner.user_id
FROM (
    VALUES
        ('B77-DC-001', 'MASTER', '홍길동', '교육과정 연구', DATE '2026-02-20', 'professor1'),
        ('B77-DC-002', 'DOCTORAL', '김영희', '교수학습 모형 연구', DATE '2026-02-25', 'professor2'),
        ('B77-DC-003', 'MASTER', '이민수', '교육평가 분석', DATE '2026-03-01', 'business-owner')
) AS seed (
    management_no,
    degree_type,
    student_name,
    thesis_title,
    degree_awarded_date,
    login_id
)
JOIN degree_completion_achievements achievement
    ON achievement.management_no = seed.management_no
JOIN users owner
    ON owner.login_id = seed.login_id
WHERE NOT EXISTS (
    SELECT 1
    FROM degree_completion_students student
    WHERE student.achievement_id = achievement.achievement_id
      AND student.degree_type = seed.degree_type
      AND student.student_name = seed.student_name
      AND student.thesis_title = seed.thesis_title
      AND student.degree_awarded_date = seed.degree_awarded_date
);
