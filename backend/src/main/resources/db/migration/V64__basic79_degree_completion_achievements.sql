INSERT INTO degree_completion_students (
    achievement_id,
    degree_type,
    student_name,
    thesis_title,
    degree_awarded_date,
    created_by,
    updated_by
)
SELECT achievement.achievement_id,
       seed.degree_type,
       seed.student_name,
       seed.thesis_title,
       seed.degree_awarded_date,
       achievement.created_by,
       achievement.updated_by
FROM degree_completion_achievements achievement
JOIN (
    VALUES
        (790401, 'MASTER', '석사 지도학생', '교육 리더십 연구', DATE '2026-02-20'),
        (790402, 'DOCTOR', '박사 지도학생', '교원 역량 연구', DATE '2026-03-15'),
        (790403, 'MASTER', '평가확정 학생', '평가 제도 연구', DATE '2026-03-25')
) AS seed(achievement_id, degree_type, student_name, thesis_title, degree_awarded_date)
  ON seed.achievement_id = achievement.achievement_id
WHERE NOT EXISTS (
    SELECT 1
    FROM degree_completion_students student
    WHERE student.achievement_id = achievement.achievement_id
);

INSERT INTO education_achievement_status_histories (
    achievement_type,
    achievement_id,
    previous_status,
    next_status,
    action_type,
    processed_by,
    created_by,
    updated_by
)
SELECT 'DEGREE_COMPLETION',
       achievement.achievement_id,
       CASE achievement.certification_status
           WHEN 'DRAFT' THEN NULL
           WHEN 'SUBMITTED' THEN 'DRAFT'
           ELSE 'CERTIFIED'
       END,
       achievement.certification_status,
       CASE achievement.certification_status
           WHEN 'DRAFT' THEN 'CREATE'
           WHEN 'SUBMITTED' THEN 'SUBMIT'
           ELSE 'CONFIRM_EVALUATION'
       END,
       admin.user_id,
       admin.user_id,
       admin.user_id
FROM degree_completion_achievements achievement
CROSS JOIN users admin
WHERE achievement.achievement_id IN (790401, 790402, 790403)
  AND admin.login_id = 'admin'
  AND NOT EXISTS (
      SELECT 1
      FROM education_achievement_status_histories history
      WHERE history.achievement_type = 'DEGREE_COMPLETION'
        AND history.achievement_id = achievement.achievement_id
        AND history.next_status = achievement.certification_status
  );

