-- BASIC-79 FR-028 석·박사 배출 실적 헤더와 지도학생 상세 원천을 추가한다.
CREATE TABLE IF NOT EXISTS degree_completion_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) REFERENCES organizations(organization_code),
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_degree_completion_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_degree_completion_achievements_status CHECK (certification_status IN (
        'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
        'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
    ))
);
COMMENT ON TABLE degree_completion_achievements IS 'FR-028 석·박사 배출 실적 헤더 원천. 교원별 배출 실적의 상태와 첨부 참조를 보존한다.';
COMMENT ON COLUMN degree_completion_achievements.teacher_user_id IS 'users.user_id 참조 의도 (실적 소유 교원 및 데이터 범위 판단)';
COMMENT ON COLUMN degree_completion_achievements.organization_code IS 'organizations.organization_code 참조 의도 (소속 기반 데이터 범위 판단)';
COMMENT ON COLUMN degree_completion_achievements.management_item_code IS 'evaluation_management_items.management_item_code 참조 의도 (활성 관리항목 검증)';
COMMENT ON COLUMN degree_completion_achievements.achievement_detail IS 'FR-018에서 결정되는 동적 입력 항목을 저장하는 JSONB 원천값';
COMMENT ON COLUMN degree_completion_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN degree_completion_achievements.attachment_ref IS 'FileStoragePort가 발급한 외부 비노출 첨부 참조값';
CREATE INDEX IF NOT EXISTS idx_degree_completion_achievements_search
    ON degree_completion_achievements (
        teacher_user_id,
        organization_code,
        occurred_date DESC
    )
    WHERE deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS degree_completion_students (
    degree_completion_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id bigint NOT NULL REFERENCES degree_completion_achievements(achievement_id),
    degree_type varchar(20) NOT NULL CHECK (degree_type IN ('MASTER', 'DOCTOR')),
    student_name varchar(100) NOT NULL,
    thesis_title varchar(500) NOT NULL,
    degree_awarded_date date NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id)
);
COMMENT ON TABLE degree_completion_students IS 'FR-028 석·박사 배출 실적의 지도학생 반복 상세. 학위구분과 논문 및 학위수여일을 함께 보존한다.';
COMMENT ON COLUMN degree_completion_students.achievement_id IS 'degree_completion_achievements.achievement_id 참조';
COMMENT ON COLUMN degree_completion_students.degree_type IS 'MASTER:석사|DOCTOR:박사';
CREATE INDEX IF NOT EXISTS idx_degree_completion_students_achievement
    ON degree_completion_students (achievement_id, degree_awarded_date);

