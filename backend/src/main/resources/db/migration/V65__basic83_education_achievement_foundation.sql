INSERT INTO menu_permissions (
    target_type,
    target_id,
    menu_id,
    access_allowed,
    status,
    created_by,
    updated_by,
    change_reason
)
SELECT
    'ROLE',
    role_seed.role_code,
    menu.menu_id,
    'ALLOW',
    'ACTIVE',
    admin_user.user_id,
    admin_user.user_id,
    'BASIC-83 교육영역 후반 실적 R01/R02/R04 접근'
FROM menus menu
CROSS JOIN users admin_user
CROSS JOIN (
    VALUES ('R01'), ('R02'), ('R04'), ('R07')
) AS role_seed(role_code)
WHERE menu.screen_id IN (
        'SCR-COURSE-OPERATIONS',
        'SCR-EMPLOYMENT-RATE-IMPROVEMENTS',
        'SCR-LECTURE-IMPROVEMENTS',
        'SCR-EMPLOYMENT-RATE-ACHIEVEMENTS'
    )
  AND (
      role_seed.role_code <> 'R07'
      OR menu.screen_id = 'SCR-EMPLOYMENT-RATE-ACHIEVEMENTS'
  )
  AND admin_user.login_id = 'admin'
ON CONFLICT (target_type, target_id, menu_id) DO UPDATE
SET access_allowed = EXCLUDED.access_allowed,
    status = EXCLUDED.status,
    updated_at = CURRENT_TIMESTAMP,
    updated_by = EXCLUDED.updated_by,
    change_reason = EXCLUDED.change_reason;

