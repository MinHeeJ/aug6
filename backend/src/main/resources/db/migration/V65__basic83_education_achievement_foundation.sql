INSERT INTO menu_execution_info (
    menu_id,
    screen_id,
    url,
    icon,
    business_category,
    description,
    updated_by
)
SELECT
    menu.menu_id,
    menu.screen_id,
    menu.url,
    menu.icon,
    menu.business_category,
    menu.description,
    admin_user.user_id
FROM menus menu
CROSS JOIN users admin_user
WHERE menu.screen_id IN (
        'SCR-EMPLOYMENT-RATE-IMPROVEMENTS',
        'SCR-COURSE-OPERATIONS',
        'SCR-LECTURE-IMPROVEMENTS',
        'SCR-EMPLOYMENT-RATE-ACHIEVEMENTS'
    )
  AND admin_user.login_id = 'admin'
ON CONFLICT (menu_id) DO UPDATE SET
    screen_id = EXCLUDED.screen_id,
    url = EXCLUDED.url,
    icon = EXCLUDED.icon,
    business_category = EXCLUDED.business_category,
    description = EXCLUDED.description,
    updated_at = CURRENT_TIMESTAMP,
    updated_by = EXCLUDED.updated_by;

