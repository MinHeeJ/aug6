CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    action_type varchar(20) NOT NULL,
    job_status varchar(20) NOT NULL DEFAULT 'QUEUED',
    total_count integer NOT NULL DEFAULT 0,
    processed_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    requested_by bigint NOT NULL,
    request_id varchar(100),
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamp,
    CONSTRAINT ck_employment_rate_batch_jobs_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_employment_rate_batch_jobs_action CHECK (action_type IN ('GENERATE', 'DELETE')),
    CONSTRAINT ck_employment_rate_batch_jobs_status CHECK (
        job_status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'PARTIAL_FAILED')
    ),
    CONSTRAINT ck_employment_rate_batch_jobs_counts CHECK (
        total_count >= 0
        AND processed_count >= 0
        AND success_count >= 0
        AND failure_count >= 0
        AND processed_count <= total_count
        AND success_count + failure_count <= processed_count
    ),
    CONSTRAINT fk_employment_rate_batch_jobs_requested_by
        FOREIGN KEY (requested_by) REFERENCES users(user_id)
);
COMMENT ON TABLE employment_rate_batch_jobs IS '취업률 실적 일괄 작업의 요청 조건, 진행 상태 및 처리 집계를 보존한다. 대상별 결과는 승인된 별도 결과 계약에서 관리한다.';
COMMENT ON COLUMN employment_rate_batch_jobs.target_condition_json IS '취업률 일괄 작업 접수 시 API targetCondition을 애플리케이션에서 저장';
COMMENT ON COLUMN employment_rate_batch_jobs.action_type IS 'GENERATE:생성요청|DELETE:삭제요청';
COMMENT ON COLUMN employment_rate_batch_jobs.job_status IS
    'QUEUED:대기|RUNNING:진행중|COMPLETED:완료|FAILED:실패|PARTIAL_FAILED:일부실패';
COMMENT ON COLUMN employment_rate_batch_jobs.requested_by IS 'users.user_id 참조 의도 (일괄 작업 요청자)';
COMMENT ON COLUMN employment_rate_batch_jobs.request_id IS 'X-Request-Id 또는 서버 생성 요청 식별자';
COMMENT ON COLUMN employment_rate_batch_jobs.total_count IS '일괄 작업 대상 확정 시 애플리케이션에서 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.processed_count IS '일괄 작업 실행 중 애플리케이션에서 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.success_count IS '일괄 작업 실행 중 성공 건수로 애플리케이션에서 갱신';
