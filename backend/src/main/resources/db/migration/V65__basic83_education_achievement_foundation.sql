CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    action_type varchar(20) NOT NULL,
    job_status varchar(20) NOT NULL DEFAULT 'REQUESTED',
    target_count integer NOT NULL DEFAULT 0,
    processed_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    request_id varchar(100) NOT NULL,
    requested_by bigint NOT NULL,
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_employment_rate_batch_jobs_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_employment_rate_batch_jobs_action CHECK (action_type IN ('GENERATE', 'DELETE')),
    CONSTRAINT ck_employment_rate_batch_jobs_status CHECK (
        job_status IN ('REQUESTED', 'RUNNING', 'COMPLETED', 'FAILED', 'REJECTED')
    ),
    CONSTRAINT ck_employment_rate_batch_jobs_counts CHECK (
        target_count >= 0
        AND processed_count >= 0
        AND success_count >= 0
        AND failure_count >= 0
    ),
    CONSTRAINT fk_employment_rate_batch_jobs_requested_by
        FOREIGN KEY (requested_by) REFERENCES users(user_id),
    CONSTRAINT fk_employment_rate_batch_jobs_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_employment_rate_batch_jobs_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE employment_rate_batch_jobs IS '취업률 실적 일괄 생성·삭제 작업 헤더. 승인된 정책에 따른 대상 조건과 처리 건수를 추적한다.';
COMMENT ON COLUMN employment_rate_batch_jobs.target_condition_json IS '일괄 작업 접수 시 애플리케이션이 검증한 대상 조건 JSON';
COMMENT ON COLUMN employment_rate_batch_jobs.action_type IS 'GENERATE:일괄생성|DELETE:일괄삭제';
COMMENT ON COLUMN employment_rate_batch_jobs.job_status IS
    'REQUESTED:접수|RUNNING:처리중|COMPLETED:완료|FAILED:실패|REJECTED:거부';
COMMENT ON COLUMN employment_rate_batch_jobs.request_id IS '취업률 일괄 처리 요청을 전 구간에서 추적하는 식별자';
COMMENT ON COLUMN employment_rate_batch_jobs.requested_by IS 'users.user_id 참조 (일괄 작업 요청자)';
COMMENT ON COLUMN employment_rate_batch_jobs.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN employment_rate_batch_jobs.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_jobs_requester
    ON employment_rate_batch_jobs (requested_by, requested_at DESC);
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_jobs_status
    ON employment_rate_batch_jobs (job_status, evaluation_year, requested_at DESC);

