-- BASIC-83 취업률 제고 실적의 공통 원천, 상태 이력 유형, 메뉴 권한과 검증 fixture를 추가한다.

CREATE TABLE IF NOT EXISTS employment_rate_improvement_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL,
    target_user_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    special_lecture_start_date date,
    special_lecture_end_date date,
    mock_exam_question_period varchar(200),
    attachment_ref varchar(300),
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_employment_rate_improvement_achievements_management_no
        UNIQUE (management_no),
    CONSTRAINT ck_employment_rate_improvement_achievements_year
        CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_employment_rate_improvement_achievements_special_lecture_period
        CHECK (
            special_lecture_end_date IS NULL
            OR special_lecture_start_date IS NULL
            OR special_lecture_end_date >= special_lecture_start_date
        ),
    CONSTRAINT ck_employment_rate_improvement_achievements_status
        CHECK (
            certification_status IN (
                'DRAFT',
                'SUBMITTED',
                'DEPARTMENT_CONFIRMED',
                'DEPARTMENT_REJECTED',
                'CERTIFIED',
                'CERTIFICATION_REJECTED',
                'EVALUATION_CONFIRMED',
                'DELETED'
            )
        ),
    CONSTRAINT ck_employment_rate_improvement_achievements_deleted
        CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_employment_rate_improvement_achievements_target_user
        FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_employment_rate_improvement_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_employment_rate_improvement_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

COMMENT ON TABLE employment_rate_improvement_achievements IS '교육영역 취업률 제고 실적 원천. 대상 교원별 관리항목, 특강·모의평가 정보, 인증상태와 논리삭제 정보를 보존한다.';
COMMENT ON COLUMN employment_rate_improvement_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN employment_rate_improvement_achievements.attachment_ref IS 'FileStoragePort의 외부 비노출 첨부 참조값';
COMMENT ON COLUMN employment_rate_improvement_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN employment_rate_improvement_achievements.target_user_id IS 'users.user_id 참조 의도 (실적 대상 교원)';
COMMENT ON COLUMN employment_rate_improvement_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN employment_rate_improvement_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_employment_rate_improvement_achievements_search
    ON employment_rate_improvement_achievements (
        target_user_id,
        evaluation_year,
        management_item_code,
        occurred_date DESC,
        certification_status
    )
    WHERE deleted_yn = 'N';

ALTER TABLE education_achievement_status_histories
