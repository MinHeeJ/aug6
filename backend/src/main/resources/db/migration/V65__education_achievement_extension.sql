-- 교육영역 후반 실적의 공통 원천과 상세를 추가한다. 기존 원천 테이블은 유지한다.
CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL UNIQUE,
    achievement_type varchar(30) NOT NULL,
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) NOT NULL REFERENCES organizations(organization_code),
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    achievement_date date NOT NULL,
    achievement_name text,
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ref varchar(300),
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_education_achievements_type CHECK (achievement_type IN (
        'EMPLOYMENT_RATE_IMPROVEMENT', 'COURSE_OPERATION',
        'LECTURE_IMPROVEMENT', 'EMPLOYMENT_RATE_ACHIEVEMENT'
    )),
    CONSTRAINT ck_education_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_education_achievements_status CHECK (achievement_status IN (
        'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
        'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
    )),
    CONSTRAINT ck_education_achievements_deleted CHECK (deleted_yn IN ('Y', 'N'))
);
COMMENT ON TABLE education_achievements IS '교육영역 후반 네 유형의 실적 공통 원천. 교원·평가연도·상태·논리삭제를 보존한다.';
COMMENT ON COLUMN education_achievements.management_item_code
    IS 'evaluation_element_management_item_settings.management_item_code 참조 의도 (규정·요소별 복합키, FK 미선언)';
COMMENT ON COLUMN education_achievements.attachment_ref
    IS '소유권과 파일 존재를 검증한 opaque token의 JSON 문자열 배열. 파일 경로를 저장하지 않는다.';
CREATE INDEX IF NOT EXISTS idx_education_achievements_teacher_search
    ON education_achievements (
        achievement_type, teacher_user_id, evaluation_year, achievement_date DESC, achievement_id
    )
    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_education_achievements_organization_search
    ON education_achievements (achievement_type, organization_code, evaluation_year, achievement_status)
    WHERE deleted_yn = 'N';
-- Excel 중복은 자동 갱신하지 않는다. 개별 실적은 동일 발생일에 서로 다른 내용이 있을 수 있다.
CREATE UNIQUE INDEX IF NOT EXISTS uq_education_achievements_employment_identity
    ON education_achievements (teacher_user_id, evaluation_year, management_item_code, achievement_date,
        COALESCE(achievement_name, ''))
    WHERE achievement_type = 'EMPLOYMENT_RATE_ACHIEVEMENT' AND deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS employment_rate_improvement_achievement_details (
    achievement_id bigint PRIMARY KEY REFERENCES education_achievements(achievement_id),
    special_lecture_start_date date,
    special_lecture_end_date date,
    mock_exam_question_period text,
    CONSTRAINT ck_employment_improvement_dates CHECK (
        (special_lecture_start_date IS NULL AND special_lecture_end_date IS NULL)
        OR (special_lecture_start_date IS NOT NULL AND special_lecture_end_date IS NOT NULL
            AND special_lecture_start_date <= special_lecture_end_date)
    )
);
COMMENT ON TABLE employment_rate_improvement_achievement_details
    IS '취업률 제고 실적의 특강기간과 모의시험 출제기간. 공통 실적 식별자와 일대일로 연결한다.';
CREATE TABLE IF NOT EXISTS course_operation_achievement_details (
    achievement_id bigint PRIMARY KEY REFERENCES education_achievements(achievement_id),
    performance_detail text NOT NULL,
    CONSTRAINT ck_course_operation_content CHECK (LENGTH(BTRIM(performance_detail)) > 0)
);
COMMENT ON TABLE course_operation_achievement_details IS '강좌 개설·운영 실적의 필수 실적내역을 보존한다.';
CREATE TABLE IF NOT EXISTS lecture_improvement_achievement_details (
    achievement_id bigint PRIMARY KEY REFERENCES education_achievements(achievement_id),
    performance_content text NOT NULL,
    academic_year integer NOT NULL,
    semester_code varchar(1) NOT NULL,
    CONSTRAINT ck_lecture_improvement_content CHECK (LENGTH(BTRIM(performance_content)) > 0),
    CONSTRAINT ck_lecture_improvement_year CHECK (academic_year >= 2000),
    CONSTRAINT ck_lecture_improvement_semester CHECK (semester_code IN ('1', '2'))
);
COMMENT ON TABLE lecture_improvement_achievement_details IS '강의개선 실적의 내용·학년도·학기를 보존한다.';

CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    action_type varchar(30) NOT NULL,
    total_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    excluded_count integer NOT NULL DEFAULT 0,
    job_status varchar(30) NOT NULL DEFAULT 'REQUESTED',
    requested_by bigint NOT NULL REFERENCES users(user_id),
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_id varchar(100) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_employment_batch_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_employment_batch_action CHECK (action_type IN ('GENERATE', 'DELETE')),
    CONSTRAINT ck_employment_batch_status CHECK (
        job_status IN ('REQUESTED', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED')
    ),
    CONSTRAINT ck_employment_batch_counts CHECK (
        total_count >= 0 AND success_count >= 0 AND failure_count >= 0 AND excluded_count >= 0
        AND success_count + failure_count + excluded_count <= total_count
    ),
    CONSTRAINT ck_employment_batch_condition CHECK (jsonb_typeof(target_condition_json) = 'object')
);
COMMENT ON TABLE employment_rate_batch_jobs
    IS '취업률 일괄 처리의 조건·요청자·처리건수. 정책 승인 전 실행 미사용 — seed는 읽기 전용 미처리 결과이다.';
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_jobs_owner
    ON employment_rate_batch_jobs (requested_by, requested_at DESC);
CREATE TABLE IF NOT EXISTS employment_rate_batch_job_items (
    batch_job_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_job_id varchar(100) NOT NULL REFERENCES employment_rate_batch_jobs(batch_job_id),
    target_user_id bigint NOT NULL REFERENCES users(user_id),
    processed_yn char(1) NOT NULL DEFAULT 'N',
    unprocessed_reason text,
    processed_at timestamp,
    request_id varchar(100) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT uq_employment_batch_item_target UNIQUE (batch_job_id, target_user_id),
    CONSTRAINT ck_employment_batch_item_processed CHECK (processed_yn IN ('Y', 'N'))
);
COMMENT ON TABLE employment_rate_batch_job_items
    IS '취업률 일괄 대상별 처리 여부와 미처리 사유. 정책 승인 전 실행 미사용 — 원천 변경 없는 읽기 전용 결과를 제공한다.';
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_items_job
    ON employment_rate_batch_job_items (batch_job_id, processed_yn, batch_job_item_id);

