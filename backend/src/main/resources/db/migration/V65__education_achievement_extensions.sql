    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_education_achievements_organization_search
    ON education_achievements (achievement_type, organization_code, evaluation_year, achievement_status, achievement_id)
    WHERE deleted_yn = 'N';
