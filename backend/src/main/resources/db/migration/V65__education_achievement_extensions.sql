-- 신규 교육실적의 정규화 원장과 상세를 추가한다. 기존 교육 원장은 그대로 유지한다.
CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(30) NOT NULL,
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) NOT NULL REFERENCES organizations(organization_code),
    evaluation_year varchar(4) NOT NULL CHECK (evaluation_year ~ '^[0-9]{4}$'),
    management_item_code varchar(50) NOT NULL,
    achievement_date date NOT NULL,
    achievement_name varchar(300),
    achievement_detail text NOT NULL DEFAULT '{}',
    attachment_ref varchar(300),
    attachment_ids jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(attachment_ids) = 'array'),
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn char(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    request_id varchar(100),
    CONSTRAINT ck_education_achievements_type CHECK (
        achievement_type IN (
            'EMPLOYMENT_RATE_IMPROVEMENT',
            'COURSE_OPERATION',
            'LECTURE_IMPROVEMENT',
            'EMPLOYMENT_RATE_ACHIEVEMENT'
        )
    ),
    CONSTRAINT ck_education_achievements_status CHECK (
        achievement_status IN (
            'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
            'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
        )
    ),
    CONSTRAINT ck_education_achievements_delete_state CHECK (
        (deleted_yn = 'Y') = (achievement_status = 'DELETED')
    )
);
COMMENT ON TABLE education_achievements IS '교육영역 후반 네 유형의 공통 실적 원장. 평가연도와 발생일을 독립 보존하고 논리삭제와 변경 이력을 적용한다.';
COMMENT ON COLUMN education_achievements.management_item_code IS
    'evaluation_management_items.management_item_code 참조 의도 (버전별 코드로 단독 FK 미선언)';
COMMENT ON COLUMN education_achievements.attachment_ref IS '첨부 저장소의 외부 비노출 참조값';
COMMENT ON COLUMN education_achievements.attachment_ids IS '첨부 서비스의 opaque 첨부 식별자 목록';
COMMENT ON COLUMN education_achievements.achievement_detail IS '관리항목 규칙에 따라 검증한 동적 상세 JSON 문자열';
CREATE UNIQUE INDEX IF NOT EXISTS uq_education_achievements_active_identity
    ON education_achievements (
        teacher_user_id, evaluation_year, achievement_type, management_item_code, achievement_date
    )
    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_education_achievements_search
    ON education_achievements (
        achievement_type, evaluation_year, organization_code, achievement_date DESC, achievement_id DESC
    )
    WHERE deleted_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_education_achievements_owner
    ON education_achievements (teacher_user_id, achievement_type, achievement_status)
    WHERE deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS employment_rate_improvement_achievement_details (
    achievement_id bigint PRIMARY KEY REFERENCES education_achievements(achievement_id),
    special_lecture_start_date date,
    special_lecture_end_date date,
    mock_exam_question_period varchar(300),
    CONSTRAINT ck_employment_rate_improvement_dates CHECK (
        special_lecture_start_date IS NULL
        OR special_lecture_end_date IS NULL
        OR special_lecture_end_date >= special_lecture_start_date
    )
);
COMMENT ON TABLE employment_rate_improvement_achievement_details IS
    '취업률 제고 실적의 특강기간과 모의시험 출제기간 상세. 공통 원장과 같은 트랜잭션에서 저장한다.';

CREATE TABLE IF NOT EXISTS course_operation_achievement_details (
    achievement_id bigint PRIMARY KEY REFERENCES education_achievements(achievement_id),
    performance_detail text NOT NULL CHECK (length(btrim(performance_detail)) > 0)
);
COMMENT ON TABLE course_operation_achievement_details IS '강좌 개설·운영 실적의 실적내역 상세. 원장 식별자로 일대일 연결한다.';

CREATE TABLE IF NOT EXISTS lecture_improvement_achievement_details (
    achievement_id bigint PRIMARY KEY REFERENCES education_achievements(achievement_id),
    performance_content text NOT NULL CHECK (length(btrim(performance_content)) > 0),
    academic_year integer NOT NULL CHECK (academic_year >= 2000),
    semester_code varchar(100) NOT NULL
);
COMMENT ON TABLE lecture_improvement_achievement_details IS '강의개선 실적의 내용·학년도·학기 상세. 학기 코드는 공통코드의 유효값을 서비스에서 검증한다.';
COMMENT ON COLUMN lecture_improvement_achievement_details.semester_code IS
    'detail_codes의 EDUCATION_SEMESTER.code_value 참조 의도 (복합 자연키이므로 단독 FK 미선언)';

CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL CHECK (evaluation_year ~ '^[0-9]{4}$'),
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    action_type varchar(20) NOT NULL CHECK (action_type IN ('GENERATE', 'DELETE')),
    status varchar(30) NOT NULL DEFAULT 'BLOCKED'
        CHECK (status IN ('BLOCKED', 'REQUESTED', 'RUNNING', 'COMPLETED', 'FAILED')),
    total_count integer NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    processed_count integer NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    unprocessed_count integer NOT NULL DEFAULT 0 CHECK (unprocessed_count >= 0),
    requester_user_id bigint NOT NULL REFERENCES users(user_id),
    request_id varchar(100),
    diagnostic_message varchar(1000),
    started_at timestamp,
    completed_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_employment_rate_batch_jobs_counts CHECK (
        processed_count + unprocessed_count <= total_count
    )
);
COMMENT ON TABLE employment_rate_batch_jobs IS
    '취업률 일괄 작업 조건과 처리건수·진단 결과. 현재 정책 미승인으로 실행은 차단하며 seed는 실행 산출물이 아닌 진단 이력이다.';
COMMENT ON COLUMN employment_rate_batch_jobs.target_condition_json IS '일괄 작업 서비스가 접수 또는 진단 생성 시 저장한 대상 조건';
COMMENT ON COLUMN employment_rate_batch_jobs.processed_count IS '일괄 작업 서비스가 처리 완료 시 갱신하는 처리 건수';
COMMENT ON COLUMN employment_rate_batch_jobs.unprocessed_count IS '일괄 작업 서비스가 처리 완료 또는 진단 생성 시 갱신하는 미처리 건수';
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_jobs_requester
    ON employment_rate_batch_jobs (requester_user_id, created_at DESC, batch_job_id);

CREATE TABLE IF NOT EXISTS employment_rate_batch_job_items (
    batch_job_item_id varchar(100) PRIMARY KEY,
    batch_job_id varchar(100) NOT NULL REFERENCES employment_rate_batch_jobs(batch_job_id),
    target_user_id bigint NOT NULL REFERENCES users(user_id),
    achievement_id bigint REFERENCES education_achievements(achievement_id),
    processed_yn char(1) NOT NULL DEFAULT 'N' CHECK (processed_yn IN ('Y', 'N')),
    unprocessed_reason varchar(1000),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT uq_employment_rate_batch_job_items_target UNIQUE (batch_job_id, target_user_id),
    CONSTRAINT ck_employment_rate_batch_job_items_reason CHECK (
        processed_yn = 'Y' OR length(btrim(unprocessed_reason)) > 0
    )
);
COMMENT ON TABLE employment_rate_batch_job_items IS
    '취업률 일괄 작업 대상별 처리 여부와 미처리 사유. 현재 seed는 미승인 정책의 진단 대상이며 실적 변경을 의미하지 않는다.';
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_job_items_job
    ON employment_rate_batch_job_items (batch_job_id, processed_yn, batch_job_item_id);

