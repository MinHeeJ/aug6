-- 교육영역 후반 실적은 하나의 원장과 유형별 상세에 저장한다.
-- 일괄 결과 seed는 조회용 증적이며 GENERATE/DELETE 실행정책을 승인하지 않는다.

CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(30) NOT NULL,
    management_no varchar(50) NOT NULL,
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) NOT NULL REFERENCES organizations(organization_code),
    evaluation_year varchar(4) NOT NULL CHECK (evaluation_year ~ '^[0-9]{4}$'),
    management_item_code varchar(50) NOT NULL CHECK (btrim(management_item_code) <> ''),
    achievement_date date NOT NULL,
    title varchar(500),
    attachment_ref varchar(300),
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn char(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT uq_education_achievements_management_no UNIQUE (management_no),
    CONSTRAINT ck_education_achievements_type CHECK (achievement_type IN (
        'EMPLOYMENT_RATE_IMPROVEMENT', 'COURSE_OPERATION', 'LECTURE_IMPROVEMENT', 'EMPLOYMENT_RATE_ACHIEVEMENT'
    )),
    CONSTRAINT ck_education_achievements_status CHECK (achievement_status IN (
        'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
        'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
    )),
    CONSTRAINT ck_education_achievements_title CHECK (
        achievement_type <> 'EMPLOYMENT_RATE_ACHIEVEMENT' OR (title IS NOT NULL AND btrim(title) <> '')
    ),
    CONSTRAINT ck_education_achievements_deletion CHECK (
        (deleted_yn = 'Y') = (achievement_status = 'DELETED')
    )
);
COMMENT ON TABLE education_achievements IS '취업률 제고·강좌 운영·강의개선·취업률 실적 공통 원장. 대상 교원과 연도, 상태, 첨부 및 입력·수정자를 보존한다.';
COMMENT ON COLUMN education_achievements.management_item_code IS
    'evaluation_management_items.management_item_code 참조 의도 (element별 중복 가능, 교육영역 검증은 service 담당)';
COMMENT ON COLUMN education_achievements.achievement_type IS
    'EMPLOYMENT_RATE_IMPROVEMENT:취업률제고|COURSE_OPERATION:강좌운영|LECTURE_IMPROVEMENT:강의개선|EMPLOYMENT_RATE_ACHIEVEMENT:취업률';
COMMENT ON COLUMN education_achievements.attachment_ref IS '기존 파일 서비스의 opaque token 참조; 저장 경로를 노출하지 않는다.';
COMMENT ON COLUMN education_achievements.achievement_status IS
    'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|'
    'CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievements.deleted_yn IS 'Y:삭제|N:정상';

CREATE INDEX IF NOT EXISTS idx_education_achievements_teacher_search
    ON education_achievements (
        achievement_type, teacher_user_id, evaluation_year, achievement_date DESC, achievement_id
