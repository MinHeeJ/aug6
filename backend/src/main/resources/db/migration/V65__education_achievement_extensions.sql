-- 기존 EDUCATION 평가연도를 학과의 연중 입력 fixture에 사용하며 기존 대학 기간은 변경하지 않는다.
INSERT INTO input_period_settings (
    evaluation_year, area_code, organization_code, user_type_code, start_at, end_at, base_date,
    active_yn, created_by, updated_by, change_reason
)
SELECT
    p.evaluation_year, p.area_code, 'KNUE-DEPT-COMP', p.user_type_code,
    make_date(p.evaluation_year::integer, 1, 1)::timestamp,
    make_date(p.evaluation_year::integer + 1, 1, 1)::timestamp - INTERVAL '1 second', p.base_date,
    p.active_yn, p.created_by, p.updated_by, '교육영역 학과 입력기간 fixture'
FROM input_period_settings p
WHERE p.area_code = 'EDUCATION'
  AND p.organization_code = 'KNUE-COL-EDU'
  AND p.active_yn = 'Y'
  AND NOT EXISTS (
      SELECT 1
      FROM input_period_settings existing
      WHERE existing.evaluation_year = p.evaluation_year
        AND existing.area_code = p.area_code
        AND existing.organization_code = 'KNUE-DEPT-COMP'
        AND existing.active_yn = 'Y'
  );

