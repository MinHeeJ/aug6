CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL CHECK (evaluation_year ~ '^[0-9]{4}$'),
    target_condition_json jsonb NOT NULL CHECK (jsonb_typeof(target_condition_json) = 'object'),
    action_type varchar(20) NOT NULL CHECK (action_type IN ('GENERATE', 'DELETE')),
    requester_user_id bigint NOT NULL REFERENCES users(user_id),
    job_status varchar(20) NOT NULL CHECK (job_status IN ('REQUESTED', 'COMPLETED', 'FAILED')),
    total_count integer NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    processed_count integer NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    unprocessed_count integer NOT NULL DEFAULT 0 CHECK (unprocessed_count >= 0),
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamp,
    request_id varchar(200),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_employment_rate_batch_jobs_counts CHECK (total_count = processed_count + unprocessed_count)
);
COMMENT ON TABLE employment_rate_batch_jobs IS
    '취업률 일괄 작업의 대상조건·요청자·처리건수 조회 원장. 현재 실행정책 미승인으로 신규 실행은 차단하며 시드는 조회용 증적이다.';
COMMENT ON COLUMN employment_rate_batch_jobs.job_status IS 'REQUESTED:요청됨|COMPLETED:처리완료|FAILED:처리실패';
COMMENT ON COLUMN employment_rate_batch_jobs.action_type IS 'GENERATE:생성|DELETE:삭제';
COMMENT ON COLUMN employment_rate_batch_jobs.request_id IS '요청 경계의 X-Request-Id 참조 의도 (FK 미선언)';
COMMENT ON COLUMN employment_rate_batch_jobs.total_count IS '일괄 service가 결과 item 저장과 동일 트랜잭션에서 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.processed_count IS '일괄 service가 처리된 item 집계 후 동일 트랜잭션에서 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.unprocessed_count IS '일괄 service가 미처리 item 집계 후 동일 트랜잭션에서 갱신';
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_jobs_requester
    ON employment_rate_batch_jobs (requester_user_id, requested_at DESC, batch_job_id);

