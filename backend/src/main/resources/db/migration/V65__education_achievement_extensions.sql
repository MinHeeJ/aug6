-- 현재 최대 menu_id 이후 연속 번호를 배정하고 identity sequence도 함께 정렬한다.
WITH menu_base AS (
    SELECT COALESCE(MAX(m.menu_id), 0) AS maximum_id
    FROM menus m
), requested AS (
    SELECT s.*
    FROM (VALUES
        (1, '취업률 제고 실적 관리', 'SCR-EMPLOYMENT-RATE-IMPROVEMENT-ACHIEVEMENT',
            '/faculty/education/employment-rate-improvements'),
        (2, '강좌 개설·운영 실적 관리', 'SCR-COURSE-OFFERING-OPERATION-ACHIEVEMENT',
            '/faculty/education/course-operations'),
        (3, '강의개선 실적 관리', 'SCR-TEACHING-IMPROVEMENT-ACHIEVEMENT',
            '/faculty/education/lecture-improvements'),
        (4, '취업률 실적 관리', 'SCR-EMPLOYMENT-RATE-ACHIEVEMENT',
            '/faculty/education/employment-rate-achievements')
    ) AS s(sort_order, menu_name, screen_id, url)
), missing AS (
    SELECT r.*, ROW_NUMBER() OVER (ORDER BY r.sort_order) AS sequence_no
    FROM requested r
    WHERE NOT EXISTS (
        SELECT 1
        FROM menus m
        WHERE m.screen_id = r.screen_id OR m.url = r.url
    )
)
INSERT INTO menus (
    menu_id, menu_type, menu_name, display_order, screen_id, url, icon, business_category,
    description, system_use_yn, status, updated_by, change_reason
)
SELECT b.maximum_id + m.sequence_no, 'SCREEN', m.menu_name, 1100 + m.sort_order,
    m.screen_id, m.url, 'book-open', 'EDUCATION_ACHIEVEMENT', m.menu_name,
    'Y', 'ACTIVE', u.user_id, '교육영역 실적 화면 연결'
FROM missing m
CROSS JOIN menu_base b
CROSS JOIN users u
WHERE u.login_id = 'admin';
SELECT setval(
    pg_get_serial_sequence('menus', 'menu_id'),
    (SELECT MAX(m.menu_id) FROM menus m), true
);
