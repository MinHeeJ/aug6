CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(30) NOT NULL,
    management_no varchar(100) NOT NULL DEFAULT ('EDU-' || gen_random_uuid()::text),
    teacher_user_id bigint NOT NULL REFERENCES users(user_id),
    organization_code varchar(50) NOT NULL REFERENCES organizations(organization_code),
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    achievement_date date NOT NULL,
    achievement_name text NOT NULL DEFAULT '',
    achievement_detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    attachment_ref varchar(300),
    request_id varchar(100),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT uq_education_achievements_management_no UNIQUE (management_no),
    CONSTRAINT uq_education_achievements_id_type UNIQUE (achievement_id, achievement_type),
    CONSTRAINT ck_education_achievements_type CHECK (
        achievement_type IN (
            'EMPLOYMENT_RATE_IMPROVEMENT', 'COURSE_OPERATION',
            'LECTURE_IMPROVEMENT', 'EMPLOYMENT_RATE_ACHIEVEMENT'
        )
    ),
    CONSTRAINT ck_education_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_education_achievements_item CHECK (btrim(management_item_code) <> ''),
    CONSTRAINT ck_education_achievements_status CHECK (
        achievement_status IN (
            'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
            'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
        )
    ),
    CONSTRAINT ck_education_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT ck_education_achievements_delete_state CHECK (
        (deleted_yn = 'Y') = (achievement_status = 'DELETED')
    )
);
COMMENT ON TABLE education_achievements IS '교육영역 취업률 제고·강좌 운영·강의개선·취업률 실적 공통 원장. 기존 교육실적 원장과 독립적으로 상태와 논리삭제를 보존한다.';
COMMENT ON COLUMN education_achievements.achievement_type IS
    'EMPLOYMENT_RATE_IMPROVEMENT:취업률제고|COURSE_OPERATION:강좌운영|LECTURE_IMPROVEMENT:강의개선|EMPLOYMENT_RATE_ACHIEVEMENT:취업률';
COMMENT ON COLUMN education_achievements.achievement_status IS
    'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN education_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN education_achievements.management_item_code IS
    'evaluation_element_management_item_settings.management_item_code 참조 의도 (평가연도·범위별 복합 설정, FK 미선언)';
COMMENT ON COLUMN education_achievements.achievement_name IS '실적명. 저장 서비스가 JSON 대표 실적명과 함께 저장하며 Excel 중복키에 사용한다.';
