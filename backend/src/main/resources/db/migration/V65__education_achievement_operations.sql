COMMENT ON TABLE lecture_improvement_achievement_details IS '강의개선 실적의 내용, 학년도 및 학기 상세. 학년도는 원장 평가연도와 별개다.';

CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL CHECK (evaluation_year ~ '^[0-9]{4}$'),
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(target_condition_json) = 'object'),
    action_type varchar(20) NOT NULL CHECK (action_type IN ('GENERATE', 'DELETE')),
    job_status varchar(30) NOT NULL DEFAULT 'BLOCKED' CHECK (
        job_status IN ('BLOCKED', 'REQUESTED', 'RUNNING', 'COMPLETED', 'FAILED')
    ),
    total_count integer NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    processed_count integer NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    unprocessed_count integer NOT NULL DEFAULT 0 CHECK (unprocessed_count >= 0),
    requester_user_id bigint NOT NULL REFERENCES users(user_id),
    request_id varchar(100),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_employment_batch_counts CHECK (processed_count + unprocessed_count <= total_count)
);
COMMENT ON TABLE employment_rate_batch_jobs IS
    '취업률 일괄 작업 진단·결과 보존. 현재 실행 정책 미승인으로 생성·삭제 미실행이며 seed는 차단 진단 조회 전용이다.';
COMMENT ON COLUMN employment_rate_batch_jobs.request_id IS '처리 요청 추적 식별자 참조 의도 (FK 미선언)';
COMMENT ON COLUMN employment_rate_batch_jobs.processed_count IS
    'EmploymentRateBulkJobService가 작업 transaction 종료 시 갱신하는 처리 건수';
COMMENT ON COLUMN employment_rate_batch_jobs.unprocessed_count IS
    'EmploymentRateBulkJobService가 작업 transaction 종료 시 갱신하는 미처리 건수';
CREATE INDEX IF NOT EXISTS idx_employment_batch_jobs_owner
    ON employment_rate_batch_jobs (requester_user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS employment_rate_batch_job_items (
    batch_job_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_job_id varchar(100) NOT NULL REFERENCES employment_rate_batch_jobs(batch_job_id),
    target_user_id bigint NOT NULL REFERENCES users(user_id),
    achievement_id bigint REFERENCES education_achievements(achievement_id),
    processed_yn char(1) NOT NULL DEFAULT 'N' CHECK (processed_yn IN ('Y', 'N')),
    unprocessed_reason varchar(1000),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_employment_batch_job_target UNIQUE (batch_job_id, target_user_id),
    CONSTRAINT ck_employment_batch_item_reason CHECK (
        processed_yn = 'Y' OR NULLIF(btrim(unprocessed_reason), '') IS NOT NULL
    )
);
COMMENT ON TABLE employment_rate_batch_job_items IS
    '취업률 일괄 작업의 대상 snapshot 및 건별 결과. 현재 정책 미승인 seed는 미처리 진단만 보존한다.';
CREATE INDEX IF NOT EXISTS idx_employment_batch_items_target
    ON employment_rate_batch_job_items (target_user_id, batch_job_id);

