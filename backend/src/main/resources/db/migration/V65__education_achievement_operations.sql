  AND NOT EXISTS (
      SELECT 1
      FROM input_period_settings existing
      WHERE existing.evaluation_year = source.evaluation_year
        AND existing.area_code = source.area_code
        AND existing.organization_code = organization.organization_code
        AND existing.active_yn = 'Y'
  );

