INSERT INTO function_permissions (
    screen_id, role_code, function_type, permission_allowed, change_reason, created_by, updated_by
)
SELECT m.screen_id, r.role_code, f.function_type, 'ALLOW', '교육실적 기능 접근', 1, 1
FROM menus m
CROSS JOIN (VALUES ('R01'), ('R02'), ('R04'), ('R07'), ('R09')) AS r(role_code)
CROSS JOIN (VALUES ('READ'), ('CREATE'), ('UPDATE'), ('EXECUTE')) AS f(function_type)
WHERE m.screen_id IN (
    'SCR-EMPLOYMENT-RATE-IMPROVEMENT-ACHIEVEMENT',
    'SCR-COURSE-OFFERING-OPERATION-ACHIEVEMENT',
    'SCR-TEACHING-IMPROVEMENT-ACHIEVEMENT',
    'SCR-EMPLOYMENT-RATE-ACHIEVEMENT'
)
  AND (
      r.role_code = 'R09'
      OR (r.role_code = 'R01' AND f.function_type IN ('READ', 'CREATE', 'UPDATE'))
      OR (r.role_code IN ('R02', 'R04') AND f.function_type = 'READ')
      OR (r.role_code = 'R07' AND m.screen_id = 'SCR-EMPLOYMENT-RATE-ACHIEVEMENT'
          AND f.function_type IN ('READ', 'EXECUTE'))
  );
