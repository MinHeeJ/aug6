CREATE TABLE IF NOT EXISTS employment_rate_batch_jobs (
    batch_job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL CHECK (evaluation_year ~ '^[0-9]{4}$'),
    target_condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    action_type varchar(20) NOT NULL CHECK (action_type IN ('GENERATE', 'DELETE')),
    requester_user_id bigint NOT NULL REFERENCES users(user_id),
    job_status varchar(20) NOT NULL DEFAULT 'COMPLETED',
    total_count integer NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    processed_count integer NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    unprocessed_count integer NOT NULL DEFAULT 0 CHECK (unprocessed_count >= 0),
    request_id varchar(100),
    started_at timestamp,
    completed_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id),
    CONSTRAINT ck_employment_rate_batch_job_counts CHECK (total_count = processed_count + unprocessed_count),
    CONSTRAINT ck_employment_rate_batch_job_times CHECK (completed_at >= started_at),
    CONSTRAINT ck_employment_rate_batch_job_status CHECK (
        job_status IN ('WAITING', 'RUNNING', 'COMPLETED', 'FAILED')
    )
);
COMMENT ON TABLE employment_rate_batch_jobs IS '취업률 실적 일괄 작업의 요청자와 처리건수 결과를 보존한다. 현재 실행 정책 미승인으로 신규 실행은 거부하며 보존 결과만 조회한다.';
COMMENT ON COLUMN employment_rate_batch_jobs.action_type IS 'GENERATE:생성|DELETE:삭제';
COMMENT ON COLUMN employment_rate_batch_jobs.job_status IS 'WAITING:대기|RUNNING:실행중|COMPLETED:완료|FAILED:실패';
COMMENT ON COLUMN employment_rate_batch_jobs.total_count IS '일괄 서비스가 승인된 작업 완료 시 대상 결과에서 집계하여 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.processed_count IS '일괄 서비스가 승인된 작업 완료 시 processed_yn=Y 결과에서 집계하여 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.unprocessed_count IS '일괄 서비스가 승인된 작업 완료 시 processed_yn=N 결과에서 집계하여 갱신';
COMMENT ON COLUMN employment_rate_batch_jobs.request_id IS '작업 접수 서비스가 최초 요청의 추적 식별자로 기록';
CREATE INDEX IF NOT EXISTS idx_employment_rate_batch_jobs_requester
