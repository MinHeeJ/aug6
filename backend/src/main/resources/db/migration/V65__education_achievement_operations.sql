    SELECT m.menu_id
    FROM menus m
    JOIN menus main_menu
        ON main_menu.menu_id = m.parent_menu_id
    WHERE m.menu_name = '교육영역'
      AND main_menu.menu_name = '업적 입력 관리'
      AND m.status = 'ACTIVE'
