            '/faculty/teaching-improvement-achievements'),
        (4, '취업률 실적 관리', 'SCR-EMPLOYMENT-RATE-ACHIEVEMENT',
            '/faculty/employment-rate-achievements')
) AS seed(row_no, menu_name, screen_id, url)
