    menu_id, parent_menu_id, menu_type, menu_name, display_order, screen_id,
    url, icon, business_category, system_use_yn, status, change_reason
)
SELECT
    next_id.max_id + seed.row_no,
    parent.menu_id,
    'SCREEN',
    seed.menu_name,
    seed.row_no,
    seed.screen_id,
    seed.url,
    'graduation-cap',
