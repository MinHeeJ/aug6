    '2026',
    'COURSE_OPERATION',
    seed.occurred_date,
    seed.performance_details,
    seed.certification_status,
    owner.user_id,
    owner.user_id
FROM (
    VALUES
        ('B83-COA-001', 'professor1', DATE '2026-04-10', '정상 강좌 운영 실적', 'DRAFT'),
        ('B83-COA-002', 'professor2', DATE '2025-12-31', '평가기간 경계 강좌 운영 실적', 'SUBMITTED'),
        ('B83-COA-003', 'business-owner', DATE '2026-04-12', '인증 상태 강좌 개설 실적', 'CERTIFIED')
