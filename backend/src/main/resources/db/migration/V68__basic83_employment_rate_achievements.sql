-- BASIC-83 취업률 실적과 승인 대기 중인 일괄 작업 결과 저장 기반을 추가한다.

CREATE TABLE IF NOT EXISTS employment_rate_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(50) NOT NULL,
    target_user_id bigint NOT NULL,
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    occurred_date date NOT NULL,
    achievement_name varchar(300),
    attachment_ref varchar(300),
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_employment_rate_achievements_management_no UNIQUE (management_no),
    CONSTRAINT ck_employment_rate_achievements_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_employment_rate_achievements_status CHECK (
        certification_status IN (
            'DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED', 'DEPARTMENT_REJECTED',
            'CERTIFIED', 'CERTIFICATION_REJECTED', 'EVALUATION_CONFIRMED', 'DELETED'
        )
    ),
    CONSTRAINT ck_employment_rate_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_employment_rate_achievements_target_user
        FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_employment_rate_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_employment_rate_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

COMMENT ON TABLE employment_rate_achievements IS '교육영역 취업률 실적 원천. 개별 입력과 검증된 Excel 등록의 대상 교원별 실적을 보존한다.';
COMMENT ON COLUMN employment_rate_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN employment_rate_achievements.attachment_ref IS 'FileStoragePort의 외부 비노출 첨부 참조값';
COMMENT ON COLUMN employment_rate_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN employment_rate_achievements.target_user_id IS 'users.user_id 참조 의도 (실적 대상 교원)';
COMMENT ON COLUMN employment_rate_achievements.created_by IS 'users.user_id 참조 의도 (최초 입력자)';
COMMENT ON COLUMN employment_rate_achievements.updated_by IS 'users.user_id 참조 의도 (최종 수정자)';

CREATE INDEX IF NOT EXISTS idx_employment_rate_achievements_search
    ON employment_rate_achievements (
        target_user_id, evaluation_year, management_item_code, occurred_date DESC, certification_status
    )
    WHERE deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS employment_rate_bulk_jobs (
    job_id varchar(100) PRIMARY KEY,
    evaluation_year varchar(4) NOT NULL,
    action_type varchar(20) NOT NULL,
    target_condition jsonb,
    status varchar(30) NOT NULL,
    requested_by bigint NOT NULL,
    requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamp,
    CONSTRAINT ck_employment_rate_bulk_jobs_year CHECK (evaluation_year ~ '^[0-9]{4}$'),
    CONSTRAINT ck_employment_rate_bulk_jobs_action CHECK (action_type IN ('GENERATE', 'DELETE')),
    CONSTRAINT fk_employment_rate_bulk_jobs_requested_by
        FOREIGN KEY (requested_by) REFERENCES users(user_id)
);

COMMENT ON TABLE employment_rate_bulk_jobs IS '취업률 실적 일괄 작업 접수와 결과 집계. OQ-83-01 승인 전 실행 정책은 이 테이블에 기록하지 않는다.';
COMMENT ON COLUMN employment_rate_bulk_jobs.status IS 'PENDING:대기|RUNNING:처리중|COMPLETED:완료|FAILED:실패|REJECTED:정책미확정';
COMMENT ON COLUMN employment_rate_bulk_jobs.requested_by IS 'users.user_id 참조 의도 (R07 요청자)';

CREATE TABLE IF NOT EXISTS employment_rate_bulk_job_items (
    job_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id varchar(100) NOT NULL,
    target_user_id bigint,
    processing_status varchar(30) NOT NULL,
    result_message varchar(1000),
    processed_at timestamp,
    CONSTRAINT fk_employment_rate_bulk_job_items_job
        FOREIGN KEY (job_id) REFERENCES employment_rate_bulk_jobs(job_id),
    CONSTRAINT fk_employment_rate_bulk_job_items_target_user
        FOREIGN KEY (target_user_id) REFERENCES users(user_id)
);

COMMENT ON TABLE employment_rate_bulk_job_items IS '취업률 일괄 작업의 대상별 처리 또는 미처리 결과. 일괄 정책 승인 후에만 대상 항목을 생성한다.';
COMMENT ON COLUMN employment_rate_bulk_job_items.processing_status IS 'PENDING:대기|PROCESSED:처리됨|SKIPPED:미처리|FAILED:실패';
COMMENT ON COLUMN employment_rate_bulk_job_items.target_user_id IS 'users.user_id 참조 의도 (일괄 처리 대상 교원)';

CREATE INDEX IF NOT EXISTS idx_employment_rate_bulk_job_items_job
    ON employment_rate_bulk_job_items (job_id, processing_status);

