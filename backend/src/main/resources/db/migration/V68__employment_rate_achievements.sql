CREATE TABLE IF NOT EXISTS employment_rate_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_no varchar(100) NOT NULL UNIQUE,
    target_user_id bigint NOT NULL REFERENCES users(user_id),
    evaluation_year varchar(4) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    achievement_date date NOT NULL,
    achievement_name varchar(500),
    attachment_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
    certification_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    deleted_yn varchar(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users(user_id),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users(user_id)
);
COMMENT ON TABLE employment_rate_achievements IS '교원의 취업률 실적 원본을 논리 삭제와 감사 메타데이터로 보관한다.';
COMMENT ON COLUMN employment_rate_achievements.certification_status IS 'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|CONFIRMED:평가확정|DELETED:삭제';
CREATE INDEX IF NOT EXISTS idx_employment_rate_achievements_lookup ON employment_rate_achievements (target_user_id, achievement_date DESC);
CREATE TABLE IF NOT EXISTS employment_rate_upload_errors (
    error_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id varchar(100) NOT NULL REFERENCES excel_upload_files(upload_id),
    row_number integer NOT NULL,
    column_name varchar(100) NOT NULL,
    input_value varchar(1000),
    error_code varchar(100) NOT NULL,
    error_reason varchar(1000) NOT NULL
);
COMMENT ON TABLE employment_rate_upload_errors IS '취업률 실적 Excel 검증 실패 행의 진단 증적을 보관한다.';
CREATE TABLE IF NOT EXISTS employment_rate_bulk_jobs (
    job_id varchar(100) PRIMARY KEY,
    operator_user_id bigint NOT NULL REFERENCES users(user_id),
    evaluation_year varchar(4) NOT NULL,
    action_type varchar(20) NOT NULL,
    status varchar(20) NOT NULL,
    processed_count integer NOT NULL DEFAULT 0,
    unprocessed_count integer NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE employment_rate_bulk_jobs IS '승인된 취업률 실적 일괄 작업의 요청 및 처리 결과를 보관한다.';
COMMENT ON COLUMN employment_rate_bulk_jobs.status IS 'REQUESTED:요청|COMPLETED:완료|FAILED:실패|REJECTED:거부';
CREATE TABLE IF NOT EXISTS employment_rate_bulk_job_items (
    bulk_job_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id varchar(100) NOT NULL REFERENCES employment_rate_bulk_jobs(job_id),
    target_key varchar(200) NOT NULL,
    processing_status varchar(20) NOT NULL,
    reason varchar(1000)
);
COMMENT ON TABLE employment_rate_bulk_job_items IS '취업률 일괄 작업의 대상별 성공·미처리 결과를 보관한다.';
COMMENT ON COLUMN employment_rate_bulk_job_items.processing_status IS 'PROCESSED:처리|UNPROCESSED:미처리|FAILED:실패';
