CREATE TABLE IF NOT EXISTS file_policies (
    file_policy_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type varchar(100) NOT NULL,
    allowed_extensions varchar(1000) NOT NULL,
    max_file_size_mb integer NOT NULL,
    max_files_per_item integer NOT NULL,
    max_total_size_mb integer,
    max_filename_length integer NOT NULL,
    malware_scan_enabled varchar(1) NOT NULL DEFAULT 'Y',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_file_policies_business_type UNIQUE (business_type),
    CONSTRAINT ck_file_policies_size CHECK (max_file_size_mb > 0),
    CONSTRAINT ck_file_policies_count CHECK (max_files_per_item > 0),
    CONSTRAINT ck_file_policies_total_size CHECK (max_total_size_mb IS NULL OR max_total_size_mb > 0),
    CONSTRAINT ck_file_policies_filename_length CHECK (max_filename_length > 0),
    CONSTRAINT ck_file_policies_malware_scan CHECK (malware_scan_enabled IN ('Y','N')),
    CONSTRAINT fk_file_policies_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_file_policies_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE file_policies IS '업무구분별 허용 확장자, 용량, 첨부 개수, 파일명 길이, 악성파일 검사 적용 여부를 저장하는 중앙 파일정책.';
COMMENT ON COLUMN file_policies.business_type IS '기존 기준정보 업무구분 참조 의도 (FK 미선언)';
COMMENT ON COLUMN file_policies.malware_scan_enabled IS 'Y:적용|N:미적용';

CREATE TABLE IF NOT EXISTS attachment_files (
    file_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type varchar(100) NOT NULL,
    business_record_id varchar(200) NOT NULL,
    business_record_status varchar(30) NOT NULL DEFAULT 'IN_PROGRESS',
    original_filename varchar(255) NOT NULL,
    stored_filename varchar(255) NOT NULL,
    storage_path varchar(1000) NOT NULL,
    extension varchar(50) NOT NULL,
    file_size_bytes bigint NOT NULL,
    uploaded_by bigint NOT NULL,
    uploaded_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    malware_scan_status varchar(30) NOT NULL DEFAULT 'PENDING',
    deleted_at timestamp,
    deleted_by bigint,
    delete_reason varchar(500),
    CONSTRAINT ck_attachment_files_business_status CHECK (business_record_status IN ('IN_PROGRESS','EVALUATION_CONFIRMED','UNPUBLISHED','INACTIVE')),
    CONSTRAINT ck_attachment_files_size CHECK (file_size_bytes > 0),
    CONSTRAINT ck_attachment_files_scan_status CHECK (malware_scan_status IN ('CLEAN','INFECTED','FAILED','TIMEOUT','PENDING')),
    CONSTRAINT ck_attachment_files_delete_complete CHECK ((deleted_at IS NULL AND deleted_by IS NULL AND delete_reason IS NULL) OR (deleted_at IS NOT NULL AND deleted_by IS NOT NULL AND delete_reason IS NOT NULL)),
    CONSTRAINT fk_attachment_files_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES users(user_id),
    CONSTRAINT fk_attachment_files_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id)
);
COMMENT ON TABLE attachment_files IS '업무자료에 연결된 첨부파일의 표시용 원본명, 내부 저장정보, 검사 상태, 논리삭제 상태를 보존하는 메타정보.';
COMMENT ON COLUMN attachment_files.business_type IS '기존 기준정보 업무구분 참조 의도 (FK 미선언)';
COMMENT ON COLUMN attachment_files.business_record_id IS '기존 업무자료 식별자 참조 의도 (FK 미선언)';
COMMENT ON COLUMN attachment_files.business_record_status IS 'IN_PROGRESS:진행중|EVALUATION_CONFIRMED:평가확정|UNPUBLISHED:미공개|INACTIVE:비활성';
COMMENT ON COLUMN attachment_files.malware_scan_status IS 'CLEAN:정상|INFECTED:감염|FAILED:검사실패|TIMEOUT:시간초과|PENDING:검사대기';
COMMENT ON COLUMN attachment_files.deleted_at IS 'AttachmentService.logicalDelete 시 애플리케이션에서 갱신';
COMMENT ON COLUMN attachment_files.deleted_by IS 'users.user_id 참조 의도 (논리삭제 처리자)';
COMMENT ON COLUMN attachment_files.delete_reason IS 'AttachmentService.logicalDelete 시 attachment_delete_history.reason과 함께 기록';
COMMENT ON COLUMN attachment_files.stored_filename IS '내부 저장 파일명으로 API/UI 응답에 노출하지 않는다.';
COMMENT ON COLUMN attachment_files.storage_path IS '내부 저장 경로로 API/UI 응답에 노출하지 않는다.';

CREATE TABLE IF NOT EXISTS attachment_delete_history (
    delete_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id bigint NOT NULL,
    delete_method varchar(30) NOT NULL DEFAULT 'LOGICAL',
    reason varchar(500) NOT NULL,
    deleted_by bigint NOT NULL,
    deleted_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_attachment_delete_method CHECK (delete_method IN ('LOGICAL')),
    CONSTRAINT fk_attachment_delete_history_file FOREIGN KEY (file_id) REFERENCES attachment_files(file_id),
    CONSTRAINT fk_attachment_delete_history_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(user_id)
);
COMMENT ON TABLE attachment_delete_history IS '개발·검증 환경의 첨부파일 논리삭제 사유, 삭제자, 삭제일시를 보존하는 수정·삭제 없는 감사 이력.';
COMMENT ON COLUMN attachment_delete_history.delete_method IS 'LOGICAL:논리삭제';

CREATE TABLE IF NOT EXISTS attachment_integrity_checks (
    check_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status varchar(30) NOT NULL DEFAULT 'RUNNING',
    started_by bigint NOT NULL,
    started_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamp,
    CONSTRAINT ck_attachment_integrity_check_status CHECK (status IN ('RUNNING','COMPLETED','FAILED')),
    CONSTRAINT fk_attachment_integrity_checks_started_by FOREIGN KEY (started_by) REFERENCES users(user_id)
);
COMMENT ON TABLE attachment_integrity_checks IS 'DB 첨부 메타정보와 파일 저장소 객체 비교를 수행한 정합성 점검 실행 단위와 진행 상태를 보존한다.';
COMMENT ON COLUMN attachment_integrity_checks.status IS 'RUNNING:실행중|COMPLETED:완료|FAILED:실패';

CREATE TABLE IF NOT EXISTS attachment_integrity_findings (
    finding_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id bigint NOT NULL,
    file_id bigint,
    storage_object_ref varchar(1000),
    anomaly_type varchar(50) NOT NULL,
    result_message varchar(1000) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_attachment_integrity_anomaly CHECK (anomaly_type IN ('MISSING_BUSINESS_REF','MISSING_STORAGE_FILE','DUPLICATE_FILE')),
    CONSTRAINT fk_attachment_integrity_finding_check FOREIGN KEY (check_id) REFERENCES attachment_integrity_checks(check_id),
    CONSTRAINT fk_attachment_integrity_finding_file FOREIGN KEY (file_id) REFERENCES attachment_files(file_id)
);
COMMENT ON TABLE attachment_integrity_findings IS '정합성 점검에서 발견한 연결자료 없음, 실제파일 없음, 중복파일 이상 결과를 점검별로 보존한다.';
COMMENT ON COLUMN attachment_integrity_findings.storage_object_ref IS '실제 저장소 파일 객체 참조 의도 (외부 저장소 경로 또는 key, FK 미선언)';
COMMENT ON COLUMN attachment_integrity_findings.anomaly_type IS 'MISSING_BUSINESS_REF:연결자료없음|MISSING_STORAGE_FILE:실제파일없음|DUPLICATE_FILE:중복파일';

CREATE TABLE IF NOT EXISTS malware_scan_results (
    malware_scan_result_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id bigint NOT NULL,
    scan_status varchar(30) NOT NULL,
    blocked_reason varchar(500),
    scanned_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_malware_scan_status CHECK (scan_status IN ('CLEAN','INFECTED','FAILED','TIMEOUT')),
    CONSTRAINT ck_malware_scan_block_reason CHECK ((scan_status = 'CLEAN' AND blocked_reason IS NULL) OR (scan_status <> 'CLEAN' AND blocked_reason IS NOT NULL)),
    CONSTRAINT fk_malware_scan_results_file FOREIGN KEY (file_id) REFERENCES attachment_files(file_id)
);
COMMENT ON TABLE malware_scan_results IS 'MalwareScanPort 또는 ClamAV 어댑터가 반환한 검사 상태와 fail-closed 차단 사유를 첨부파일별로 보존한다.';
COMMENT ON COLUMN malware_scan_results.scan_status IS 'CLEAN:정상|INFECTED:감염|FAILED:검사실패|TIMEOUT:시간초과';
COMMENT ON COLUMN malware_scan_results.blocked_reason IS 'MalwareScanService.finalizeScanResult 시 차단 상태(INFECTED/FAILED/TIMEOUT)에 대해 기록';

CREATE INDEX IF NOT EXISTS idx_file_policies_business_type ON file_policies(business_type);
CREATE INDEX IF NOT EXISTS idx_attachment_files_business_record ON attachment_files(business_type, business_record_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_attachment_files_storage_duplicate ON attachment_files(storage_path, stored_filename);
CREATE INDEX IF NOT EXISTS idx_attachment_delete_history_file ON attachment_delete_history(file_id, deleted_at DESC);
CREATE INDEX IF NOT EXISTS idx_attachment_integrity_checks_status ON attachment_integrity_checks(status, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_attachment_integrity_findings_check ON attachment_integrity_findings(check_id, anomaly_type);
CREATE INDEX IF NOT EXISTS idx_malware_scan_results_file ON malware_scan_results(file_id, scanned_at DESC);

