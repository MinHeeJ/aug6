CREATE TABLE IF NOT EXISTS privacy_field_policies (
    policy_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_key varchar(120) NOT NULL,
    privacy_grade varchar(30) NOT NULL,
    encryption_required_yn varchar(1) NOT NULL,
    masking_rule varchar(120),
    log_exclusion_yn varchar(1) NOT NULL,
    change_reason varchar(500),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_privacy_field_policies_field_key UNIQUE (field_key),
    CONSTRAINT ck_privacy_field_policies_grade CHECK (privacy_grade IN ('PUBLIC','PERSONAL','SENSITIVE','ACCOUNT')),
    CONSTRAINT ck_privacy_field_policies_encrypt CHECK (encryption_required_yn IN ('Y','N')),
    CONSTRAINT ck_privacy_field_policies_log_exclusion CHECK (log_exclusion_yn IN ('Y','N')),
    CONSTRAINT fk_privacy_field_policies_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_privacy_field_policies_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);
COMMENT ON TABLE privacy_field_policies IS '개인정보 업무 필드별 등급, 암호화 여부, 마스킹 규칙, 일반 로그 제외 정책을 저장한다. 실제 개인정보 원문값은 저장하지 않는다.';
COMMENT ON COLUMN privacy_field_policies.privacy_grade IS 'PUBLIC:공개|PERSONAL:개인정보|SENSITIVE:민감정보|ACCOUNT:계좌정보';
COMMENT ON COLUMN privacy_field_policies.encryption_required_yn IS 'Y:암호화필수|N:암호화미필수';
COMMENT ON COLUMN privacy_field_policies.masking_rule IS '일반 조회 시 적용할 마스킹 규칙 식별자. PrivacyFieldPolicyService.savePrivacyFieldPolicies 시 애플리케이션에서 갱신';
COMMENT ON COLUMN privacy_field_policies.log_exclusion_yn IS 'Y:일반로그제외|N:일반로그허용';
COMMENT ON COLUMN privacy_field_policies.created_by IS 'users.user_id 참조 의도 (정책 생성 처리자)';
COMMENT ON COLUMN privacy_field_policies.updated_by IS 'users.user_id 참조 의도 (정책 변경 처리자)';

CREATE INDEX IF NOT EXISTS idx_privacy_field_policies_grade ON privacy_field_policies(privacy_grade, field_key);
CREATE INDEX IF NOT EXISTS idx_privacy_field_policies_encryption ON privacy_field_policies(encryption_required_yn, field_key);

