CREATE TABLE IF NOT EXISTS teaching_improvement_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id bigint NOT NULL,
    management_no varchar(100) NOT NULL,
    management_item_code varchar(50) NOT NULL,
    achievement_date date NOT NULL,
    achievement_content text NOT NULL,
    academic_year integer NOT NULL,
    semester integer NOT NULL,
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_refs text NOT NULL DEFAULT '[]',
    deleted_yn varchar(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT uq_teaching_improvement_achievements_management_no UNIQUE (management_no),
    CONSTRAINT chk_teaching_improvement_achievements_year CHECK (academic_year >= 2000),
    CONSTRAINT chk_teaching_improvement_achievements_semester CHECK (semester IN (1, 2)),
    CONSTRAINT chk_teaching_improvement_achievements_status CHECK (
        achievement_status IN (
            'DRAFT',
            'SUBMITTED',
            'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED',
            'CERTIFIED',
            'CERTIFICATION_REJECTED',
            'EVALUATION_CONFIRMED',
            'DELETED'
        )
    ),
    CONSTRAINT chk_teaching_improvement_achievements_deleted_yn CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_teaching_improvement_achievements_target_user
        FOREIGN KEY (target_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_teaching_improvement_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_teaching_improvement_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

COMMENT ON TABLE teaching_improvement_achievements IS
    '강의개선 실적의 학년도·학기·내용과 상태를 보관하는 교육영역 업무 원장이다.';
COMMENT ON COLUMN teaching_improvement_achievements.achievement_status IS
    'DRAFT:작성중|SUBMITTED:제출|DEPARTMENT_CONFIRMED:학과장확인|DEPARTMENT_REJECTED:학과장미승인|CERTIFIED:인증|CERTIFICATION_REJECTED:인증반려|EVALUATION_CONFIRMED:평가확정|DELETED:삭제';
COMMENT ON COLUMN teaching_improvement_achievements.deleted_yn IS 'Y:삭제|N:정상';
COMMENT ON COLUMN teaching_improvement_achievements.attachment_refs IS
    '첨부 참조 JSON 배열이며 LectureImprovementService.create/update 시 애플리케이션에서 갱신';

CREATE INDEX IF NOT EXISTS idx_teaching_improvement_achievements_owner_date
    ON teaching_improvement_achievements (target_user_id, achievement_date DESC, achievement_id DESC)
    WHERE deleted_yn = 'N';
