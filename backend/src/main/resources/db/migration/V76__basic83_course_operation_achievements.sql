-- BASIC-83 강좌 개설·운영 실적의 공통 원천 및 상세 테이블을 추가한다.
-- CourseOperationMapper의 조회/저장 계약은 이 원천과 1:1 상세 레코드를 함께 사용한다.

CREATE TABLE IF NOT EXISTS education_achievements (
    achievement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_type varchar(50) NOT NULL,
    teacher_user_id bigint NOT NULL,
    management_item_code varchar(50) NOT NULL,
    achievement_date date NOT NULL,
    achievement_status varchar(30) NOT NULL DEFAULT 'DRAFT',
    attachment_ids varchar(500)[],
    deleted_yn char(1) NOT NULL DEFAULT 'N',
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint,
    CONSTRAINT ck_education_achievements_type CHECK (
        achievement_type IN ('COURSE_OPERATION')
    ),
    CONSTRAINT ck_education_achievements_status CHECK (
        achievement_status IN ('DRAFT', 'SUBMITTED', 'DEPARTMENT_CONFIRMED',
            'DEPARTMENT_REJECTED', 'CERTIFIED', 'CERTIFICATION_REJECTED',
            'EVALUATION_CONFIRMED', 'DELETED')
    ),
    CONSTRAINT ck_education_achievements_deleted CHECK (deleted_yn IN ('Y', 'N')),
    CONSTRAINT fk_education_achievements_teacher
        FOREIGN KEY (teacher_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_created_by
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_education_achievements_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

COMMENT ON TABLE education_achievements IS
    '강좌 개설·운영 실적의 대상 교원, 관리항목, 발생일, 상태 및 첨부 참조를 보관한다.';
COMMENT ON COLUMN education_achievements.attachment_ids IS
    '외부 파일 저장소의 비노출 첨부 참조 배열';
COMMENT ON COLUMN education_achievements.deleted_yn IS 'Y:삭제|N:정상';

CREATE INDEX IF NOT EXISTS idx_education_achievements_course_operation_search
    ON education_achievements (
        teacher_user_id,
        achievement_date DESC,
        achievement_id DESC
    )
    WHERE achievement_type = 'COURSE_OPERATION'
      AND deleted_yn = 'N';

CREATE TABLE IF NOT EXISTS course_operation_achievement_details (
    achievement_id bigint PRIMARY KEY,
    performance_detail text NOT NULL,
    CONSTRAINT fk_course_operation_achievement_details_achievement
        FOREIGN KEY (achievement_id) REFERENCES education_achievements(achievement_id)
            ON DELETE CASCADE
);

COMMENT ON TABLE course_operation_achievement_details IS
    '강좌 개설·운영 실적 원천과 1:1로 연결되는 실적 상세 내용';
COMMENT ON COLUMN course_operation_achievement_details.performance_detail IS
    '강좌 개설 또는 운영의 구체적 실적 내용';
