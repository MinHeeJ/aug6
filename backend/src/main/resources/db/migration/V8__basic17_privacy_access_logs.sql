CREATE TABLE IF NOT EXISTS privacy_access_logs (
    history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_type varchar(20) NOT NULL,
    actor_user_id bigint NOT NULL,
    target_ref varchar(120) NOT NULL,
    process_purpose varchar(300) NOT NULL,
    processed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_ip varchar(64) NOT NULL,
    process_result varchar(30) NOT NULL,
    CONSTRAINT ck_privacy_access_logs_process_type CHECK (process_type IN ('VIEW','PRINT','DOWNLOAD')),
    CONSTRAINT ck_privacy_access_logs_process_result CHECK (process_result IN ('SUCCESS','DENIED','FAILED')),
    CONSTRAINT fk_privacy_access_logs_actor_user FOREIGN KEY (actor_user_id) REFERENCES users(user_id)
);
COMMENT ON TABLE privacy_access_logs IS '개인정보 조회·출력·다운로드 처리 목적, 처리자, 대상 참조, 일시, IP, 결과를 보존하는 읽기 전용 감사 이력이다. 원문 개인정보 값은 저장하지 않는다.';
COMMENT ON COLUMN privacy_access_logs.process_type IS 'VIEW:조회|PRINT:출력|DOWNLOAD:다운로드';
COMMENT ON COLUMN privacy_access_logs.actor_user_id IS 'users.user_id 참조 의도 (개인정보 처리자)';
COMMENT ON COLUMN privacy_access_logs.target_ref IS '개인정보 원문이 아닌 업무 대상 참조 식별자. PrivacyAccessLogService.recordPrivacyAccessLog 시 애플리케이션에서 기록';
COMMENT ON COLUMN privacy_access_logs.process_purpose IS '처리 전 확인한 개인정보 처리 목적. PrivacyAccessLogService.recordPrivacyAccessLog 시 애플리케이션에서 기록';
COMMENT ON COLUMN privacy_access_logs.processed_at IS 'PrivacyAccessLogService.recordPrivacyAccessLog 시 데이터베이스 CURRENT_TIMESTAMP로 생성';
COMMENT ON COLUMN privacy_access_logs.request_ip IS '개인정보 처리 요청 IP. PrivacyAccessLogController.recordPrivacyAccessLog 시 헤더 또는 요청 원격주소에서 기록';
COMMENT ON COLUMN privacy_access_logs.process_result IS 'SUCCESS:성공|DENIED:차단|FAILED:실패';

CREATE INDEX IF NOT EXISTS idx_privacy_access_logs_actor_time ON privacy_access_logs(actor_user_id, processed_at DESC);
CREATE INDEX IF NOT EXISTS idx_privacy_access_logs_target_time ON privacy_access_logs(target_ref, processed_at DESC);
CREATE INDEX IF NOT EXISTS idx_privacy_access_logs_type_time ON privacy_access_logs(process_type, processed_at DESC);

